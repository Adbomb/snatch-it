def text_block(m, jt, TXT=TXT):
    """Текстовая колонка строки: признаки, проблемы, правки, автопроверка. Высота — по содержимому."""
    item, num, name, sil, traits, probs, fixes, rate = m
    im = Image.new("RGB", (TXT, 1200), "white")
    d = ImageDraw.Draw(im)
    f, fb = font(17), font(17, True)
    ty = 0
    d.text((0, ty), "Признаки вида:", font=fb, fill=(30, 30, 40))
    tx = d.textlength("Признаки вида: ", font=fb)
    for t, mk in traits:
        word, col = MARK[mk]
        s = f"{t} — {word};"
        if tx + d.textlength(s, font=f) > TXT:
            ty += 22
            tx = 0
        d.text((tx, ty), s, font=f, fill=col)
        tx += d.textlength(s + " ", font=f)
    ty += 30
    for title, items, col in (("Проблемы:", probs, (170, 40, 40)), ("Как исправить:", fixes, (30, 100, 60))):
        d.text((0, ty), title, font=fb, fill=col)
        ty += 22
        for it in items:
            for k, ln in enumerate(wrap(d, it, f, TXT - 24)):
                d.text((4, ty), ("• " if k == 0 else "   ") + ln, font=f, fill=(35, 35, 45))
                ty += 21
        ty += 6
    for ln in wrap(d, jt, font(15), TXT):
        d.text((0, ty), ln, font=font(15), fill=(90, 90, 110))
        ty += 19
    return im.crop((0, 0, TXT, ty + 6))


