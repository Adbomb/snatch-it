# ---------------------------------------------------------------- силуэты настоящих зверей (сбоку, морда вправо)
def _sil(d, kind, box):
    x0, y0, w, h = box
    k = min(w, h) / 100.0
    ox, oy = x0 + (w - 100 * k) / 2, y0 + (h - 100 * k) / 2
    ink, eye = (35, 40, 50), (255, 255, 255)

    def P(*pts, c=ink):
        d.polygon([(ox + x * k, oy + y * k) for x, y in pts], fill=c)

    def E(x, y, rx, ry, c=ink):
        d.ellipse([ox + (x - rx) * k, oy + (y - ry) * k, ox + (x + rx) * k, oy + (y + ry) * k], fill=c)

    def L(pts, wd, c=ink):
        q = [(ox + x * k, oy + y * k) for x, y in pts]
        d.line(q, fill=c, width=max(1, int(wd * k)), joint="curve")
        for x, y in q:
            d.ellipse([x - wd * k / 2, y - wd * k / 2, x + wd * k / 2, y + wd * k / 2], fill=c)

    if kind == "penguin":
        E(50, 58, 19, 28); E(53, 26, 12, 11); P((63, 23), (75, 27), (63, 30))
        P((42, 45), (34, 72), (40, 74), (50, 50)); P((44, 84), (66, 84), (66, 90), (44, 90)); E(57, 24, 2, 2, eye)
    elif kind == "giraffe":
        E(42, 55, 22, 11)
        for x in (26, 32, 52, 58):
            L([(x, 58), (x, 92)], 3)
        L([(58, 50), (76, 12)], 7); E(80, 11, 8, 4.5); L([(77, 8), (76, 2)], 2); L([(81, 8), (81, 2)], 2)
        L([(20, 52), (14, 64)], 2)
    elif kind == "fox":
        E(40, 70, 18, 17); E(56, 56, 11, 19); P((52, 60), (60, 60), (61, 92), (53, 92)); E(61, 34, 10, 9)
        P((67, 31), (82, 36), (67, 40)); P((55, 28), (57, 14), (62, 26)); P((61, 26), (65, 13), (68, 28))
        E(25, 86, 20, 6); E(64, 32, 1.6, 1.6, eye)
    elif kind == "walrus":
        E(44, 66, 32, 20); E(73, 50, 13, 13); E(80, 58, 9, 6)
        L([(79, 62), (80, 84)], 3, (230, 230, 230)); P((14, 74), (2, 90), (22, 88)); P((58, 78), (56, 92), (72, 92))
