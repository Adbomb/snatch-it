SKIP_YETI = ("Ex",)  # экспонаты вморожены в лёд по замыслу (D64) — не суставы


def joint_text(item, issues, scale=1.0):
    if item == "Yeti":
        issues = [i for i in issues if not i["part"].startswith(SKIP_YETI)]
    issues = [i for i in issues if i["kind"] != "точка вращения вне частей" and i["part"] != "Stand"
              and not (i["kind"] == "сустав раскрывается" and i.get("parent") == "Stand")]
    if not issues:
        return "автопроверка: щелей, летающих деталей и раскрытых сгибов нет"
    parts = []
    for i in issues:
        g = i.get("gap")
        if i["kind"] == "щель в суставе" and i["parent"] == "Stand":
            parts.append(f"{i['part']} не касается ног и подставки ({g * scale:.2f} ст.)")
        elif i["kind"] == "щель в суставе":
            parts.append(f"щель {i['part']}↔{i['parent']} {g * scale:.2f} ст.")
        elif i["kind"] == "летающая деталь":
            parts.append(f"летает кусок {i['part']} ({g * scale:.2f} ст.)")
        elif i["kind"] == "сустав раскрывается":
            parts.append(f"сгиб {i['part']}↔{i['parent']} раскрыт {int(i['share'] * 100)} %")
        elif i["kind"] == "точка вращения вне частей":
            parts.append(f"ось {i['part']} вне частей")
        else:
            parts.append(f"ось {i['part']} далеко от сустава ({i.get('dist', 0) * scale:.2f} ст.)")
    seen, uniq = set(), []
    for p in parts:
        if p not in seen:
            seen.add(p)
            uniq.append(p)
    more = f" … ещё {len(uniq) - 6}" if len(uniq) > 6 else ""
    return "автопроверка: " + "; ".join(uniq[:6]) + more


