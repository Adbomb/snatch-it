def crop(im):
    im = im.convert("RGB")
    bg = im.getpixel((2, 2))
    m = ImageChops.difference(im, Image.new("RGB", im.size, bg)).convert("L").point(lambda v: 255 if v > 18 else 0)
    bb = m.getbbox() or (0, 0, *im.size)
    pad = 16
    return im.crop((max(0, bb[0] - pad), max(0, bb[1] - pad), min(im.width, bb[2] + pad), min(im.height, bb[3] + pad)))


def fit(im, w, h):
    im = im.copy()
    im.thumbnail((w, h))
    c = Image.new("RGB", (w, h), (232, 236, 242))
    c.paste(im, ((w - im.width) // 2, (h - im.height) // 2))
    return c


