def reports(folder):
    out = {}
    for f in os.listdir(folder) if os.path.isdir(folder) else []:
        if f.startswith("report_") and f.endswith(".json"):
            for k, r in json.load(open(os.path.join(folder, f), encoding="utf-8")).items():
                out[k] = r
    return out


