def text_rows(word):
    """Слово пиксельным шрифтом FONT6 (6 строк, буквы через пустой столбец)."""
    rows = [""] * 6
    for i, ch in enumerate(word):
        for r in range(6):
            rows[r] += ("." if i else "") + FONT6[ch][r]
    return rows


