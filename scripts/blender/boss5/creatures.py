COMMON = {"dark": ("1B1B2A", False), "white": ("FFFFFF", False), "pink": ("FF7F9F", False),
          "blush": ("FFA3B5", False), "gold": ("F5B21C", True), "ivory": ("F3E9D2", False)}


def R(axis, deg, c=(0, 0, 0)):
    return C.tilt(c, axis, deg)


def T(v):
    return Matrix.Translation(V(v))


def key(k):
    K.KEY = k


def new(name, pal, rings=()):
    a = S.Art(name, ring_z0=1.0)
    a.ring = dict(S.RING, core=0.55)
    for k, (code, r) in {**COMMON, **pal}.items():
        a.paint(k, code, rings=r or k in rings)
    return a


def eye(a, x, y, z, r, hi=True, iris=None):
    """Глаз на лицевой плоскости y (смотрит в −y): тёмный восьмигранник, радужка, блик."""
    if iris:
        a.prism(iris, S.octagon(x - r * 1.45, x + r * 1.45, z - r * 1.45, z + r * 1.45, r * 0.5), y - 0.02, y + 0.06,
                axis="y")
    a.prism("dark", S.octagon(x - r, x + r, z - r, z + r, r * 0.4), y - 0.05, y + 0.05, axis="y")
    if hi:
        a.prism("white", S.octagon(x + r * 0.1, x + r * 0.55, z + r * 0.1, z + r * 0.55, r * 0.12), y - 0.08, y - 0.03,
                axis="y")


def disc_y(a, k, x, y, z, r, t=0.06):
    a.prism(k, S.octagon(x - r, x + r, z - r, z + r, r * 0.4), y - t, y + t, axis="y")


