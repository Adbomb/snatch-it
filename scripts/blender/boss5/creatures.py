def hedgehog(a):
    """Ёжик-сосулька: колючки — ледяные сосульки, носик-кнопка, розовые щёчки."""
    C.blob(a, "hedge", (0, 0.1, 0.85), 0.95, 1.1, 0.8, n=6)
    C.blob(a, "cream", (0, -0.78, 0.72), 0.58, 0.42, 0.5, n=4)
    K.KEY = "cream"
    K.taper(a, (0, -1.0, 0.7), (0, -1.5, 0.62), 0.36, 0.12, 0.3, 0.12, up=(0, 0, 1))
    C.blob(a, "dark", (0, -1.55, 0.63), 0.1, 0.08, 0.08, n=2)
    for s in S2:
        eye(a, s * 0.24, -1.12, 0.92, 0.09)
        disc_y(a, "blush", s * 0.42, -1.05, 0.62, 0.09, t=0.03)
        C.blob(a, "cream", (s * 0.45, -0.6, 0.1), 0.18, 0.24, 0.1, n=2)
    n = 0
    for el in (20, 45, 70, 90):
        for az in range(-150, 151, 30 if el < 80 else 60):
            t, p = math.radians(az), math.radians(el)
            d = V((math.sin(t) * math.cos(p), math.cos(t) * math.cos(p) * 1.15 + 0.15, math.sin(p) * 0.85)).normalized()
            if d.y < -0.45 and el < 60:
                continue
            base = V((0, 0.1, 0.85)) + V((d.x * 0.85, d.y * 0.98, d.z * 0.72))
            key(("iceS", "iceL", "neonIce")[n % 3] if n % 5 else "iceL")
            K.spike(a, base, base + d * (0.7 + 0.15 * (n % 3)) + V((0, 0.2, 0)), 0.3)
