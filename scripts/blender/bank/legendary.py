def sapphire_tiger():
    """2. Тигр-сапфир: белый тигр, у которого полосы синие, как сапфиры, и светятся (Neon); ступает важно, задрав хвост.
    Признаки: мощные плечи и крупные лапы, круглые уши с белым пятном, белые бакенбарды, длинный полосатый хвост,
    розовый нос. v3 (владелец 2026-11-26, «спереди ящик на столбиках»): голова крупнее и круглее по-кошачьи — широкие
    щёки с белыми бакенбардами, морда вперёд; тело сужается к пояснице, хвост толще; не слабее грифона и гиппокампа."""
    a = new("SapphireTiger", {"tig": ("E6EEFB", True), "tigL": ("C8DCF6", False), "tigB": ("CFE0F7", True), "tigD": ("2A2D3A", False), "neonS": ("2E6BFF", False), "nose": ("FF8FB2", False)})
    glow(a, 1.8)
    t = legendary_stand(a, 1.7)
    part(a, "Body", "Stand", (0, 0.1, t + 0.95))
    A.body(a, "tigB", (0, -0.4, t + 0.45), 0.44, 0.4, 0.82, "egg", n=2)  # мощная грудь — светло-голубая
    a.prism("tigB", S.octagon(-0.3, 0.3, -0.3, 0.5, 0.1), t + 0.7, t + 0.76, bevel=0)  # светло-голубой живот
    kchain(a, "tig", [(0, -0.4, t + 1.02), (0, 0.05, t + 0.98), (0, 0.38, t + 0.94), (0, 0.66, t + 0.98)],
           [0.84, 0.66, 0.5, 0.6], [0.72, 0.6, 0.48, 0.56], up=(0, 0, 1), overlap=0.5)  # сужается к пояснице
    for s in S2:
        A.ball(a, "tig", (s * 0.34, -0.42, t + 0.98), 0.27, n=2)  # плечи
        A.body(a, "tig", (s * 0.29, 0.6, t + 0.52), 0.19, 0.3, 0.56, "egg", n=2)  # бедро
        A.limb(a, "tig", [(s * 0.29, 0.66, t + 0.74), (s * 0.3, 0.84, t + 0.36), (s * 0.29, 0.7, t + 0.12)],
               [0.24, 0.2, 0.18])
        taper(a, "tig", (s * 0.29, 0.76, t + 0.08), (s * 0.29, 0.46, t + 0.08), 0.28, 0.26, 0.16, 0.14)  # лапа
        a.box("neonS", s * 0.29 - 0.13, s * 0.29 + 0.13, 0.7, 0.92, t + 0.4, t + 0.45, bevel=0,
              matrix=tilt((s * 0.29, 0.8, t + 0.4), "X", 30))  # светящаяся полоса на задней лапе
    for k in range(3):  # светящиеся сапфировые полосы по спине и бокам
        y = -0.3 + 0.42 * k
        for s in S2:
            kchain(a, "neonS", [(s * 0.04, y, t + 1.37 - 0.04 * k), (s * 0.36, y + 0.1, t + 1.08),
                                (s * 0.38, y + 0.16, t + 0.74)], [0.08, 0.07, 0.06], [0.05, 0.05, 0.05],
                   up=(s * 0.5, 0, 1), overlap=0.2)  # полосы от хребта вниз по боку
    part(a, "ArmR", "Body", (-0.28, -0.45, t + 0.86))  # левая передняя (−x) — опора, лапа под грудью
    A.ball(a, "tig", (-0.28, -0.45, t + 0.86), 0.2, n=2)
    A.limb(a, "tig", [(-0.28, -0.45, t + 0.86), (-0.25, -0.52, t + 0.46), (-0.22, -0.56, t + 0.16)], [0.3, 0.26, 0.24],
           joints=False)
    for zz in (0.32, 0.56):  # светящиеся полосы на лапе
        a.box("neonS", -0.39, -0.08, -0.7, -0.66, t + zz, t + zz + 0.05, bevel=0)
    taper(a, "tig", (-0.22, -0.46, t + 0.08), (-0.22, -0.82, t + 0.08), 0.32, 0.3, 0.17, 0.15)  # крупная лапа
    part(a, "ArmL", "Body", (0.28, -0.45, t + 0.86))  # правая передняя (+x) поднята — шаг
    A.ball(a, "tig", (0.28, -0.45, t + 0.86), 0.2, n=2)
    A.limb(a, "tig", [(0.28, -0.45, t + 0.86), (0.28, -0.72, t + 0.6), (0.27, -0.82, t + 0.36)], [0.3, 0.26, 0.24],
           joints=False)
    a.box("neonS", 0.12, 0.44, -0.68, -0.62, t + 0.7, t + 0.75, bevel=0)  # полоса на поднятой лапе
    taper(a, "tig", (0.27, -0.78, t + 0.34), (0.27, -1.04, t + 0.3), 0.32, 0.3, 0.17, 0.15)  # поднятая лапа
    part(a, "Tail", "Body", (0, 0.82, t + 1.05))
    A.ball(a, "tig", (0, 0.82, t + 1.05), 0.16, n=2)
    tp = [(0, 0.82, t + 1.05), (0, 1.12, t + 1.12), (0, 1.3, t + 1.42), (0, 1.25, t + 1.78), (0, 1.02, t + 1.98)]
    for i in range(len(tp) - 1):  # хвост толще, дугой, с сапфировыми кольцами
        kchain(a, "tig" if i % 2 == 0 else "neonS", [tp[i], tp[i + 1]], [0.21 - 0.015 * i, 0.19 - 0.015 * i],
               up=(1, 0, 0))
    part(a, "Head", "Body", (0, -0.72, t + 1.25))
    hc = V((0, -0.92, t + 1.42))
    th = A.body(a, "tig", (hc.x, hc.y, hc.z - 0.36), 0.5, 0.42, 0.74, "ball", n=3)  # круглая кошачья голова
    for s in S2:  # широкие щёки с белыми бакенбардами
        A.ball(a, "tigL", (s * 0.36, hc.y - 0.12, hc.z - 0.16), 0.2, n=2)
        spike(a, "tigL", (s * 0.42, hc.y - 0.1, hc.z - 0.18), (s * 0.72, hc.y + 0.02, hc.z - 0.3), 0.2)
    fy = front_y(th, 0, hc.z - 0.1)
    kchain(a, "tigL", [(0, fy + 0.1, hc.z - 0.14), (0, fy - 0.16, hc.z - 0.17)], [0.36, 0.3], [0.24, 0.2],
           up=(0, 0, 1))  # морда вперёд
    a.box("nose", -0.075, 0.075, fy - 0.2, fy - 0.14, hc.z - 0.1, hc.z - 0.03, bevel=0)
    a.box("tigD", -0.006, 0.006, fy - 0.2, fy - 0.16, hc.z - 0.24, hc.z - 0.1, bevel=0)
    for s in S2:
        eye2(a, (s * 0.18, front_y(th, s * 0.18, hc.z + 0.1) + 0.02, hc.z + 0.1), 0.085, (s * 0.3, -1, 0),
             "calm", s, "tig", "tigD", lid=0.3)
        A.ball(a, "tig", (s * 0.32, hc.y + 0.08, hc.z + 0.36), 0.13, n=2, ry=0.06)  # круглые уши
        a.prism("white", S.octagon(s * 0.32 - 0.045, s * 0.32 + 0.045, hc.z + 0.33, hc.z + 0.41, 0.01), hc.y + 0.15,
                hc.y + 0.16, axis="y", bevel=0)  # белое пятно на ухе
        kchain(a, "neonS", [(s * 0.08, front_y(th, s * 0.1, hc.z + 0.26) - 0.01, hc.z + 0.29),
                            (s * 0.14, front_y(th, s * 0.15, hc.z + 0.34), hc.z + 0.37)], [0.045, 0.04],
               up=(0, -1, 0))  # сапфировые полоски на лбу
    face_point(a, (0, fy, hc.z))
    closeup(a, (0.0, 0.0, t + 1.3))
    a.pose = {"ArmL": ((-20, 0, 0), (0, 0, 0)), "Tail": ((0, 12, 0), (0, 0, 0))}
    return a


def gold_mane_hippocamp():
    """3. Гиппокамп-златогрив: спереди конь, сзади рыбий хвост; встал на дыбы из волны, грива и плавники — бирюза с
    золотом. Признаки: конская голова с гривой, передние ноги с плавниками-перепонками, чешуйчатый рыбий хвост с
    веером, перламутровое брюхо."""
    a = new("GoldManeHippocamp", {"hc": ("2EC4C0", True), "hcD": ("1E8E9A", True), "hcB": ("F0F6FF", False),
                                  "gold": ("F5B21C", True), "water": ("3BA7E0", True), "foam": ("E6F7FF", False),
                                  "hoof": ("1E5E6A", False)})
    t = legendary_stand(a, 1.7)
    part(a, "Wave", "Stand", (0, 0, t))  # волна — часть композиции
    a.prism("water", S.octagon(-0.9, 0.9, -0.85, 0.95, 0.35), t, t + 0.18, bevel=0)
    for k, ang in enumerate(range(20, 360, 50)):
        r = math.radians(ang)
        spike(a, "foam", (0.55 * math.cos(r), 0.55 * math.sin(r), t + 0.12),
              (0.72 * math.cos(r), 0.72 * math.sin(r), t + 0.38 + 0.06 * (k % 2)), 0.14)
    part(a, "Body", "Wave", (0, 0.1, t + 0.8))
    # рыбий хвост из волны вверх к телу, чешуя — два тона по очереди
    tail = [(0.1, 0.55, t + 0.12), (0.05, 0.45, t + 0.45), (0, 0.3, t + 0.75), (0, 0.12, t + 1.0)]
    for i in range(len(tail) - 1):
        kchain(a, "hc" if i % 2 else "hcD", [tail[i], tail[i + 1]], [0.36 + 0.06 * i, 0.4 + 0.06 * i], up=(0, -1, 0))
    for s in S2:  # хвостовой веер — золото, поднят из волны сзади
        a.extrude("gold", [(0, 0), (0.18, 0.1), (0.45, 0.42), (0.18, 0.32)], -0.03, 0.03, axis="x",
                  matrix=Matrix.Translation((s * 0.05, 0.62, t + 0.15)) @ Matrix.Rotation(math.radians(s * 20), 4, "Z"))
    A.body(a, "hc", (0, 0.0, t + 0.95), 0.36, 0.34, 0.6, "egg", n=4, lean=-0.15,
           front=("hcB", 0.6, t + 0.95, t + 1.45))  # грудь коня, перламутровое брюхо
    for s in S2:  # передние ноги на дыбах с плавниками-перепонками
        part(a, "Arm" + ("L" if s > 0 else "R"), "Body", (s * 0.2, -0.2, t + 1.35))
        A.limb(a, "hc", [(s * 0.2, -0.2, t + 1.35), (s * 0.26, -0.5, t + 1.3), (s * 0.24, -0.55, t + 1.0)],
               [0.13, 0.11, 0.1])
        a.prism("hoof", S.octagon(s * 0.24 - 0.07, s * 0.24 + 0.07, -0.62, -0.48, 0.03), t + 0.92, t + 1.0, bevel=0)
        a.extrude("gold", [(0, 0), (0.25, -0.05), (0.3, -0.3)], -0.02, 0.02, axis="x",
                  matrix=Matrix.Translation((s * 0.24, -0.5, t + 1.3)))  # плавник-перепонка
        a.group = "Body"
    part(a, "Head", "Body", (0, -0.15, t + 1.5))
    kchain(a, "hc", [(0, -0.05, t + 1.4), (0, -0.15, t + 1.75), (0, -0.2, t + 1.95)], [0.3, 0.26, 0.24],
           up=(0, -1, 0))  # шея
    hc = V((0, -0.3, t + 2.05))
    th = A.body(a, "hc", (hc.x, hc.y, hc.z - 0.16), 0.17, 0.2, 0.32, "ball", n=3)
    fy = front_y(th, 0, hc.z - 0.05)
    taper(a, "hc", (0, fy + 0.08, hc.z - 0.06), (0, fy - 0.3, hc.z - 0.16), 0.24, 0.18, 0.22, 0.16)  # конская морда
    a.box("hcD", -0.05, 0.05, fy - 0.33, fy - 0.29, hc.z - 0.15, hc.z - 0.1, bevel=0)
    grin(a, (0, fy - 0.3, hc.z - 0.22), 0.1, h=0.035)
    for s in S2:
        eye2(a, (s * 0.11, front_y(th, s * 0.11, hc.z + 0.04) + 0.01, hc.z + 0.04), 0.06, (s * 0.5, -1, 0), "goofy",
             s, "hc", "hcD")
        tri_ear(a, "hc", "hcB", (s * 0.08, hc.y + 0.04, hc.z + 0.12), (s * 0.14, hc.y + 0.08, hc.z + 0.34), 0.1)
    for k in range(5):  # золотая грива по шее
        z = t + 1.5 + 0.13 * k
        y = 0.05 - 0.07 * k
        spike(a, "gold", (0, y, z), (0, y + 0.3, z + 0.12), 0.16)
    face_point(a, (0, fy - 0.15, hc.z))
    closeup(a, (0.0, 0.1, t + 1.1))
    a.pose = {"ArmL": ((-20, 0, 0), (0, 0, 0)), "ArmR": ((15, 0, 0), (0, 0, 0))}
    return a


