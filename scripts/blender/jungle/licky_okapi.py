ROLL = -10.0  # голова наклонена к уху, которое лижет (−x)
YAW = 22.0  # голова повёрнута мордой к +x: облизываемое ухо и дуга языка — к зрителю
OY = 0.34  # всё существо сдвинуто назад (+y): длинная голова впереди, центр массы над серединой подставки
SH = Matrix.Translation((0, OY, 0))


def sh(p):
    """Точка модели со сдвигом OY (точки вращения частей)."""
    return tuple(V(p) + V((0, OY, 0)))


def _axis_pt(p0, p1, f):
    return V(p0).lerp(V(p1), f)


def _bands(a, key, p0, p1, w0, w1, fs, hb=0.075, out=0.05):
    """Полосы-кольца поперёк звена p0 → p1 (ширина w0 → w1): в долях fs, шириной hb, выступают на out/2."""
    for i, f in enumerate(fs):
        c = _axis_pt(p0, p1, f)
        d = (V(p1) - V(p0)).normalized()
        w = w0 + (w1 - w0) * f + out + 0.006 * (i % 2)  # соседние полосы чуть разной толщины — грани не совпадают
        taper(a, key, c - d * hb / 2, c + d * hb / 2, w, w, cut=0.26)


def _leg(a, nm, hip, knee, hoof, w, t, front):
    """Нога зебры: бедро тёмное с белыми полосами, ниже колена — белый «чулок», у копыта тёмное кольцо, копыто."""
    part(a, nm, "Body", sh(hip))
    A.limb(a, "ok", [hip, knee], [w, w * 0.72], joints=False)
    A.ball(a, "ok", knee, w * 0.44, n=3)  # колено входит и в бедро, и в голень
    A.limb(a, "okW", [knee, hoof], [w * 0.62, w * 0.5], joints=False)
    vis = 0.12 if front else 0.05  # видимая часть бедра под телом
    # задние: верхняя полоса сразу под крупом — продолжает полосы крупа
    _bands(a, "okW", hip, knee, w, w * 0.72, (0.34 + vis, 0.56 + vis * 0.5, 0.78) if front else (0.3, 0.47, 0.64, 0.82))
    _bands(a, "okD", knee, hoof, w * 0.62, w * 0.5, (0.8,), hb=0.07, out=0.04)  # тёмный «браслет» над копытом
    hx, hy = hoof[0], hoof[1]
    a.prism("okD", S.octagon(hx - 0.11, hx + 0.11, hy - 0.13, hy + 0.08, 0.04), t + 0.004 + 0.003 * (len(nm) % 3),
            hoof[2] + 0.05, bevel=0)  # копыто


def _scaled(prof, anchor, sy, sz):
    ay, az = anchor
    return [(ay + (y - ay) * sy, az + (z - az) * sz) for y, z in prof]


def _band_prof(prof, z0, z1, y0):
    """Часть бокового профиля (y, z) в полосе z0 ≤ z ≤ z1 и позади y0 — сечение полосы крупа."""
    pz = clip_band([(z, y) for y, z in prof], z0, z1)
    return clip_band([(y, z) for z, y in pz], y0, 9.0)


def _ear_frame(base, tip, n0):
    """Оси уха: x — от основания к кончику, z — нормаль розовой стороны (ближе к n0), y — поперёк."""
    e1 = (V(tip) - V(base)).normalized()
    n = V(n0) - e1 * V(n0).dot(e1)
    n.normalize()
    e2 = n.cross(e1)
    m = Matrix.Identity(4)
    for i in range(3):
        m[i][0], m[i][1], m[i][2], m[i][3] = e1[i], e2[i], n[i], base[i]
    return m


EAR = [(-0.12, -0.1), (0.1, -0.2), (0.34, -0.24), (0.6, -0.14), (0.72, 0.0), (0.6, 0.14), (0.34, 0.24), (0.1, 0.2),
       (-0.12, 0.1)]  # контур уха (u вдоль, w поперёк): узкое основание, широкая середина, тупой кончик
EAR_IN = [(0.04, -0.09), (0.32, -0.15), (0.54, -0.09), (0.62, 0.0), (0.54, 0.09), (0.32, 0.15), (0.04, 0.09)]


def licky_okapi():
    a = new("LickyOkapi", {"ok": ("5E2537", True), "okD": ("3A1820", False), "okW": ("FFF8EE", False),
                           "cream": ("F7E2BF", True), "tongueV": ("7A3CFF", True), "nose": ("6E3426", False),
                           "earIn": ("FF9FB8", False)})
    t = rare_stand(a, 1.55)
    with_matrix(a, SH)

    # ── тело: слоёный профиль сбоку (y — длина, z), холка выше крупа, как у жирафовых ──
    part(a, "Body", "Stand", sh((0, 0, t + 1.4)))
    prof = [(-0.74, t + 1.12), (-0.86, t + 1.42), (-0.74, t + 1.78), (-0.36, t + 1.86), (0.3, t + 1.74),
            (0.78, t + 1.66), (0.9, t + 1.42), (0.78, t + 1.14), (0.3, t + 1.06), (-0.3, t + 1.06)]
    anchor = (0.0, t + 1.44)
    layered(a, "ok", prof, [(0.3, 1, 1), (0.42, 0.9, 0.86)], anchor)
    # белые полосы крупа обвивают круп (бока и зад обоих слоёв), выступают на 0.03, начинаются на разной длине;
    # нижняя доходит до бёдер, где продолжаются полосы ног
    K.KEY = "okW"
    for k, (z0, y0) in enumerate(((1.13, 0.36), (1.27, 0.2), (1.41, 0.42), (1.55, 0.3))):
        zb0, zb1 = t + z0, t + z0 + 0.075 + 0.004 * k
        outer = _band_prof(_scaled(prof, anchor, 0.9 * 1.04, 0.86), zb0, zb1, y0)
        K.slab(a, outer, -0.45 - 0.003 * k, 0.45 + 0.003 * k)
        inner = _band_prof(_scaled(prof, anchor, 1.035, 1.0), zb0 + 0.008, zb1 - 0.008, max(y0, 0.6))  # без общих граней
        if len(inner) >= 3:
            K.slab(a, inner, -0.33, 0.33)
    # шея короткая и толстая — от холки вперёд-вверх
    kchain(a, "ok", [(0, -0.55, t + 1.6), (0, -0.82, t + 1.92), (0, -0.92, t + 2.12)], [0.46, 0.4, 0.36],
           up=(0, -1, 0))

    # ── ноги зебры ──
    for s in S2:
        sx = "L" if s > 0 else "R"
        _leg(a, "LegF" + sx, (s * 0.25, -0.5, t + 1.3), (s * 0.27, -0.56, t + 0.62), (s * 0.27, -0.54, t + 0.06), 0.25,
             t, True)
        _leg(a, "LegB" + sx, (s * 0.25, 0.55, t + 1.3), (s * 0.28, 0.66, t + 0.64), (s * 0.27, 0.56, t + 0.06), 0.29,
             t, False)

    # ── хвост: короткий, с тёмной кисточкой ──
    part(a, "Tail", "Body", sh((0, 0.84, t + 1.55)))
    kchain(a, "ok", [(0, 0.8, t + 1.58), (0.04, 0.95, t + 1.42), (0.07, 0.97, t + 1.16)], [0.13, 0.11, 0.1],
           up=(0, 1, 0))
    knob(a, "okD", (0.07, 0.98, t + 1.06), 0.09)

    # ── голова жирафа (в осях головы: поворот к зрителю и наклон к уху): длинная, слоями сбоку — тёмный череп
    # с ровным лбом и ступенью макушки, кремовые морда и щёки; глаза на лбу над мордой ──
    hc = V((0, -1.0, t + 2.42))
    part(a, "Head", "Body", sh((0, -0.9, t + 2.1)))
    hm = SH @ Matrix.Translation(hc) @ Matrix.Rotation(math.radians(YAW), 4, "Z") @ Matrix.Rotation(
        math.radians(ROLL), 4, "Y")
    with_matrix(a, hm)
    skull = [(0.32, 0.0), (0.26, 0.3), (0.05, 0.38), (-0.3, 0.36), (-0.42, 0.28), (-0.42, 0.0), (-0.2, -0.1),
             (0.25, -0.12)]
    layered(a, "ok", skull, [(0.38, 1, 1)], (0.0, 0.15))  # череп: перёд — ровный лоб под глаза
    crown = [(0.22, 0.28), (0.15, 0.45), (-0.1, 0.48), (-0.3, 0.4), (-0.34, 0.28)]
    layered(a, "ok", crown, [(0.26, 1, 1)], (0.0, 0.3))  # ступень макушки
    cheek = [(-0.45, -0.12), (-0.5, -0.3), (-0.3, -0.42), (0.15, -0.36), (0.25, -0.1), (-0.1, 0.0)]
    layered(a, "cream", cheek, [(0.34, 1, 1)], (0.0, -0.2))  # кремовые щёки
    muzzle = [(-0.98, -0.1), (-1.0, -0.34), (-0.9, -0.44), (-0.3, -0.44), (0.05, -0.32), (0.05, 0.0), (-0.4, 0.05)]
    layered(a, "cream", muzzle, [(0.17, 1, 1), (0.23, 0.88, 0.92)], (-0.3, -0.2))  # морда жирафа, к носу уже
    for s in S2:  # ноздри — сверху на конце морды
        a.box("nose", s * 0.085 - 0.035, s * 0.085 + 0.035, -0.05, 0.05, -0.03, 0.02, bevel=0,
              matrix=Matrix.Translation((0, -0.86, -0.062)) @ Matrix.Rotation(math.radians(14.5), 4, "X"))
    # рот: щель спереди морды (из неё выходит язык), от неё по бокам — улыбка с поднятыми уголками
    a.box("mouth", -0.16, 0.09, -1.035, -0.9, -0.37, -0.23, bevel=0)
    for s in S2:
        bar(a, "dark", (s * 0.247, -0.9, -0.31), (s * 0.247, -0.64, -0.31), 0.05, 0.08, bevel=0)
        bar(a, "dark", (s * 0.247, -0.67, -0.315), (s * 0.247, -0.54, -0.19), 0.05, 0.08, bevel=0)  # уголок вверх
        # румянец — квадраты на боках кремовых щёк над уголками улыбки
        a.box("blush", s * 0.33, s * 0.36, -0.44, -0.26, -0.3, -0.16, bevel=0)
    # глаз +x — довольный прищур: низкий белок-щёлочка, щека снизу поднимает середину, бровь поднята к виску
    ec, en = V((0.2, -0.42, 0.17)), (0.12, -1, 0.1)
    eye2(a, ec, 0.12, en, "calm", 1, "ok", "okD", lid=0.0, look=(0.0, 0.5), pupil=0.5, h=0.75, show_brow=False)
    em = Matrix.Translation(ec) @ A.facing(en)
    with_matrix(a, hm @ em)  # белок полумесяцем «◠»: снизу щека поднята ровно, верхние углы прикрыты веком
    a.box("ok", -0.135, 0.135, -0.068, 0.04, -0.11, -0.025, bevel=0)  # щека-нижнее веко
    for s in S2:
        a.box("ok", s * 0.065, s * 0.135, -0.07, 0.04, 0.035, 0.11, bevel=0)  # скруглённые верхние углы
    a.box("okD", -0.1, 0.1, -0.03, 0.12, 0.12, 0.19, bevel=0,
          matrix=Matrix.Rotation(math.radians(-12), 4, "Y"))  # бровь поднята, наружный конец выше
    em = Matrix.Translation(V((-0.22, -0.42, 0.17))) @ A.facing((-0.2, -1, 0.1))
    with_matrix(a, hm @ em)  # зажмуренный глаз
    a.box("ok", -0.11, 0.11, -0.03, 0.06, -0.11, 0.11, bevel=0)  # веко
    bar(a, "dark", (-0.1, -0.055, -0.04), (0.0, -0.055, 0.04), 0.05, 0.075, bevel=0)  # «^»
    bar(a, "dark", (0.0, -0.06, 0.04), (0.1, -0.06, -0.04), 0.05, 0.075, bevel=0)
    a.box("okD", -0.1, 0.1, -0.03, 0.12, 0.16, 0.23, bevel=0,
          matrix=Matrix.Rotation(math.radians(-8), 4, "Y"))  # бровь расслаблена: внутренний конец чуть выше
    with_matrix(a, hm)
    # рожки-оссиконы: в шерсти, кончики тёмные
    for s in S2:
        taper(a, "ok", (s * 0.13, 0.02, 0.42), (s * 0.16, 0.08, 0.66), 0.13, 0.11, cut=0.26)
        knob(a, "okD", (s * 0.16, 0.08, 0.68), 0.07)

    # ── огромные уши: плоские пластины с чистым контуром, розовая сторона вперёд; −x поднято навстречу языку ──
    ears = {1: ((0.33, 0.08, 0.24), (0.98, 0.2, 0.5), (0.2, -1, 0.15)),
            -1: ((-0.33, -0.1, 0.26), (-0.84, -0.34, 0.62), (-0.45, -1, 0.1))}
    em_l = None
    for s, (base, tip, n0) in ears.items():
        nm = "EarL" if s > 0 else "EarR"
        part(a, nm, "Head", tuple(hm @ V(base)))
        m = hm @ _ear_frame(base, tip, n0)
        with_matrix(a, m)
        a.prism("ok", EAR, -0.05, 0.05, bevel=0)
        a.prism("earIn", EAR_IN, 0.0, 0.08, bevel=0)  # розовая сторона — ступень над пластиной
        if s < 0:
            em_l = _ear_frame(base, tip, n0)

    # ── язык: из щели рта вперёд, вбок и вверх перед щекой одной дугой — кончиком-лопаткой на розовое ухо ──
    root = V((-0.04, -0.89, -0.3))
    part(a, "Tongue", "Head", tuple(hm @ root))
    with_matrix(a, hm)
    # дуга в своей плоскости: ось da — вбок (−x), ось db — от рта к уху; сначала язык свисает вперёд-вниз,
    # потом широкой дугой огибает щёку снаружи и ложится на ухо; середина дуги выгнута к зрителю
    o = V((-0.04, -1.1, -0.32))
    end = em_l @ V((0.22, -0.06, 0.08))
    da = V((-1, 0, 0))
    rel = end - o
    db = (rel - da * rel.dot(da)).normalized()
    dn = da.cross(db).normalized()
    if dn.y > 0:
        dn = -dn
    be = rel.dot(db)
    arc = [(0.12, -0.12, 0.0), (0.36, -0.18, 0.04), (0.6, -0.08, 0.06), (0.76, 0.18, 0.06), (0.78, 0.5, 0.04),
           (0.66, 0.79, 0.02)]  # (вбок, доля пути к уху, выгиб к зрителю)
    tp = [tuple(root), tuple(o)] + [tuple(o + da * u + db * w * be + dn * q) for u, w, q in arc] + [tuple(end)]
    up = tuple(dn)  # нормаль плоскости дуги: язык плоский, широкой стороной к зрителю
    kchain(a, "tongueV", tp[:3], [0.2, 0.24, 0.28], [0.15, 0.16, 0.17], up=up, cut=0.3)  # корень — из щели рта
    kchain(a, "tongueV", tp[2:], [0.28] * (len(tp) - 3) + [0.26], [0.17] * (len(tp) - 3) + [0.14], up=up, cut=0.3)
    with_matrix(a, hm @ em_l)  # кончик-лопатка лежит на розовой стороне уха
    a.prism("tongueV", S.octagon(0.14, 0.44, -0.2, 0.15, 0.07), 0.04, 0.16, bevel=0)
    with_matrix(a, None)  # дальше конвейер добавляет метки без сдвига

    face_point(a, tuple(hm @ V((-0.2, -0.7, 0.12))))
    tg = hm @ V((-0.25, -0.55, 0.12))
    FACE_CAM["LickyOkapi"] = (tuple(tg + V((0.2, -5.8, 1.2))), tuple(tg))  # лицо, язык и ухо целиком
    closeup(a, (0.3, OY, t + 1.5), eye_off=(-0.5, -2.4, 0.8))
    a.pose = {"Head": ((0, -8, 6), (0, 0, 0)), "Tongue": ((0, 0, -6), (0, 0, 0)), "EarL": ((0, 18, 0), (0, 0, 0)),
              "LegFL": ((-28, 0, 0), (0, 0, 0)), "Tail": ((0, 0, 25), (0, 0, 0))}
    return a


