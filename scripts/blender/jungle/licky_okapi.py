"""Окапи-лизун (LickyOkapi, Rare, №20 каталога docs/BOSS6_CATALOG.md) — голова как у жирафа, ноги как у зебры, а
сине-фиолетовый язык такой длинный, что окапи одной дугой облизывает им собственное ухо (окапи так умеют).
Признаки вида: бархатное тёмное сливово-каштановое тело; белые полосы на ногах и крупе; голова жирафа с двумя рожками
в шерсти (оссиконы с тёмными кончиками); огромные уши; длинный сине-фиолетовый язык. Шея короткая (шутка — язык).
Эмоция — блаженство: глаз на стороне языка зажмурен «^», второй довольно прищурен полумесяцем, улыбка, румянец.
Голова повёрнута облизываемым ухом к зрителю: дуга языка идёт перед мордой, а не за головой.
Цвета: тёмный сливово-каштановый, белые полосы, кремовая морда, язык сине-фиолетовый, уши внутри розовые.
"""

