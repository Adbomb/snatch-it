"""Фонарница-крокодил (CrocLanternfly, Rare, №15 каталога docs/BOSS6_CATALOG.md) — у крошечной цикадки вместо лба
огромный вздутый вырост-«крокодилья морда», больше всего тела (так маскируется настоящая фонарница Fulgora laternaria).
Сидит низко на шести коротких лапках, расправив в стороны плоские яркие крылья. Признаки вида: вырост головы растёт из
всего лба вперёд (лоб плавно переходит в морду, без ступеньки-«шляпы»), на нём «глаза»-бугры крокодила, «ноздри»,
оранжевые пятна и нарисованная сомкнутая пасть — одна сплошная тёмная линия без зубов, к кончику чуть вверх; маленькие
настоящие глазки у основания выроста; две пары плоских крыльев — передние узкие пёстрые лежат на переднем крае задних,
задние с крупными «глазками»; короткий тёмный хоботок под личиком назад; шесть лапок. Эмоция — робость: глазки-бусинки
виновато косятся вверх-внутрь на собственную морду, брови домиком, румянец, ротик — маленькая смущённая волнистая
линия. Цвета: зелёно-бурая «крокодилья» морда с бурыми пятнами, ноздрями-бугорками и нарисованными сомкнутыми зубами-полосками (правка владельца 2026-11-26); передние крылья оранжево-алые
с жёлтыми и кремовыми крапинами, задние насыщенно-жёлтые с крупными чёрно-алыми «глазками» в белом ободке; тельце рыжее.
Силуэт не путается с Мотыльком-пуделем (круглый и пушистый): тело тонкое, морда длинная вперёд, крылья плоские в стороны
(решение владельца 2026-11-25).
Зависит от jungle_kit.py (creature_kit, anatomy_kit, art_style, v4_kit).
"""

import math
import os
import sys

from mathutils import Matrix, Vector

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from jungle_kit import *  # noqa: E402,F401,F403

YAW = 25  # всё существо чуть повёрнуто вправо: в кадре героя и с телефона морда видна сбоку (пасть, пятна)
SHIFT_Y = 0.24  # сдвиг назад: длинная морда и тело с крыльями — над серединой подставки
PITCH = 6  # морда — продолжение головы вперёд, почти горизонтально (подъём не больше 10°)
DIHEDRAL = 12  # крылья плоские, в стороны: подняты всего на 12° над горизонтом
SPLAY = 10  # задние крылья чуть назад; передние лежат на их переднем крае
PITCH_W = 14  # задний край крыльев чуть приподнят: верх крыльев и «глазки» смотрят вверх и к игроку спереди-сбоку


def basis(o, x, z):
    """Оси детали: начало o, ось x, ось z (вдоль детали); y = z × x (правая тройка)."""
    x, z = V(x).normalized(), V(z).normalized()
    y = z.cross(x).normalized()
    return Matrix(((x.x, y.x, z.x, o[0]), (x.y, y.y, z.y, o[1]), (x.z, y.z, z.z, o[2]), (0, 0, 0, 1)))


def wing_frame(o, s, splay, dihedral, phi):
    """Плоскость крыла: u — размах наружу (±x), повёрнутый назад на splay° (вперёд — минус) и поднятый на dihedral°;
    c — хорда назад, поднятая на phi°; нормаль — поперёк крыла (правая тройка для обеих сторон: у левого крыла
    нормаль смотрит вниз, поэтому «вверх» по нормали — это s · z)."""
    d, p, w = math.radians(dihedral), math.radians(phi), math.radians(splay)
    es = V((s * math.cos(w) * math.cos(d), math.sin(w) * math.cos(d), math.sin(d)))
    ec = V((-s * math.sin(w) * math.cos(p), math.cos(w) * math.cos(p), math.sin(p)))
    ec = (ec - es * ec.dot(es)).normalized()
    n = es.cross(ec)
    return Matrix(((es.x, ec.x, n.x, o[0]), (es.y, ec.y, n.y, o[1]), (es.z, ec.z, n.z, o[2]), (0, 0, 0, 1)))


def through_spot(a, key, m, u, c, r, lo, hi):
    """Пятно-восьмиугольник насквозь через пластину крыла (видно с обеих сторон): от lo до hi по нормали крыла."""
    a.prism(key, S.octagon(u - r, u + r, c - r, c + r, r * 0.42), lo, hi, axis="z", bevel=0, matrix=m)


def croc_lanternfly():
    a = new("CrocLanternfly", {"snout": ("F6EBA8", True), "snoutL": ("FFF6DE", True), "spotO": ("FF8A1F", False), "spotB": ("4A3A1C", False), "jawU": ("6F7E2E", True), "jawL": ("A9A55C", True),
                               "jawS": ("4A3A1C", False), "tooth": ("F4EDC8", False),
                               "bug": ("C4602C", True), "bugD": ("6E3420", False), "rost": ("3A2418", False),
                               "fore": ("F0472A", True), "foreY": ("FFD23C", False), "foreC": ("FFF0C8", False),
                               "hind": ("FFC81E", True), "ocK": ("111118", False), "ocR": ("E0203A", False)})
    t = rare_stand(a, 1.6)
    G = Matrix.Rotation(math.radians(YAW), 4, "Z") @ Matrix.Translation((0, SHIFT_Y, 0))

    def g(p):
        return tuple(G @ V(p))

    with_matrix(a, G)

    # ── тело: грудь-шар низко над подставкой (брюшко груди ≈ 0.35) и тонкое полосатое брюшко назад-вниз (цикадка) ──
    TH = V((0, 0.12, t + 0.65))
    part(a, "Body", "Stand", g(TH))
    A.body(a, "bug", (TH.x, TH.y, TH.z - 0.3), 0.3, 0.32, 0.6, "ball", n=3)
    d_ab = V((0, 0.95, -0.25)).normalized()
    m_ab = basis(TH + V((0, 0.14, -0.04)), (1, 0, 0), d_ab)
    A.body(a, "bug", (0, 0, 0), 0.25, 0.23, 1.0, "drop", n=4, t0=0.06, t1=0.8, keys=["bugD", "bug"], matrix=m_ab)

    # ── шесть коротких лапок (звенья ≥ 0.14): из-под груди, колени сразу у боков, стопы-подушечки под телом и
    # крыльями; передняя пара — под личиком и тяжёлой мордой ──
    legs = (("LegFL", "LegFR", (0.14, -0.02, 0.52), (0.36, -0.2, 0.46), (0.42, -0.42, 0.05)),
            ("LegML", "LegMR", (0.17, 0.1, 0.46), (0.42, 0.12, 0.44), (0.48, 0.14, 0.05)),
            ("LegBL", "LegBR", (0.14, 0.32, 0.48), (0.38, 0.46, 0.44), (0.44, 0.66, 0.05)))
    for nl, nr, hp, kn, ft in legs:
        for s, nm in ((-1, nl), (1, nr)):
            hip = V((s * hp[0], hp[1], t + hp[2]))
            part(a, nm, "Body", g(hip))
            knee = V((s * kn[0], kn[1], t + kn[2]))
            foot = V((s * ft[0], ft[1], t + ft[2]))
            A.limb(a, "bugD", [tuple(hip), tuple(knee), tuple(foot)], [0.16, 0.15, 0.14], joints=False)
            a.box("bugD", foot.x - 0.09, foot.x + 0.09, foot.y - 0.09, foot.y + 0.09, t + 0.005, t + 0.07, bevel=0)

    # ── голова: маленькое личико внизу, а весь лоб — корень огромной «морды» вперёд ──
    HC = V((0, -0.28, t + 0.73))
    z0 = HC.z
    part(a, "Head", "Body", g(HC + V((0, 0.22, -0.04))))
    # личико — брусок во всю ширину лба; верхний ярус расширен до корня морды: лоб плавно переходит в морду
    # (кремовый к лимонно-кремовому, без ступеньки — морда растёт из головы, а не надета шляпой)
    face = A.body(a, "snoutL", (HC.x, HC.y, z0 - 0.38), 0.31, 0.28, 0.7,
                  lambda u: 0.86 if u < 0.34 else (1.0 if u < 0.67 else 1.1), n=3)
    FY = HC.y - 0.28  # плоскость лица: отсюда морда растёт вперёд
    d_sn = V((0, -math.cos(math.radians(PITCH)), math.sin(math.radians(PITCH))))
    O = V((0, FY, z0 + 0.42))
    m_sn = basis(O, (1, 0, 0), d_sn)  # оси морды: z — вперёд, y — её верх, x — вбок
    # морда-крокодил одной массой: ярусы-восьмиугольники (от, до, полуширина, верх); первый ярус — сам лоб и темя над
    # личиком в ширину его верхнего яруса, дальше вздутие «челюстного шарнира», сужение к рылу и вздутие с ноздрями.
    # Низ нижней челюсти — одна плоскость (как у крокодила); верхняя челюсть лимонно-кремовая, нижняя — кремовая
    SN = ((-0.46, 0.0, 0.335, 0.24), (0.0, 0.28, 0.35, 0.3), (0.28, 0.56, 0.315, 0.26), (0.56, 0.82, 0.275, 0.21),
          (0.82, 1.04, 0.235, 0.185), (1.04, 1.26, 0.27, 0.22))
    BOT, YM = -0.22, -0.05  # низ морды и линия пасти (по оси морды)
    sn = []
    for k, (za, zb, rx, ry) in enumerate(SN):
        zb2 = zb + (0.012 if k < len(SN) - 1 else 0.0)
        cut = min(rx, (ry - BOT) / 2) * 0.34
        pts = S.octagon(-rx, rx, BOT, ry, cut)
        # правка владельца 2026-11-26: «морда» зелёно-бурая (верхняя челюсть — бурая олива, нижняя — светлее)
        a.prism("jawL", A._clip(pts, (0, -1), -(YM + 0.012)), za, zb2, axis="z", bevel=0, matrix=m_sn)
        a.prism("jawU", A._clip(pts, (0, 1), YM - 0.012), za + 0.003, zb2 + 0.004, axis="z", bevel=0, matrix=m_sn)
        sn.append((za, zb, rx, ry, cut))
    # сомкнутая пасть без зубов: одна сплошная тёмная линия высотой 0.09 по бокам и по торцу рыла, выступает на 0.025;
    # к кончику плавно приподнята (на каждом ярусе на 0.01 выше — верхние грани соседних кусков не совпадают)
    for k, (za, zb, rx, ry, cut) in enumerate(sn[1:], 1):
        last = k == len(SN) - 1
        ym = YM + 0.045 * (k / (len(SN) - 1)) ** 1.4
        pr = 0.025
        band = A._clip(A._clip(S.octagon(-rx - pr, rx + pr, BOT - pr, ry + pr, cut), (0, 1), ym + 0.045),
                       (0, -1), -(ym - 0.045))
        # конец куска — на 0.02 дальше конца яруса: ступенька к следующему (более узкому) ярусу на высоте пасти тоже
        # тёмная, линия не рвётся кремовыми торцами
        a.prism("ocK", band, za + 0.004, zb + (0.025 if last else 0.02), axis="z", bevel=0, matrix=m_sn)
        # нарисованные сомкнутые «зубы»: светлые полоски поперёк тёмной линии пасти (по бокам рыла), выступают на 0.01
        for f in (0.3, 0.75):
            zt = za + (zb - za) * f
            for sx in (-1, 1):
                x0, x1 = sx * (rx + pr - 0.01), sx * (rx + pr + 0.012)
                a.box("tooth", min(x0, x1), max(x0, x1), ym - 0.04, ym + 0.04, zt - 0.022, zt + 0.022, bevel=0,
                      matrix=m_sn)
    # оранжевые «крокодильи» пятна: по верху и по бокам верхней челюсти (мимо глаз-бугров)
    for k, xc, r in ((2, -0.12, 0.085), (3, 0.1, 0.075), (4, -0.05, 0.065), (2, 0.17, 0.06)):
        za, zb, rx, ry, cut = sn[k]
        zc = (za + zb) / 2
        a.prism("spotB", S.octagon(xc - r, xc + r, zc - r, zc + r, r * 0.42), ry - 0.05, ry + 0.024, axis="y",
                bevel=0, matrix=m_sn)
    for s, k, r in ((-1, 2, 0.075), (-1, 3, 0.065), (1, 2, 0.07), (1, 4, 0.055)):
        za, zb, rx, ry, cut = sn[k]
        zc, yc = (za + zb) / 2, (YM + 0.1 + ry - cut) / 2
        a.prism("spotB", S.octagon(zc - r, zc + r, yc - r, yc + r, r * 0.42), s * (rx - 0.05), s * (rx + 0.024),
                axis="x", bevel=0, matrix=m_sn)
    # «глаза» крокодила (ложные, как у настоящей фонарницы): два бугра на корне морды — оранжевое кольцо, кремовый
    # купол и тёмный зрачок-щель
    za, zb, rx, ry, cut = sn[1]
    zc = (za + zb) / 2
    for s in S2:
        xc = s * 0.165
        a.prism("spotO", S.octagon(xc - 0.14, xc + 0.14, zc - 0.14, zc + 0.14, 0.058), ry - 0.06, ry + 0.07,
                axis="y", bevel=0.012, matrix=m_sn)
        a.prism("jawL", S.octagon(xc - 0.1, xc + 0.1, zc - 0.1, zc + 0.1, 0.042), ry + 0.04, ry + 0.15, axis="y",
                bevel=0.012, matrix=m_sn)
        a.box("ocK", xc - 0.035, xc + 0.035, ry + 0.13, ry + 0.17, zc - 0.075, zc + 0.075, bevel=0, matrix=m_sn)
    # «ноздри» на кончике рыла: два бугра ≈ 0.2 с тёмными дырочками
    za, zb, rx, ry, cut = sn[-1]
    zc = (za + zb) / 2
    for s in S2:
        xc = s * 0.112
        a.prism("jawU", S.octagon(xc - 0.11, xc + 0.11, zc - 0.11, zc + 0.11, 0.045), ry - 0.05, ry + 0.11,
                axis="y", bevel=0.012, matrix=m_sn)
        a.prism("ocK", S.octagon(xc - 0.05, xc + 0.05, zc - 0.05, zc + 0.05, 0.02), ry + 0.08, ry + 0.13,
                axis="y", bevel=0, matrix=m_sn)
    # настоящее личико под мордой: маленькие глазки-бусинки у самого основания морды косятся вверх-внутрь на неё,
    # толстые брови домиком (внутренние концы подняты), румянец, ротик — смущённая волнистая линия
    ze = z0 - 0.03
    for s in S2:
        ex = s * 0.13
        ey = front_y(face, ex, ze)
        eye2(a, (ex, ey, ze), 0.064, (s * 0.1, -1, 0.05), "worried", s, "snoutL", "bugD", show_brow=False,
             look=(-s * 1.2, 1.2), pupil=0.62, lid=0.0)
        brow_bar(a, "bugD", (ex, ey, ze), (s * 0.1, -1, 0.05), 0.085, 0.135, s * 24, thick=0.06, depth=0.12)
        zb_ = z0 - 0.16
        fy = front_y(face, s * 0.18, zb_)
        a.box("blush", s * 0.18 - 0.055, s * 0.18 + 0.055, fy - 0.025, fy + 0.03, zb_ - 0.035, zb_ + 0.035, bevel=0)
    zm = z0 - 0.25
    fy = front_y(face, 0, zm)
    for x0, x1, dz, dy in ((-0.075, 0.006, 0.0, 0.0), (-0.006, 0.075, 0.02, 0.007)):  # волна: правая половина выше
        a.box("mouth", x0, x1, fy - 0.025 - dy, fy + 0.03, zm - 0.029 + dz, zm + 0.029 + dz, bevel=0)
    # хоботок: короткий тёмный (≈ 0.1 × 0.1), из-под личика назад-вниз между передними лапками
    taper(a, "rost", V((0, FY + 0.16, z0 - 0.3)), V((0, FY + 0.48, z0 - 0.63)), 0.11, 0.09, cut=0.25)

    # ── крылья плоские, раскинуты в стороны (подняты всего на DIHEDRAL°): задние жёлтые с крупным «глазком» сверху,
    # передние узкие пёстрые лежат поверх переднего края задних — в кадре героя видны обе пары ──
    th_h, th_f = 0.09, 0.11
    lift = th_h / 2 + th_f / 2 + 0.006  # передние над задними по нормали крыла: не пересекаются и грани не совпадают
    hind = [(0.0, 0.04), (0.7, 0.08), (1.18, 0.25), (1.36, 0.58), (1.23, 0.95), (0.84, 1.14), (0.36, 1.07),
            (0.05, 0.7)]
    fore = [(0.0, -0.1), (0.5, -0.3), (1.1, -0.42), (1.6, -0.36), (1.76, -0.16), (1.62, 0.08), (0.9, 0.24),
            (0.0, 0.22)]
    for s, nf, nh in ((-1, "WingFL", "WingHL"), (1, "WingFR", "WingHR")):
        hh = V((s * 0.06, 0.2, t + 0.79))
        mh = wing_frame(hh, s, SPLAY, DIHEDRAL, PITCH_W)
        part(a, nh, "Body", g(hh))
        a.prism("hind", hind, -th_h / 2, th_h / 2, axis="z", bevel=0, matrix=mh)
        # «глазок»: белый ободок, широкое тёмное кольцо, алый центр и блик — насквозь, видно сверху и снизу
        for key, r, half in (("white", 0.36, th_h / 2 + 0.02), ("ocK", 0.29, th_h / 2 + 0.035),
                             ("ocR", 0.16, th_h / 2 + 0.05)):
            through_spot(a, key, mh, 0.8, 0.68, r, -half, half)
        through_spot(a, "white", mh, 0.74, 0.75, 0.05, -(th_h / 2 + 0.062), th_h / 2 + 0.062)
        # передние — в осях задних, сдвинуты «вверх» (у левого крыла нормаль вниз — отсюда знак s); та же точка
        # вращения, что у задних: в позе пары не расходятся и не пересекаются
        mf = mh @ Matrix.Translation((0, 0, s * lift))
        part(a, nf, "Body", g(hh))
        a.prism("fore", fore, -th_f / 2, th_f / 2, axis="z", bevel=0, matrix=mf)
        hf = th_f / 2 + 0.022
        for key, u, c, r in (("foreY", 0.45, -0.12, 0.09), ("foreC", 0.9, -0.22, 0.1), ("foreY", 1.3, -0.16, 0.1),
                             ("foreC", 1.58, -0.2, 0.07)):
            through_spot(a, key, mf, u, c, r, -hf, hf)
    with_matrix(a, None)

    face_point(a, g(V((0, FY - 0.02, z0 - 0.06))))
    closeup(a, g(O + d_sn * 0.6 + V((0, 0, 0.3))), eye_off=(-1.4, -1.9, 0.9))

    # поза: взмах — плоские крылья чуть приподняты (не встают «парусами»), голова втянута, морда чуть опущена (сам её
    # боится). Повороты — вокруг осей самого существа (оно повёрнуто на YAW), в градусах Эйлера XYZ
    def turn(axis, deg):
        e = Matrix.Rotation(math.radians(deg), 3, G.to_3x3() @ V(axis)).to_euler("XYZ")
        return tuple(round(math.degrees(x), 2) for x in e)

    back = G.to_3x3() @ V((0, 1, 0))
    a.pose = {"WingHL": (turn((0, 1, 0), 7), (0, 0, 0)), "WingHR": (turn((0, 1, 0), -7), (0, 0, 0)),
              "WingFL": (turn((0, 1, 0), 7), (0, 0, 0)), "WingFR": (turn((0, 1, 0), -7), (0, 0, 0)),
              "Head": (turn((1, 0, 0), 6), tuple(back * 0.04)),
              "LegFR": (turn((1, 0, 0), -12), (0, 0, 0))}
    return a


