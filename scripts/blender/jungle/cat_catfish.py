def _ngon(r, n=12, cx=0.0, cy=0.0):
    return [(cx + r * math.cos(math.pi / n + 2 * math.pi * i / n), cy + r * math.sin(math.pi / n + 2 * math.pi * i / n))
            for i in range(n)]


def _axes(o, x, y):
    """Матрица осей: начало o, ось x детали — x, ось y — y (z — их произведение)."""
    x, y = Vector(x).normalized(), Vector(y).normalized()
    z = x.cross(y).normalized()
    y = z.cross(x)
    return Matrix(((x.x, y.x, z.x, o[0]), (x.y, y.y, z.y, o[1]), (x.z, y.z, z.z, o[2]), (0, 0, 0, 1)))


def _sec(w, zb, h, ct, cb=0.07):
    """Сечение тела поперёк длины (точки (x, z)): плоский низ на луже, округлый верх — скос верхних углов радиусом ct
    тремя гранями (спина и лоб читаются округлыми, а не ящиком), нижние углы срезаны на cb."""
    zt = zb + h
    arc = [(w - ct + ct * math.cos(math.radians(g)), zt - ct + ct * math.sin(math.radians(g))) for g in (0, 30, 60, 90)]
    return [(-w + cb, zb), (w - cb, zb), (w, zb + cb)] + arc + [(-x, z) for x, z in reversed(arc)] + [(-w, zb + cb)]


def _segment(a, key, y0, y1, w, zb, h, ct, zw=None, chin=False):
    """Звено тела вдоль y: верх — key, низ боков до zw — белая полоса чуть шире звена (только снизу, по торцам не
    заходит; chin — у переднего звена головы полоса выходит на перёд, это подбородок)."""
    poly = _sec(w, zb, h, ct)
    if zw is None:
        a.prism(key, poly, y0, y1, axis="y")
        return
    a.prism(key, A._clip(poly, (0, -1), -zw), y0, y1, axis="y")
    low = A._clip(_sec(w + 0.014, zb, h, ct), (0, 1), zw + 0.014)
    a.prism("belly", low, y0 - 0.014 if chin else y0 + 0.01, y1 - 0.012, axis="y", bevel=0)


def _ear(a, s, base, h):
    """Кошачье ушко: рыжая пирамидка с плоским передом, отклонена наружу; поперёк переда — две тёмно-рыжие полоски
    (на переде, не торчат по краям), внизу — розовая серединка."""
    m = Matrix.Translation(base) @ Matrix.Rotation(math.radians(12 * s), 4, "Y")
    bw, bd = 0.25, 0.14  # полуширина и полуглубина основания
    a.frustum("ear", (-bw, bw, -bd, bd), (-0.03, 0.03, -bd, -bd + 0.06), -0.1, h, bevel=0, matrix=m)

    def half(z):  # полуширина ушка на высоте z
        return bw + (0.03 - bw) * (z + 0.1) / (h + 0.1)

    for k, zc in enumerate((h * 0.47, h * 0.71)):
        z0, z1 = zc - 0.04, zc + 0.04
        w0, w1 = half(z0) - 0.022, half(z1) - 0.022
        a.extrude("earD", [(-w0, z0), (w0, z0), (w1, z1), (-w1, z1)], -bd - 0.022 - 0.004 * k, -bd + 0.03,
                  axis="y", matrix=m)
    a.extrude("pink", [(-0.11, -0.02), (0.11, -0.02), (0.0, h * 0.42)], -bd - 0.032, -bd + 0.02, axis="y", matrix=m)


def _arc(a, key, pts, w=0.075, h=0.08):
    kchain(a, key, pts, [w] * len(pts), [h] * len(pts), up=(0, -1, 0), cut=0.2, overlap=0.3)


def cat_catfish():
    a = new("CatCatfish", {"back": ("3A4560", True), "head": ("3A4560", False), "belly": ("F7F4EC", False),
                           "fin": ("6F86B8", False), "tailR": ("E8283C", True), "tailO": ("FF6A3D", False),
                           "ear": ("FF8A3D", False), "earD": ("C2541A", False), "whisk": ("F3E9D2", False),
                           "lip": ("FFA3B8", False), "water": ("14B8C4", True), "waterD": ("0B7F8C", False)})
    t = common_stand(a, 1.5)

    # лужа — своя часть Haze (в игре подставка скрыта, лужа остаётся): насыщенная бирюза и тёмная кромка
    part(a, "Haze", "Stand", (0, 0, t))
    a.prism("water", _ngon(1.32), t - 0.015, t + 0.055, bevel=0)
    a.frame("waterD", _ngon(1.4), 0.13, t + 0.02, t + 0.08, axis="z", bevel=0)

    # тело лежит вдоль y (морда к −y, хвост к +y): звенья с округлой спиной, горб сразу за головой, к хвосту тело
    # сужается и опускается; белое — только полоса по низу боков (y0, y1, полуширина, высота)
    part(a, "Body", "Stand", (0, 0.2, t + 0.35))
    body = [(-0.12, 0.18, 0.72, 0.76), (0.16, 0.44, 0.62, 0.66), (0.42, 0.66, 0.50, 0.54), (0.64, 0.84, 0.40, 0.43),
            (0.82, 0.98, 0.30, 0.33)]
    for k, (y0, y1, w, h) in enumerate(body):
        zb = t + 0.02 + 0.003 * k  # низ звеньев на разной высоте — грани не совпадают (низ утоплен в лужу)
        _segment(a, "back", y0, y1, w, zb, h, min(0.45 * w, 0.5 * h), zb + 0.14 + 0.006 * k if k < 4 else None)
    # спинной плавник — невысокий округлый парус над горбом, отклонён назад
    fin = [(0.08, t + 0.72), (0.5, t + 0.52), (0.48, t + 0.62), (0.36, t + 0.76), (0.22, t + 0.88), (0.1, t + 0.88)]
    a.extrude("fin", [(z, y) for y, z in fin], -0.06, 0.06, axis="x")

    # голова — широкая, плоская, лоб округлый (не ярусы-торт): три звена, переднее — морда без узора D39
    part(a, "Head", "Body", (0, -0.25, t + 0.35))
    head = [("head", -0.84, -0.64, 0.86, 0.70), ("back", -0.66, -0.30, 0.92, 0.78), ("back", -0.32, -0.06, 0.84, 0.80)]
    for k, (key, y0, y1, w, h) in enumerate(head):
        zb = t + 0.024 + 0.004 * k
        _segment(a, key, y0, y1, w, zb, h, min(0.5 * w, 0.55 * h), zb + 0.13 + 0.005 * k, chin=k == 0)
    yf = -0.84  # перёд морды
    # глаза-щёлочки «^ ^» — блаженно щурится (белые: на графите читаются издали), под ними — приподнятые румяные щёки
    ze = t + 0.53
    for s in S2:
        x = s * 0.38
        a.extrude("white", [(x - 0.175, ze - 0.035), (x, ze + 0.085), (x + 0.175, ze - 0.035), (x + 0.13, ze - 0.08),
                            (x, ze + 0.0), (x - 0.13, ze - 0.08)], yf - 0.025, yf + 0.03, axis="y")  # «^» цельный
        a.prism("blush", S.octagon(s * 0.6 - 0.12, s * 0.6 + 0.12, t + 0.36, t + 0.46, 0.03), yf - 0.045, yf + 0.03,
                axis="y", bevel=0)  # щека-бугорок выступает: мурлычет, щёки подняты
    # розовый кошачий носик и улыбка «ω» прямо на морде (над белым подбородком)
    a.prism("pink", [(-0.095, t + 0.47), (0.095, t + 0.47), (0.0, t + 0.39)], yf - 0.03, yf + 0.03, axis="y", bevel=0)
    zm = t + 0.29
    mouth = [(-0.4, zm + 0.065), (-0.27, zm - 0.01), (-0.12, zm - 0.015), (0.0, zm + 0.045), (0.12, zm - 0.015),
             (0.27, zm - 0.01), (0.4, zm + 0.065)]
    _arc(a, "lip", [(x, yf - 0.006 - 0.005 * (i % 2), z) for i, (x, z) in enumerate(mouth)], w=0.075)
    # рыжие полосатые ушки на макушке
    for s, nm in ((1, "EarL"), (-1, "EarR")):
        base = V((s * 0.36, -0.5, t + 0.024 + 0.004 + 0.78))
        part(a, nm, "Head", tuple(base + V((0, 0, 0.02))))
        _ear(a, s, base, 0.58)
    # усы-«антенны» из уголков рта: свисают вперёд и вниз и лежат на луже, сужаются к концу, без загиба вверх
    for s, nm in ((1, "BarbelL"), (-1, "BarbelR")):
        root = (s * 0.46, -0.78, zm + 0.04)
        part(a, nm, "Head", root)
        pts = [root, (s * 0.66, -1.0, t + 0.19), (s * 0.86, -1.18, t + 0.12), (s * 0.98, -1.33, t + 0.105)]
        kchain(a, "whisk", pts, [0.12, 0.11, 0.095, 0.08], [0.11, 0.1, 0.09, 0.08], up=(0, 0, 1), cut=0.25,
               overlap=0.4)

    # грудные плавники — плоские, светло-синие, по бокам тела за головой, отведены назад
    for s, nm in ((1, "FinL"), (-1, "FinR")):
        part(a, nm, "Body", (s * 0.62, -0.04, t + 0.12))
        pf = [(0.5, -0.12), (0.8, -0.07), (0.98, 0.1), (1.0, 0.28), (0.88, 0.36), (0.55, 0.16)]
        a.extrude("fin", [(s * x, y) for x, y in pf], t + 0.085, t + 0.155, axis="z")

    # хвост загнут набок (−x, к камере hero), как у довольной кошки, и поднят (стебель под 45°, плавник круче):
    # алый раздвоенный плавник стоит вертикально плоскостью к игроку (лопасти вверх и в сторону), нижняя лопасть —
    # над краем лужи
    part(a, "Tail", "Body", (0, 0.86, t + 0.2))
    tp = [(0.0, 0.86, t + 0.2), (-0.18, 1.04, t + 0.26), (-0.34, 1.02, t + 0.4), (-0.46, 0.96, t + 0.6)]
    kchain(a, "back", tp[:3], [0.3, 0.25, 0.22], [0.3, 0.25, 0.21], up=(0, 0, 1), cut=0.26)
    kchain(a, "tailR", tp[2:], [0.22, 0.19], [0.21, 0.18], up=(0, 0, 1), cut=0.26)
    d = V((-0.6, -0.06, 0.8)).normalized()
    m = _axes(V(tp[-1]), d, V((0, 0, 1)) - d * d.z)  # плоскость плавника — почти x z мира: лицом к игроку
    prof = [(-0.1, 0.13), (0.26, 0.36), (0.56, 0.48), (0.45, 0.16), (0.36, 0.0), (0.45, -0.16), (0.56, -0.48),
            (0.26, -0.36), (-0.1, -0.13)]
    a.extrude("tailR", prof, -0.055, 0.055, axis="z", matrix=m)
    a.extrude("tailO", [(0.06 + (u - 0.06) * 0.72, v * 0.68) for u, v in prof[1:-1]], -0.085, 0.085, axis="z",
              matrix=m)

    face_point(a, (0, yf, t + 0.45))
    closeup(a, (0.2, 0.0, t + 0.55))
    a.pose = {"Head": ((-6, 0, 8), (0, 0, 0)), "Tail": ((0, 0, 14), (0, 0, 0)), "BarbelL": ((0, 0, 10), (0, 0, 0)),
              "BarbelR": ((0, 0, -6), (0, 0, 0)), "EarR": ((0, 15, 0), (0, 0, 0)), "FinL": ((0, 0, 14), (0, 0, 0))}
    return a


ITEM = ("CatCatfish", cat_catfish, "Сом-котик", "Common")
