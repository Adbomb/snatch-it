"""Сом-котик (CatCatfish, Common, №11 каталога docs/BOSS6_CATALOG.md) — краснохвостый амазонский сом с кошачьими
ушками лежит в своей луже и мурлычет. Признаки вида: широкая плоская голова с округлым лбом, длинные усы-«антенны»
из уголков рта (свисают вперёд на лужу), ярко-алый хвостовой плавник, гладкое тело без чешуи, сужается к хвосту
(белая полоса только по низу боков), маленькие глазки. Эмоция — блаженство: глаза-щёлочки «^ ^», улыбка «ω»,
приподнятые румяные щёки (мурлычет). Шутка: сом ведёт себя как кот — хвост загнут набок и вверх, как у довольной
кошки. Цвета: графитово-синяя спина, белый низ, алый хвост, рыжие ушки с тёмными полосками поперёк; лужа бирюзовая
с тёмной кромкой — отдельная часть Haze (D58).
"""

