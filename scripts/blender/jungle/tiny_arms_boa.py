"""Удав-ручки (TinyArmsBoa, Common, №7 каталога docs/BOSS6_CATALOG.md) — у пухлого удава отросли две крошечные
ручки-культяпки: он лежит низкими кольцами (спираль в 1.75 витка, внутренний виток лёг на внешний), поднял голову
толстой шеей-«S» и гордо машет: одна ручка поднята и отведена в сторону («привет!»), другая — маленький «бицепс».
Признаки вида: длинное тело без ног, свёрнутое кольцами (от тонкого хвоста к толстой шее); узкая голова-клин с ямками
над губой (ряд тёмных термоямок над линией рта с обеих сторон); раздвоенный язычок; жёлтые ромбы с чёрной каймой вдоль
спины (один ряд по хребту, ряд на боку внешнего витка, на шее сзади и на макушке); светлое брюхо из поперечных щитков
(кремовые плитки на поднятой шее). Эмоция — восторг: улыбка до ушей (уголки вверх, линия рта уходит назад за глаза),
брови дугой, глаза прищурены снизу от радости, большие блики. Цвета: кораллово-красное тело, жёлтые ромбы с чёрной
каймой, кремовое брюхо; ручки — светлый коралл с кремовыми манжетами, круглый кулачок-культяпка без пальцев (не
человеческие кисти): шутка своя, не мемная «змея с руками».
Зависит от jungle_kit (creature_kit, anatomy_kit, art_style, v4_kit).
"""

import math
import os
import sys

import bmesh
from mathutils import Matrix, Vector

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from jungle_kit import *  # noqa: E402,F401,F403

BIG = 1.06  # звенья через одно толще: радиальный шов-ступень на каждом стыке, грани соседей не совпадают
EXT = 0.03  # толстое звено заходит за стык (торец тонкого прячется внутри)
RIM = 0.07  # ширина чёрной каймы ромба (тоньше — мерцает на телефоне)


def _frame(c, f, out):
    """Оси детали в точке c: z — вдоль f, y — out (наружу грани, без составляющей по f), x — поперёк."""
    f = V(f).normalized()
    u = V(out) - f * V(out).dot(f)
    u.normalize()
    x = u.cross(f)
    return Matrix(((x.x, u.x, f.x, c.x), (x.y, u.y, f.y, c.y), (x.z, u.z, f.z, c.z), (0, 0, 0, 1)))


def _path(a, key, P, W, H, up0, k0=0, e_end=0.0):
    """Тело-цепь по точкам P: восьмигранные звенья со скошенными (по биссектрисе) торцами — стыки ровные радиальные,
    без косых щелей и наплывов. Сечение W × H в точках; через одно звено в BIG раз толще и заходит за стык на EXT.
    Оси звеньев переносятся вдоль цепи без закрутки (верх — up0 у первого звена); e_end — последнее звено заходит
    за конец (в соседнюю часть). Возвращает [(f, u, k)] звеньев."""
    n = len(P)
    F = [(P[i + 1] - P[i]).normalized() for i in range(n - 1)]
    T = [F[0]] + [(F[i - 1] + F[i]).normalized() for i in range(1, n - 1)] + [F[-1]]
    segs, u = [], V(up0)
    for i in range(n - 1):
        f = F[i]
        u = u - f * u.dot(f)
        u.normalize()
        r = f.cross(u)
        big = (i + k0) % 2 == 1
        k, e = (BIG, EXT) if big else (1.0, 0.0)

        def ring(c, w, h):
            return [c + r * x + u * y for x, y in S.octagon(-w / 2, w / 2, -h / 2, h / 2, A.CUT * min(w, h))]

        def cut(ra, rb, c, tn, off):
            """Рёбра звена (от ra к rb) до плоскости стыка: боковые грани остаются плоскими (деталь выпуклая)."""
            p0 = c + tn * off
            return [qa + (qb - qa) * ((p0 - qa).dot(tn) / (qb - qa).dot(tn)) for qa, qb in zip(ra, rb)]

        ra = ring(P[i], W[i] * k, H[i] * k)
        rb = ring(P[i + 1], W[i + 1] * k, H[i + 1] * k)
        bm = bmesh.new()
        lo = [bm.verts.new(p) for p in cut(ra, rb, P[i], T[i], -e if i > 0 else 0.0)]
        hi = [bm.verts.new(p) for p in cut(ra, rb, P[i + 1], T[i + 1], e if i < n - 2 else e_end)]
        bm.faces.new(lo)
        bm.faces.new(list(reversed(hi)))
        for j in range(8):
            jj = (j + 1) % 8
            bm.faces.new((lo[j], lo[jj], hi[jj], hi[j]))
        bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
        bm.normal_update()
        a._add(bm, key, S._convex_planes(bm), None)
        segs.append((f, u.copy(), k))
    return segs


def _at(P, W, H, segs, d):
    """Точка на длине d вдоль цепи: (точка, номер звена, ширина, высота)."""
    for i in range(len(P) - 1):
        ln = (P[i + 1] - P[i]).length
        if d <= ln or i == len(P) - 2:
            q = min(d / ln, 1.0)
            return P[i].lerp(P[i + 1], q), i, W[i] + (W[i + 1] - W[i]) * q, H[i] + (H[i + 1] - H[i]) * q
        d -= ln


def _length(P):
    return sum((P[i + 1] - P[i]).length for i in range(len(P) - 1))


def _diamond(a, m, out, ly, wy):
    """Жёлтый ромб (полудиагонали ly вдоль звена, wy поперёк) в чёрной рамке шириной RIM на грани out (оси m из
    _frame): рамка и ромб стоят встык (ромб не лежит на чёрной плитке), уходят в тело на 0.05; рамка выступает на
    0.05, ромб — на 0.1 (заходит под рамку на 0.012 — щели нет, грани не совпадают)."""
    hyp = math.hypot(ly, wy) / (ly * wy)
    k, g = 1.0 + RIM * hyp, 1.0 + 0.012 * hyp  # рамка шириной RIM по нормали к стороне ромба
    a.frame("dark", [(0.0, -ly * k), (wy * k, 0.0), (0.0, ly * k), (-wy * k, 0.0)], RIM, out - 0.05, out + 0.05,
            axis="y", bevel=0, matrix=m)
    a.prism("dia", [(0.0, -ly * g), (wy * g, 0.0), (0.0, ly * g), (-wy * g, 0.0)], out - 0.065, out + 0.1, axis="y",
            bevel=0, matrix=m)


def _happy_eye(a, c, r, normal, look):
    """Глаз восторга в точке c (поверхность глазного бугра), смотрит по normal: белок, большой зрачок с крупным
    бликом (≈ 40 % зрачка), нижнее веко-«горка» цвета тела (глаз улыбается снизу) и бровь дугой (концы ниже середины)."""
    m = A._at(c, normal)
    w, hh, lift = r, r * 1.1, 0.04
    a.box("white", -w, w, -lift, A.SINK, -hh, hh, bevel=0.01, matrix=m)
    pr = w * 0.56
    px, pz = look[0] * w * 0.3, hh * 0.22
    a.box("dark", px - pr, px + pr, -lift - 0.025, -lift + 0.01, pz - pr, pz + pr, bevel=0, matrix=m)
    g = pr * 0.8
    a.box("glint", px - pr + 0.02, px - pr + 0.02 + g, -lift - 0.05, -lift - 0.02, pz + pr - 0.02 - g, pz + pr - 0.02,
          bevel=0, matrix=m)
    lid = [(-w * 1.12, -hh * 1.1), (w * 1.12, -hh * 1.1), (w * 1.12, -hh * 0.5), (0.0, -hh * 0.08),
           (-w * 1.12, -hh * 0.5)]  # верхний край — «горка»: белок над ним — дуга радости
    a.prism("boa", lid, -lift - 0.065, A.SINK * 0.5, axis="y", bevel=0, matrix=m)
    for s in S2:  # бровь пологой дугой: две половинки, внешние концы ниже, середина поднята
        mb = m @ Matrix.Translation((s * w * 0.42, 0, hh + 0.09)) @ Matrix.Rotation(math.radians(s * 16), 4, "Y")
        a.box("dark", -w * 0.5, w * 0.5, -lift - 0.035, 0.12, -0.0375, 0.0375, bevel=0, matrix=mb)


def tiny_arms_boa():
    a = new("TinyArmsBoa", {"boa": ("FF5A46", True), "arm": ("FF8070", True), "dia": ("FFD23C", False),
                            "belly": ("FFF2CF", False), "bellyD": ("F6DFA8", False)})
    t = common_stand(a, 1.5)

    # кольца: спираль 1.75 витка против часовой (сверху) от хвоста (спереди, снаружи) к шее (слева, внутри);
    # внутренний виток приподнят на 0.3 и лёг на внутреннее плечо внешнего — две ступени колец, середина закрыта
    NS = 23  # ≈ 13 звеньев на виток, швы радиальные
    P, W = [], []
    for k in range(NS + 1):
        s = k / NS
        th = math.radians(-450 + 630 * s)
        r = 1.12 - 0.82 * s ** 0.9
        w = 0.22 + 0.4 * min(s / 0.45, 1.0) ** 0.8  # хвост тонкий, к шее тело пухлое
        q = min(max((s - 0.5) / 0.3, 0.0), 1.0)
        rise = 0.3 * q * q * (3 - 2 * q)
        P.append(V((r * math.cos(th), r * math.sin(th), t + 0.006 + 0.43 * w + rise)))
        W.append(w)
    ncoil = len(P)
    # толстая шея (0.97 → 0.77 сечения колец, сужается только у головы) поднимается из внутреннего конца S-изгибом:
    # вперёд, назад, снова вперёд к голове
    for p, w in (((-0.3, -0.16, 0.68), 0.6), ((-0.3, -0.27, 0.92), 0.58), ((-0.29, -0.31, 1.3), 0.57),
                 ((-0.25, -0.2, 1.7), 0.55), ((-0.21, -0.22, 2.06), 0.52), ((-0.2, -0.36, 2.3), 0.48)):
        P.append(V((p[0], p[1], t + p[2])))
        W.append(w)
    H = [w * 0.86 for w in W]  # одно соотношение сечения: грани звеньев плоские
    part(a, "Body", "Stand", (0, 0, t + 0.3))
    segs = _path(a, "boa", P, W, H, (0, 0, 1))
    a.prism("boa", S.octagon(-0.4, 0.4, -0.4, 0.4, 0.12), t + 0.006, t + 0.66, axis="z", bevel=0)  # середина колец

    # хвост — своя часть: от начала спирали назад-влево, кончик лёг поперёк внешнего витка
    TP = [V((-0.56, -0.5, t + 0.62)), V((-0.76, -0.66, t + 0.52)), V((-0.72, -0.9, t + 0.34)),
          V((-0.4, -1.07, t + 0.17)), P[0].copy()]
    TW = [0.14, 0.16, 0.18, 0.2, W[0]]
    part(a, "Tail", "Body", tuple(P[0]))
    _path(a, "boa", TP, TW, [w * 0.86 for w in TW], (0, 0, 1), e_end=0.1)
    a.group = "Body"

    # ромбы: один ряд по хребту колец через 0.62 (по касательной, без нахлёста), кроме места под хвостом
    L = _length(P[:ncoil])
    d = 0.4
    while d < L - 0.2:
        c, i, w, h = _at(P, W, H, segs, d)
        f, u, k = segs[i]
        if (c - TP[0]).length > 0.42 and (c - TP[1]).length > 0.42:
            _diamond(a, _frame(c, f, u), h * k / 2, 0.17, 0.12)
        d += 0.62
    # ряд на внешнем боку внешнего витка (виден спереди и с телефона)
    d = 0.9
    while d < 4.6:
        c, i, w, h = _at(P, W, H, segs, d)
        f, u, k = segs[i]
        _diamond(a, _frame(c, f, f.cross(u)), w * k / 2, 0.14, 0.08)
        d += 0.62
    # шея: сзади два ромба, спереди кремовые щитки брюха — по плитке на звено, через одну светлее
    for i in range(ncoil, len(P) - 1):
        f, u, k = segs[i]
        c = (P[i] + P[i + 1]) / 2
        w, h = (W[i] + W[i + 1]) / 2 * k, (H[i] + H[i + 1]) / 2 * k
        ln = (P[i + 1] - P[i]).length
        hw = w / 2 - A.CUT * min(w, h) - 0.01
        a.box("belly" if i % 2 else "bellyD", -hw, hw, h / 2 - 0.05, h / 2 + 0.05, -ln * 0.42, ln * 0.42, bevel=0,
              matrix=_frame(c, f, -u))
        if i in (ncoil + 1, ncoil + 3):
            _diamond(a, _frame(c, f, u), h / 2, 0.12, 0.09)

    # голова — своя часть: узкий клин (затылок в 1.25 шеи, морда уже и ниже затылка) смотрит вперёд (−y)
    hx, zc = -0.2, t + 2.4
    part(a, "Head", "Body", (hx, -0.33, t + 2.28))
    a.prism("boa", S.octagon(hx - 0.3, hx + 0.3, zc - 0.24, zc + 0.28, 0.11), -0.64, -0.16, axis="y", bevel=0)
    yb, yf = -0.6, -1.04
    _path(a, "boa", [V((hx, yb, zc - 0.07)), V((hx, yf, zc - 0.07))], [0.52, 0.44], [0.44, 0.374], (0, 0, 1))
    _diamond(a, _frame(V((hx, -0.4, zc + 0.28)), (0, -1, 0), (0, 0, 1)), 0.0, 0.12, 0.085)  # ромб на макушке
    # глаза на верхних передних углах затылка, на невысоких буграх (выступ за бок головы ≤ 0.1)
    for s in S2:
        nrm = V((s * 0.5, -0.8, 0.3)).normalized()
        c = V((hx + s * 0.25, -0.66, zc + 0.1))
        ms = A._at(c, nrm)
        a.prism("boa", S.octagon(-0.17, 0.17, -0.17, 0.3, 0.06), 0.0, 0.26, axis="y", bevel=0, matrix=ms)
        _happy_eye(a, c, 0.13, nrm, (-s, 0))
    # рот: улыбка-дуга на торце морды (уголки на 0.1 выше середины), от уголков линия идёт назад вдоль челюсти и вверх
    # мимо глаз к затылку — улыбка до ушей; над ней — ряд термоямок (признак удава)
    zm = zc - 0.15
    top, bot = [], []
    for j in range(7):
        x = -0.19 + 0.38 * j / 6
        zz = zm + 0.1 * (abs(x) / 0.19) ** 2
        top.append((hx + x, zz + 0.04))
        bot.append((hx + x, zz - 0.04))
    a.extrude("mouth", top + bot[::-1], yf - 0.03, yf + 0.06, axis="y")
    for s in S2:
        taper(a, "mouth", V((hx + s * 0.2, yf + 0.01, zm + 0.1)), V((hx + s * 0.25, -0.6, zm + 0.12)), 0.1, 0.1,
              0.08, 0.08, up=(s, 0, 0), cut=0.2)
        taper(a, "mouth", V((hx + s * 0.3, -0.66, zm + 0.11)), V((hx + s * 0.3, -0.28, zm + 0.21)), 0.1, 0.1,
              0.08, 0.08, up=(s, 0, 0), cut=0.2)
        for yy in (yf + 0.09, yf + 0.21, yf + 0.33):
            xs = 0.22 + 0.04 * (yy - yf) / (yb - yf)  # бок морды сужается к носу
            zz = zm + 0.1 + 0.02 * (yy - yf) / (yb - yf) + 0.06
            a.box("dark", hx + s * (xs - 0.03), hx + s * (xs + 0.025), yy - 0.04, yy + 0.04, zz - 0.035, zz + 0.035,
                  bevel=0)
    # раздвоенный язычок из улыбки вперёд-вниз
    tg0 = V((hx, yf + 0.05, zm - 0.02))
    tg1 = V((hx, yf - 0.17, zm - 0.13))
    taper(a, "tongue", tg0, tg1, 0.12, 0.1, 0.08, 0.08, cut=0.25)
    for s in S2:
        taper(a, "tongue", tg1 + V((0, 0.03, 0)), tg1 + V((s * 0.1, -0.11, -0.05)), 0.095, 0.08, 0.08, 0.08,
              cut=0.25)

    # ручки-культяпки низко на шее (на 0.6 выше колец): одно звено светлого коралла без локтя, кремовая манжета,
    # круглый кулачок без пальцев. Левая (+x) поднята и отведена — машет «привет!» рядом с головой, правая (−x) —
    # короткий «бицепс» вбок; плечевых блоков нет
    for nm, root, dirv, ln in (("ArmL", (-0.11, -0.3, t + 1.5), (0.6, -0.25, 0.75), 0.42),
                               ("ArmR", (-0.45, -0.3, t + 1.4), (-0.85, -0.35, 0.3), 0.38)):
        root, dv = V(root), V(dirv).normalized()
        part(a, nm, "Body", tuple(root))
        tip = root + dv * ln
        taper(a, "arm", root, tip, 0.21, 0.19, 0.19, 0.17, up=(0, -1, 0), cut=0.26)
        taper(a, "belly", tip - dv * 0.1, tip - dv * 0.02, 0.25, 0.25, 0.23, 0.23, up=(0, -1, 0), cut=0.26)
        A.ball(a, "arm", tuple(tip + dv * 0.06), 0.12, n=3)

    face_point(a, (hx, yf, zc))
    closeup(a, (0.55, -0.95, t + 0.3))
    a.pose = {"Head": ((-6, 12, 12), (0, 0, 0)), "ArmL": ((0, -22, 0), (0, 0, 0)), "ArmR": ((0, 22, 0), (0, 0, 0)),
              "Tail": ((0, 25, -15), (0, 0, 0))}  # голова набок, ручка машет выше, «бицепс» поднят, хвост виляет
    return a


ITEM = ("TinyArmsBoa", tiny_arms_boa, "Удав-ручки", "Common")
