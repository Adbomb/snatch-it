"""Черепаха-улитка (SnailTurtle, Common, №4 каталога docs/BOSS6_CATALOG.md) — у черепахи вместо панциря высокая
спиральная раковина улитки (2.5 витка), а на лбу выросли две пары улиточьих рожек; глаза свои, черепашьи.
Признаки: черепаха — короткий крючковатый клюв без зубов и ноздри над ним, плоское темя с приподнятыми щитками,
морда-клин, ноги-тумбы в крупной роговой чешуе, короткий хвостик; улитка — спиральная раковина с белой полосой
и фиолетовой шишкой-макушкой, две пары рожек-щупалец на лбу. Эмоция — мечтательность: голова поднята, взгляд вверх,
мягкая улыбка и румянец. Цвета: кожа солнечно-жёлтая с оранжевыми щитками и чешуёй, клюв охристо-оранжевый (темнее
щитков), раковина розово-фиолетовая (от устья к макушке: розовый → орхидея → фиолетовый) с белой спиральной
полосой; зелёного нет.
Зависит от jungle_kit.py (creature_kit, anatomy_kit, v4_kit).
"""

