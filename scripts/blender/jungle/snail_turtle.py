SHELL_KEYS = ("shellP", "shellM", "shellV")  # от устья к макушке раковины


def _spiral(c, r0, k, turns, step, phi0=-115.0, shift=0.6):
    """Точки осевой линии раковины: логарифмическая спираль в плоскости y–z вокруг c (радиус r0 · k^виток),
    вытянута вверх на 8 %; макушка (внутренние витки) смещена к −x на shift — раковина винтовая, а не плоский диск.
    Возвращает [(точка, радиус)…] от устья к макушке."""
    out = []
    n = int(round(turns * 360 / step))
    for i in range(n + 1):
        phi = phi0 + i * step
        r = r0 * k ** ((phi - phi0) / 360.0)
        f = r / r0
        x = c.x - shift * (1.0 - f)
        out.append((V((x, c.y + r * math.cos(math.radians(phi)), c.z + 1.08 * r * math.sin(math.radians(phi)))), r))
    return out


def _scale(a, tiers, k, face, u, zc, hw, hh, out=0.07, inset=0.024):
    """Крупная роговая чешуя ноги-тумбы: приподнятая пластина со скошенными краями (усечённая пирамида) на плоской
    грани яруса k — face "R" / "L" (±x) или "F" (−y), u — центр вдоль грани (доля плоской части), zc — центр по
    высоте, hw / hh — полуширина / полувысота. Уходит в ярус на 0.03, выступает на out; верх меньше низа на inset."""
    za, zb, bx, by, wx, wy, cut = tiers[k]
    if face in ("R", "L"):
        sx = 1 if face == "R" else -1
        f = bx + sx * wx
        yc = by + u * (wy - cut - hw - 0.012)
        a.frustum("scute", (zc - hh, zc + hh, yc - hw, yc + hw),
                  (zc - hh + inset, zc + hh - inset, yc - hw + inset, yc + hw - inset), f - sx * 0.03, f + sx * out,
                  axis="x", bevel=0)
    else:
        f = by - wy
        xc = bx + u * (wx - cut - hw - 0.012)
        a.frustum("scute", (xc - hw, xc + hw, zc - hh, zc + hh),
                  (xc - hw + inset, xc + hw - inset, zc - hh + inset, zc + hh - inset), f + 0.03, f - out, axis="y",
                  bevel=0)


def _shield(a, key, x, y, z_top, rx, ry, rise):
    """Приподнятый щиток на плоском темени: восьмигранная пластина со скосом (низ шире верха), встроена на 0.04."""
    K.KEY = key
    K.taper(a, (x, y, z_top - 0.04), (x, y, z_top + rise), 2 * rx, 2 * rx - 0.05, 2 * ry, 2 * ry - 0.05,
            up=(0, -1, 0), cut=0.3)


def snail_turtle():
    a = new("SnailTurtle", {"skin": ("FFC928", True), "skinD": ("E89B1A", False), "scute": ("FF7F1E", True),
                            "beak": ("CC7A22", False), "beakD": ("A65E1C", False), "shellP": ("FF6FB4", True),
                            "shellM": ("DD62D8", True), "shellV": ("9F5BEF", True), "boss": ("8A4FE0", True),
                            "stripe": ("FFF7FC", False), "tent": ("FFDD6E", False)})
    t = common_stand(a, 1.5)

    # ── туловище: низкое жёлтое «яйцо» под раковиной (видно юбкой вокруг устья), короткие ноги-тумбы под центром масс
    part(a, "Body", "Stand", (0, 0.05, t + 0.45))
    tb = A.body(a, "skin", (0, 0.05, t + 0.24), 0.62, 0.74, 0.5, "barrel", n=3, bevel=0)  # почти скрыто раковиной
    for face, u in (("R", -0.45), ("L", 0.35)):  # оранжевые щитки на боках туловища
        plate_spot(a, "scute", tb, face, u, t + 0.49, 0.1)
    for i, (x, y) in enumerate(((0.46, -0.38), (-0.46, -0.38), (0.48, 0.46), (-0.48, 0.46))):
        s = 1 if x > 0 else -1
        nm = "Leg" + "FB"[i // 2] + "LR"[i % 2]
        side = "R" if s > 0 else "L"
        part(a, nm, "Body", (x, y, t + 0.36))
        # тумба: шире книзу, две ступени — как у слоновьей ноги
        lt = A.body(a, "skin", (x, y, t), 0.25, 0.25, 0.44, lambda u: 1.0 - 0.22 * u, n=2, corner=0.4)
        # крупная роговая чешуя кирпичной кладкой: внизу две пластины, на ярусе выше — одна со сдвигом
        z0, z1 = (lt[0][0] + lt[0][1]) / 2 + 0.02, (lt[1][0] + lt[1][1]) / 2
        for face in ((side, "F") if y < 0 else (side,)):
            _scale(a, lt, 0, face, -1.0, z0, 0.062, 0.074)
            _scale(a, lt, 0, face, 1.0, z0 + 0.006, 0.062, 0.074)
            _scale(a, lt, 1, face, 0.0, z1, 0.082, 0.074)
        for k, dx in enumerate((-0.12, 0.0, 0.12) if y < 0 else (-0.08, 0.08)):  # тупые ноготки спереди стопы
            a.box("ivory", x + dx - 0.045, x + dx + 0.045, y - 0.3 - 0.01 * (k % 2), y - 0.2, t + 0.004, t + 0.085,
                  bevel=0)

    # ── хвостик: короткий конус сзади под раковиной
    part(a, "Tail", "Body", (0, 0.74, t + 0.42))
    taper(a, "skin", (0, 0.66, t + 0.44), (0.05, 1.18, t + 0.26), 0.26, 0.08, 0.22, 0.07, cut=0.3)

    # ── раковина: трубка-спираль 2.6 витка, сечение — брусок со скосами (D39), широкая у устья и тонкая к макушке;
    # белая полоса по оси трубки видна спиралью на обоих боках, в середине — сплошная фиолетовая шишка-макушка
    part(a, "Shell", "Body", (0, 0.2, t + 0.62))
    r0, k, step = 0.84, 0.55, 55.0
    c = V((0.08, 0.28, t + 1.74))  # по x сдвинута к +x: винтовая макушка уходит к −x, центр масс — над ногами
    # плоскость спирали повёрнута на 16° к игроку: завиток с полосой виден и спереди (в игре), и в hero
    with_matrix(a, Matrix.Translation((c.x, c.y, 0)) @ Matrix.Rotation(math.radians(16), 4, "Z") @ Matrix.Translation(
        (-c.x, -c.y, 0)))
    pts = _spiral(c, r0, k, 2.6, step, shift=0.3)
    n = len(pts) - 1
    for i in range(n):
        (p0, ra), (p1, rb) = pts[i], pts[i + 1]
        w0, w1 = 0.76 * ra, 0.76 * rb  # ширина трубки больше шага витка: витки лежат друг на друге без щелей
        h0, h1 = 0.8 + 0.38 * ra / r0, 0.8 + 0.38 * rb / r0  # толщина по x: у устья толще
        K.KEY = SHELL_KEYS[min(i * 3 // n, 2)]
        e0, e1 = (w0 * 0.2 if i else 0.0), w1 * 0.2
        if i * step < 330.0:  # внешний виток (его видно сзади): лишняя ступень скругления — сечение из двух брусков
            K.taper(a, p0, p1, w0, w1, h0 * 0.84, h1 * 0.84, up=(1, 0, 0), cut=0.3, ext0=e0, ext1=e1)
            K.taper(a, p0, p1, w0 * 0.72, w1 * 0.72, h0, h1, up=(1, 0, 0), cut=0.34, ext0=e0 * 0.9, ext1=e1 * 0.9)
        else:
            K.taper(a, p0, p1, w0, w1, h0, h1, up=(1, 0, 0), cut=0.34, ext0=e0, ext1=e1)
        if i:  # белая спиральная полоса (у устья её нет): шириной ≥ 0.1, выступает из боков трубки на 0.03
            K.KEY = "stripe"
            sw0, sw1 = max(0.1 * ra / r0 + 0.06, 0.1), max(0.1 * rb / r0 + 0.06, 0.1)
            K.taper(a, p0, p1, sw0, sw1, h0 + 0.06, h1 + 0.06, up=(1, 0, 0), cut=0.3, ext0=sw0 * 0.3, ext1=sw1 * 0.3)
    # макушка: сплошная фиолетовая шишка в центре спирали (две ступени) насквозь, выступает с обоих боков
    fe = pts[-1][1] / r0
    xm, hx = c.x - 0.3 * (1.0 - fe), (0.8 + 0.38 * fe) / 2
    for rr, ex, key in ((0.19, 0.07, "shellV"), (0.11, 0.14, "boss")):
        a.prism(key, S.octagon(c.z - 1.08 * rr, c.z + 1.08 * rr, c.y - rr, c.y + rr, rr * 0.6), xm - hx - ex,
                xm + hx + ex, axis="x", bevel=0)
    with_matrix(a, None)

    # ── шея и голова черепахи: плоское темя со щитками, морда-клин сужается вперёд, короткий крючковатый клюв;
    # голова поднята к небу на 20° — мечтательно смотрит вверх
    part(a, "Head", "Body", (0, -0.6, t + 0.52))
    kchain(a, "skin", [(0, -0.42, t + 0.48), (0, -0.78, t + 0.66), (0, -0.96, t + 0.86)], [0.42, 0.38, 0.36],
           [0.38, 0.36, 0.34], up=(0, 0, 1))
    hc = V((0, -1.06, t + 1.02))
    hm = Matrix.Translation(hc) @ Matrix.Rotation(math.radians(-20), 4, "X") @ Matrix.Translation(-hc)
    with_matrix(a, hm)
    K.KEY = "skin"
    zt = hc.z + 0.36  # плоское темя
    yf = hc.y - 0.12  # лицевая грань черепа (на ней глаза)
    K.taper(a, (0, hc.y + 0.32, hc.z + 0.06), (0, yf, hc.z + 0.06), 0.72, 0.86, 0.6, 0.6, up=(0, 0, 1), cut=0.3)
    # морда-клин: из-под глаз вперёд, уже к носу; на конце — роговой клюв того же сечения (не накладка-губа)
    yb = hc.y - 0.34  # передняя грань морды: над клювом на ней ноздри
    K.taper(a, (0, hc.y - 0.02, hc.z - 0.16), (0, yb, hc.z - 0.16), 0.64, 0.5, 0.36, 0.38, up=(0, 0, 1), cut=0.22)
    # щитки на темени: крупный спереди, два поменьше сзади, приподняты на 0.05–0.06
    _shield(a, "scute", 0.0, hc.y - 0.02, zt, 0.14, 0.12, 0.06)
    for s in S2:
        _shield(a, "scute", s * 0.115, hc.y + 0.2, zt, 0.085, 0.085, 0.05)
        # щиток на виске: восьмигранная пластина на боку черепа, приподнята на 0.05
        xs = 0.398  # полуширина черепа на этой глубине (череп сужается к затылку: 0.43 → 0.36)
        K.KEY = "scute"
        K.taper(a, (s * (xs - 0.04), hc.y + 0.08, hc.z + 0.08), (s * (xs + 0.05), hc.y + 0.08, hc.z + 0.08), 0.22,
                0.17, 0.2, 0.15, up=(0, 0, 1), cut=0.3)
    # клюв без зубов: верхний — короткий клин (выступает на 0.17), у основания ~55 % ширины головы, сужается
    # и опускается к концу, по центру — острый крючок вниз на 0.1; нижний — темнее, уже и короче, заходит под верхний:
    # рот закрыт, вдоль края — тёмная линия рта
    K.KEY = "beak"
    K.taper(a, (0, yb + 0.05, hc.z - 0.14), (0, yb - 0.17, hc.z - 0.2), 0.48, 0.2, 0.22, 0.1, up=(0, 0, 1),
            cut=0.25)
    K.spike(a, (0, yb - 0.13, hc.z - 0.22), (0, yb - 0.19, hc.z - 0.35), 0.11)
    K.KEY = "beakD"
    K.taper(a, (0, yb + 0.04, hc.z - 0.29), (0, yb - 0.04, hc.z - 0.287), 0.4, 0.3, 0.1, 0.08, up=(0, 0, 1),
            cut=0.25)
    # линия рта: от крючка по краю клюва, уголки — по бокам челюсти назад и вверх (мягкая улыбка, не на щёки)
    for s in S2:
        sm = [(s * 0.07, yb - 0.06, hc.z - 0.262), (s * 0.25, yb + 0.01, hc.z - 0.258),
              (s * 0.285, hc.y - 0.24, hc.z - 0.222)]
        kchain(a, "mouth", sm, [0.042] * 3, [0.042] * 3, up=(0, 0, 1), cut=0.2, overlap=0.3)
    # ноздри: две тёмные точки на носу над клювом
    for s in S2:
        a.box("dark", s * 0.08 - 0.035, s * 0.08 + 0.035, yb - 0.012, yb + 0.03, hc.z - 0.02, hc.z + 0.022, bevel=0)
    # глаза черепахи на лицевой грани черепа, взгляд вверх, брови мягко подняты; румянец на щеках у морды
    for s in S2:
        ec = (s * 0.2, yf + 0.03, hc.z + 0.19)
        eye2(a, ec, 0.115, (s * 0.15, -1, -0.1), "calm", s, "skin", "skinD", look=(0.1 * s, 0.95), lid=0.06,
             brow_tilt=-12, brow_lift=0.45, pupil=0.5)
        a.box("blush", s * 0.36 - 0.06, s * 0.36 + 0.06, yf - 0.01, yf + 0.06, hc.z - 0.03, hc.z + 0.03, bevel=0)
    # рожки улитки на лбу: короткая пара — вперёд, над глазами (глаз на рожках нет)
    for s in S2:
        b = V((s * 0.1, hc.y - 0.02, zt - 0.06))
        tip = V((s * 0.2, hc.y - 0.3, zt + 0.16))
        taper(a, "tent", b, tip, 0.13, 0.11, cut=0.3)
        knob(a, "tent", tuple(tip), 0.075, n=1)
    with_matrix(a, None)
    # длинная пара — своими частями (качаются), растёт с темени вверх и в стороны
    for s, nm in ((1, "HornL"), (-1, "HornR")):
        b = hm @ V((s * 0.2, hc.y + 0.12, zt - 0.08))
        tip = hm @ V((s * 0.44, hc.y + 0.06, zt + 0.48))
        part(a, nm, "Head", tuple(b))
        taper(a, "tent", b, tip, 0.15, 0.115, cut=0.3)
        knob(a, "tent", tuple(tip), 0.09)

    face_point(a, tuple(hm @ V((0, hc.y - 0.4, hc.z))))
    closeup(a, (-0.3, 0.3, t + 1.7), eye_off=(-2.2, -1.2, 0.5))
    a.pose = {"Head": ((-12, 0, 16), (0, 0, 0)), "HornL": ((0, 18, -10), (0, 0, 0)), "HornR": ((10, -12, 0), (0, 0, 0)),
              "Tail": ((0, 0, 28), (0, 0, 0)), "LegFL": ((-22, 0, 0), (0, 0, 0)), "LegBR": ((16, 0, 0), (0, 0, 0)),
              "Shell": ((0, -6, 0), (0, 0, 0))}
    return a


