def _puddle(r, n=16, y=0.0):
    """Неровный скруглённый контур лужи радиуса r (выпуклый: волна контура мала)."""
    pts = []
    for i in range(n):
        th = 2 * math.pi * i / n
        k = 1 + 0.045 * math.sin(3 * th + 0.5) + 0.015 * math.cos(5 * th)
        pts.append((r * k * math.cos(th), y + r * k * math.sin(th)))
    return pts


def _seg(a, key, y, z0, z1, hw0, hd0, hw1, hd1, cut=0.3):
    """Звено тела-бочки вдоль z: сечение — восьмиугольник полуширины hw (x) и полуглубины hd (y), скосы углов."""
    taper(a, key, (0, y, z0), (0, y, z1), 2 * hw0, 2 * hw1, 2 * hd0, 2 * hd1, up=(0, -1, 0), cut=cut)


def _arc_eye(a, key, c, normal, w, h, thick=0.075):
    """Закрытый глаз блаженства — дуга «∩» в осях глаза (c, normal): три звена, середина выше краёв."""
    m = Matrix.Translation(V(c)) @ A.facing(normal)
    pts = [m @ V((-w, -0.03, -h * 0.4)), m @ V((-w * 0.4, -0.035, h * 0.45)), m @ V((w * 0.4, -0.03, h * 0.45)),
           m @ V((w, -0.035, -h * 0.4))]
    nrm = (m.to_3x3() @ V((0, -1, 0))).normalized()
    kchain(a, key, [tuple(p) for p in pts], [thick] * 4, [0.06] * 4, up=tuple(nrm), cut=0.2, overlap=0.3)


def _smile(a, c, w, h, thick=0.075):
    """Широкая сонная улыбка-дуга «U» на торце морды (c — середина, морда смотрит в −y): пять звеньев, уголки вверх."""
    x, y, z = c
    pts = [(x - w, y, z + h), (x - w * 0.6, y - 0.004, z + h * 0.1), (x, y, z - h * 0.25),
           (x + w * 0.6, y - 0.004, z + h * 0.1), (x + w, y, z + h)]
    kchain(a, "mouth", pts, [thick] * 5, [0.07] * 5, up=(0, -1, 0), cut=0.2, overlap=0.3)


def _steam(a, x, y, z, h, s, ry=0.0):
    """Струйка пара над водой — волнистая лента вверх (как значок горячего источника), не куб и не облако;
    s — в какую сторону первый изгиб, ry — разворот ленты вокруг z (градусы)."""
    m = Matrix.Translation((x, y, z)) @ Matrix.Rotation(math.radians(ry), 4, "Z")
    pts = [m @ V((s * 0.065 * math.sin(k * 3 * math.pi / 6), 0, h * k / 6)) for k in range(7)]  # полторы волны
    nrm = (m.to_3x3() @ V((0, -1, 0))).normalized()
    kchain(a, "steam", [tuple(p) for p in pts], [0.12 - 0.006 * k for k in range(7)], [0.08] * 7, up=tuple(nrm),
           cut=0.2, overlap=0.3)


def _paw(a, wrist, fwd, z):
    """Кисть лежит на воде: три пальца веером, сверху между ними — светлая перепонка (признак вида)."""
    f = V((fwd[0], fwd[1], 0)).normalized()
    wr = V((wrist[0], wrist[1], 0))
    knob(a, "fur", (wr.x, wr.y, z + 0.06), 0.12)  # запястье
    tips = []
    for i in range(3):
        d = Matrix.Rotation((i - 1) * 0.5, 3, "Z") @ f
        tip = wr + d * 0.24
        taper(a, "fur", (wr.x, wr.y, z + 0.05 + 0.008 * i), (tip.x, tip.y, z + 0.042 + 0.005 * i), 0.1, 0.085, 0.085,
              0.075, cut=0.25)  # у пальцев разная высота и наклон — грани не совпадают
        tips.append(tip)
    pts = [(wr.x - f.x * 0.04, wr.y - f.y * 0.04)] + [(wr.x + (p.x - wr.x) * 0.82, wr.y + (p.y - wr.y) * 0.82)
                                                       for p in tips]
    a.prism("web", pts, z + 0.065, z + 0.1, bevel=0)  # перепонка лежит на пальцах, кончики пальцев торчат из неё


def spa_capybara():
    a = new("SpaCapybara", {"fur": ("D27B3A", True), "furM": ("AD5828", False), "cream": ("F8DFB2", True),
                            "nose": ("4E2618", False), "nostril": ("7A3A22", False), "earIn": ("E99A7A", False),
                            "web": ("F3C08A", False),
                            "lemon": ("FFE135", True), "lemonD": ("F2C21E", False), "leaf": ("5CC94A", False),
                            "leafV": ("3C9A36", False), "water": ("2ED3C6", False), "waterM": ("74E8DD", False),
                            "waterL": ("C2FAF3", False), "waterD": ("13959C", False), "steam": ("E4FAF7", False)})
    t = common_stand(a, 1.5)
    W = t + 0.22  # уровень воды: лужа тонкая, но тело уходит под воду до груди

    # ── лужа с паром — видимая часть Haze (подставка в игре скрыта): тёмная кайма, бирюза, светлая середина
    part(a, "Haze", "Stand", (0, 0, t))
    a.prism("waterD", _puddle(1.3), t - 0.02, W - 0.04, bevel=0.02)  # тёмная кайма ниже воды
    a.prism("water", _puddle(1.18), t, W, bevel=0.02)
    a.prism("waterM", _puddle(0.86, n=12, y=0.02), W - 0.03, W + 0.012, bevel=0)  # светлая середина
    by = 0.12  # середина тела по y
    hw, hd, cut = 0.6, 0.66, 0.36  # сечение тела у воды — самая широкая полоса бочки (скос углов 0.3 × 1.2)
    a.frame("waterL", S.octagon(-hw - 0.13, hw + 0.13, by - hd - 0.13, by + hd + 0.13, cut + 0.054),
            0.17, W - 0.02, W + 0.035, axis="z", bevel=0.01)  # кольцо ряби вокруг тела (0.13 снаружи, 0.04 под телом)
    _steam(a, -0.98, 0.2, W - 0.03, 0.66, 1, ry=-25)
    _steam(a, 0.98, 0.36, W - 0.03, 0.58, -1, ry=25)

    # ── тело-бочка по грудь в воде: нижняя половина бочки под водой, над водой — самая широкая полоса и плечи,
    # скруглённые скосом к голове (не ярусы-ступени наружу)
    part(a, "Body", "Stand", (0, by, W))
    _seg(a, "fur", by, t + 0.03, W + 0.02, 0.5, 0.56, 0.595, 0.655)  # под водой
    _seg(a, "fur", by, W, W + 0.3, hw, hd, hw, hd)  # самая широкая полоса у воды
    # жёсткая шерсть ярусами: плечи — верхний слой шерсти темнее и чуть нависает над широкой полосой (кромка 0.025),
    # без шипов и чешуи
    _seg(a, "furM", by, W + 0.28, W + 0.44, 0.625, 0.685, 0.56, 0.62)  # плечи круглятся: крутой скос,
    _seg(a, "furM", by, W + 0.42, W + 0.64, 0.555, 0.615, 0.36, 0.42)  # затем пологий к шее
    # передние лапы: предплечье выходит из груди у воды и лежит на поверхности, кисть с перепонками
    for s, nm in ((1, "ArmL"), (-1, "ArmR")):
        root = V((s * 0.36, -0.3, W + 0.12))
        part(a, nm, "Body", tuple(root))
        wrist = V((s * 0.56, -0.84, W + 0.07))
        taper(a, "fur", root, wrist, 0.24, 0.2, 0.2, 0.16)
        _paw(a, wrist, (s * 0.1, -1, 0), W)

    # ── голова: длинная, тупая квадратная морда; ноздри, глаза и ушки — на одной верхней линии
    zc = W + 0.6  # голова низко над водой, подбородок почти на воде
    part(a, "Head", "Body", (0, -0.2, W + 0.36))
    # череп: затылок ниже лба — голова округло сходит к шее, а не стоит башней
    taper(a, "fur", (0, 0.08, zc - 0.03), (0, -0.4, zc), 0.86, 0.9, 0.56, 0.64, up=(0, 0, 1), cut=0.26)
    top = zc + 0.32
    # переносица — верх морды, ниже лба: на лбу место для глаз
    taper(a, "fur", (0, -0.3, zc), (0, -1.02, zc - 0.02), 0.74, 0.7, 0.26, 0.24, up=(0, 0, 1), cut=0.24)
    # кремовая морда снизу: тупая, квадратная, глубокая и длинная, чуть выступает вперёд и в стороны
    taper(a, "cream", (0, -0.34, zc - 0.2), (0, -1.06, zc - 0.21), 0.8, 0.76, 0.34, 0.3, up=(0, 0, 1), cut=0.26)
    # ноздри — две тёмные подушечки рядом у середины переднего верхнего края морды (видны и спереди, и сверху;
    # близко друг к другу — читаются носом, а не второй парой глаз)
    for s in S2:
        x0, x1 = sorted((s * 0.03, s * 0.13))
        a.prism("nostril", S.octagon(x0, x1, -1.04, -0.96, 0.02), zc + 0.05, zc + 0.11, bevel=0)
    _smile(a, (0, -1.08, zc - 0.2), 0.2, 0.07)  # широкая сонная улыбка
    for s in S2:
        n = (s * 0.25, -1, 0.1)
        # глаза закрыты дугами «∩» на лбу над переносицей — на одной линии с ноздрями и ушами
        _arc_eye(a, "nose", (s * 0.21, -0.375, zc + 0.255), n, 0.095, 0.085, thick=0.075)
        # приподнятая щёчка-румянец прямо под дугой — вровень со лбом (выступ 0.025)
        a.prism("blush", S.octagon(-0.085, 0.085, -0.04, 0.04, 0.025), -0.025, 0.03, axis="y", bevel=0,
                matrix=Matrix.Translation((s * 0.22, -0.4, zc + 0.17)) @ A.facing(n))
        # маленькие круглые ушки сверху-сзади
        e = V((s * 0.3, 0.0, top + 0.05))
        a.prism("fur", S.octagon(-0.1, 0.1, -0.09, 0.09, 0.035), -0.05, 0.05, axis="y",
                matrix=Matrix.Translation(e) @ A.facing((s * 0.3, -1, 0)))
        a.prism("earIn", S.octagon(-0.06, 0.06, -0.055, 0.055, 0.02), -0.068, -0.03, axis="y", bevel=0,
                matrix=Matrix.Translation(e) @ A.facing((s * 0.3, -1, 0)))

    # ── лимон на макушке: овальный, носик только с одного конца, на другом — черенок с листиком
    part(a, "Lemon", "Head", (0, -0.14, top))
    lc = V((0.0, -0.14, top + 0.17))
    d = V((math.cos(math.radians(16)), math.sin(math.radians(16)), 0))
    pts = [lc + d * u for u in (-0.36, -0.2, 0.0, 0.18, 0.34)]
    kchain(a, "lemon", [tuple(p) for p in pts], [0.24, 0.42, 0.48, 0.42, 0.25], [0.21, 0.37, 0.42, 0.37, 0.22],
           up=(0, 0, 1), cut=0.3, overlap=0.3)
    blunt(a, "lemonD", pts[-1] + d * 0.0, pts[-1] + d * 0.13, 0.13, 0.06)  # один носик
    taper(a, "leafV", pts[0] + d * 0.04, pts[0] - d * 0.08 + V((0, 0, 0.03)), 0.08, 0.07)  # черенок
    flat_leaf(a, "leaf", "leafV", tuple(pts[0] - d * 0.06 + V((0, 0, 0.03))),
              tuple(pts[0] - d * 0.3 + V((0, -0.05, 0.16))), 0.18, 0.07, (0.25, -0.6, 0.75))

    face_point(a, (0, -0.95, zc + 0.05))
    closeup(a, (0.0, -0.55, zc - 0.05))
    # поза: голова блаженно запрокинута и склонена набок, лимон съехал, одна лапа всплыла помахать
    a.pose = {"Head": ((-14, 0, 10), (0, 0, 0)), "Lemon": ((0, 16, 0), (0.03, 0, 0.02)),
              "ArmL": ((-38, 0, -10), (0, 0, 0)), "ArmR": ((6, 0, 0), (0, 0, 0))}
    return a


