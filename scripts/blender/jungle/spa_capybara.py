"""Капибара-спа (SpaCapybara, Common, №8 каталога docs/BOSS6_CATALOG.md) — капибара сидит по грудь в тёплой бирюзовой
луже, как в спа, с лимоном на макушке: ей так хорошо, что больше ничего не нужно.
Признаки вида: бочкообразное округлое тело без хвоста (бочка со скосами 45°, шире всего у воды, низ уходит под воду);
длинная тупая квадратная морда; ноздри, глаза и маленькие круглые ушки на одной линии сверху головы; жёсткая шерсть
ярусами (верхний слой на плечах темнее и нависает кромкой над нижним); перепонки между тремя пальцами лап (лапы лежат на воде).
Эмоция — блаженство: глаза закрыты дугами «∩» на лбу, под ними приподнятые розовые щёчки, широкая сонная улыбка.
Цвета: тёплый рыже-коричневый мех, кремовая морда, ярко-жёлтый лимон с листиком (зелёный только акцентом), бирюзовая
лужа с тёмной каймой, светлой серединой, кольцом ряби у тела и паром — отдельная видимая часть Haze (подставка в игре
скрыта, D58). Зависит от jungle_kit.py.
"""

