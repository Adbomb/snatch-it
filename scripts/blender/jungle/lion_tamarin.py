MANE_N = 11  # прядей в кольце гривы (каталог: 10–12)
MANE_BACK = 35.0  # наклон прядей назад, градусы: грива обнимает голову, сзади — пушистый шар, а не солнце
BODY_PROF = (0.92, 0.98, 0.85, 0.7, 0.55)  # тельце-груша по ярусам снизу вверх: плавное сужение без ступени-«пояса»


def _pear(t):
    """Профиль тельца: кусочно-линейно по BODY_PROF (t от 0 до 1)."""
    x = min(max(t, 0.0), 1.0) * len(BODY_PROF) - 0.5
    i = min(max(int(math.floor(x)), 0), len(BODY_PROF) - 2)
    f = min(max(x - i, 0.0), 1.0)
    return BODY_PROF[i] * (1 - f) + BODY_PROF[i + 1] * f


def _mane_dir(ang, back=MANE_BACK):
    """Направление пряди: ang в плоскости лица (0 — к +x, 90 — вверх), наклон назад (+y) на back градусов."""
    a, b = math.radians(ang), math.radians(back)
    return V((math.cos(a) * math.cos(b), math.sin(b), math.sin(a) * math.cos(b)))


def _wedge(a, key, p, f, ln, w0, w1, h0, h1, up=(0, -1, 0)):
    """Четырёхгранный клин без фаски от p по f длиной ln (сечение w × h, широкая сторона поперёк up): кончик пряди
    дешевле восьмигранного звена (12 треугольников вместо 28)."""
    f = V(f).normalized()
    u = V(up) - f * V(up).dot(f)
    u.normalize()
    r = f.cross(u).normalized()
    m = Matrix(((r.x, u.x, f.x, p.x), (r.y, u.y, f.y, p.y), (r.z, u.z, f.z, p.z), (0, 0, 0, 1)))
    a.frustum(key, (-w0 / 2, w0 / 2, -h0 / 2, h0 / 2), (-w1 / 2, w1 / 2, -h1 / 2, h1 / 2), -0.05, ln, bevel=0,
              matrix=m)


def _strand(a, key, root, d, ln):
    """Прядь-клин гривы: плоский клин (широкая сторона к лицу) от корня ~0.5 к срезанному кончику ~0.12; кончик
    загнут наружу, вниз и назад (верхние — назад, на затылок): грива ложится слоями, а не лучами-солнцем."""
    p0 = V(root)
    p1 = p0 + d * ln * 0.55
    radial = V((d.x, 0.0, d.z)).normalized() if abs(d.x) + abs(d.z) > 1e-4 else V((0, 0, 1))
    d2 = (d * 0.6 + radial * 0.15 + V((0, 0.25, -0.45))).normalized()
    taper(a, key, p0, p1, 0.5, 0.33, 0.24, 0.17, up=(0, -1, 0), cut=0.3)
    _wedge(a, key, p1, d2, ln * 0.5, 0.31, 0.12, 0.16, 0.08)


def _hand(a, wrist, s, out):
    """Кисть тамарина: ладошка и четыре длинных растопыренных пальца веером, на концах короткие светлые коготки.
    out — направление руки наружу-вверх в плоскости xz."""
    w = V(wrist)
    knob(a, "furS", tuple(w), 0.11)
    base = math.degrees(math.atan2(out[1], out[0]))
    for k in range(4):
        ang = math.radians(base + s * (-45 + 30 * k))
        d = V((math.cos(ang), -0.3, math.sin(ang))).normalized()
        ln = (0.22, 0.27, 0.27, 0.22)[k]
        p0 = w + d * 0.04
        p1 = w + d * ln + V((0, 0.006 * k, 0))  # пальцы на чуть разной глубине — грани не совпадают
        taper(a, "furD", p0, p1, 0.085, 0.075, 0.08, 0.072, up=(0, -1, 0), cut=0.25)
        spike(a, "claw", p1 - d * 0.02, p1 + d * 0.1, 0.07)  # коготок ~0.12, не зуб и не шип


def lion_tamarin():
    # ключ "gold" занят подставкой (creature_kit.stand красит его заново) — шерсть под своим ключом;
    # furS — та же шерсть без колец: на тонких лапах и хвосте кольца читаются как пластины-броня
    a = new("LionTamarin", {"fur": ("F2C14E", True), "furS": ("F2C14E", False), "furD": ("D9922C", False),
                            "furL": ("FFEBB8", False), "maneO": ("F0641E", False), "maneR": ("D8401A", False),
                            "maneB": ("E0521C", False), "skin": ("7E4F33", False), "muzzle": ("8C5A38", False),
                            "mouthD": ("2E170D", False), "throat": ("8C2A2A", False), "claw": ("F3E6CC", False)})
    t = rare_stand(a, 1.55)

    # тело: маленькая груша, плавно сужается к плечам (без широкого «таза» и ступени); светлое брюхо — овал
    part(a, "Body", "Stand", (0, 0.06, t + 0.6))
    A.body(a, "fur", (0, 0.08, t + 0.3), 0.42, 0.36, 0.8, _pear, n=4, lean=-0.1, floor=0.3,
           front=("furL", 0.7, t + 0.5, t + 0.92))

    # задние лапы по-обезьяньи: колени наружу и вперёд, два гладких звена, длинные стопы с отставленным пальцем
    for s in S2:
        nm = "Leg" + ("L" if s > 0 else "R")
        part(a, nm, "Body", (s * 0.22, 0.06, t + 0.42))
        A.limb(a, "furS", [(s * 0.22, 0.06, t + 0.44), (s * 0.5, -0.14, t + 0.34), (s * 0.4, -0.06, t + 0.1)],
               [0.19, 0.17, 0.15])
        A.foot(a, "furS", (s * 0.4, -0.06, t), (s * 0.3, -1, 0), 0.44, 0.26, toes=3, toe_key="furD", h=0.1, z=t)
        taper(a, "furD", (s * 0.33, -0.1, t + 0.045), (s * 0.18, -0.24, t + 0.04), 0.085, 0.075, 0.075, 0.07,
              cut=0.22)  # большой палец-хваталка внутрь

    # руки подняты и растопырены — «р-р-р!»: два гладких звена, пальцы веером вверх-наружу
    for s in S2:
        nm = "Arm" + ("L" if s > 0 else "R")
        part(a, nm, "Body", (s * 0.28, 0.0, t + 0.92))
        knob(a, "furS", (s * 0.3, 0.0, t + 0.92), 0.13)  # плечо входит в тело
        elbow, wrist = (s * 0.62, -0.16, t + 0.94), (s * 0.82, -0.4, t + 1.24)
        A.limb(a, "furS", [(s * 0.3, 0.0, t + 0.92), elbow, wrist], [0.15, 0.13, 0.12])
        _hand(a, wrist, s, (s * 0.5, 0.87))

    # хвост: длинный и тонкий, свисает сзади-сбоку низкой S-волной, тёмный кончик на высоте бедра загнут наружу;
    # далеко от рук (спереди и сзади между хвостом и кистью ≥ 0.3)
    part(a, "Tail", "Body", (0.06, 0.34, t + 0.45))
    tail = [(0.06, 0.34, t + 0.45), (0.3, 0.74, t + 0.24), (0.74, 0.94, t + 0.22), (1.1, 0.94, t + 0.44),
            (1.26, 0.88, t + 0.7)]
    kchain(a, "furS", tail, [0.14, 0.13, 0.125, 0.12, 0.115], up=(0, 0, 1))
    kchain(a, "furD", [(1.26, 0.88, t + 0.7), (1.36, 0.86, t + 0.96)], [0.115, 0.1], up=(0, 1, 0))

    # голова: шоколадное безволосое лицо в огненной гриве
    part(a, "Head", "Body", (0, -0.08, t + 1.05))
    hc = V((0, -0.14, t + 1.4))
    A.body(a, "skin", (hc.x, hc.y, hc.z - 0.34), 0.36, 0.31, 0.68, "ball", n=4, floor=0.5, corner=0.42)

    # грива: шар-основание за лицом и ровно 11 прядей-клиньев одним кольцом (шаг 32.7°), наклонены назад; верхние
    # три на четверть короче (грива круглая), нижние короче — не ложатся на плечи; тона чередуются
    mc = hc + V((0, 0.28, 0.0))
    A.body(a, "maneB", (mc.x, mc.y, mc.z - 0.5), 0.56, 0.4, 0.98, "ball", n=5, floor=0.55, corner=0.45)
    step = 360.0 / MANE_N
    for k in range(MANE_N):
        ang = 270.0 + step / 2 + step * k  # k = 5 — верхняя прядь, ровно вверх
        d = _mane_dir(ang)
        sz = math.sin(math.radians(ang))
        ln = 0.66 if sz < -0.5 else (0.68 if sz > 0.8 else 0.9)
        key = "maneO" if abs(k - 5) % 2 == 0 else "maneR"
        _strand(a, key, mc + d * 0.36, d, ln)

    # мордочка: узкая (~40 % ширины лица) коричневая плашка, выступает из лица не больше 0.08; носик — две тёмные
    # точки рядом над ртом (плоский нос обезьянки, не пятачок)
    mz = hc.z - 0.17
    yf = hc.y - 0.375  # перед мордочки (лицо — hc.y − 0.30)
    bell = [(-0.07, hc.z - 0.01), (0.07, hc.z - 0.01), (0.145, hc.z - 0.15), (0.145, hc.z - 0.24), (0.1, hc.z - 0.29),
            (-0.1, hc.z - 0.29), (-0.145, hc.z - 0.24), (-0.145, hc.z - 0.15)]  # колокол: узкая спинка носа вверху
    a.prism("muzzle", bell, yf, hc.y - 0.15, axis="y")
    for s in S2:
        a.box("mouthD", s * 0.034 - 0.024, s * 0.034 + 0.024, yf - 0.012, yf + 0.03, mz + 0.045, mz + 0.09, bevel=0)
    # рот «р-р-р»: маленький тёмный открытый овал без контура губ, внутри тёмно-красное горлышко
    a.prism("mouthD", S.octagon(-0.08, 0.08, mz - 0.08, mz + 0.0, 0.03), yf - 0.012, yf + 0.04, axis="y",
            bevel=0)
    a.prism("throat", S.octagon(-0.05, 0.05, mz - 0.068, mz - 0.028, 0.015), yf - 0.02, yf + 0.03, axis="y",
            bevel=0)
    # глаза: широко раскрытые, над ними нахмуренные огненные брови — грозно, но мило
    for s in S2:
        eye2(a, tuple(hc + V((s * 0.13, -0.29, 0.1))), 0.085, (s * 0.3, -1, 0.05), "angry", s, "skin", "maneO",
             pupil=0.56, lid=0.0, brow_lift=0.2)

    face_point(a, tuple(hc + V((0, -0.42, 0))))
    closeup(a, (0.0, -0.3, t + 1.2), eye_off=(-1.2, -3.0, 1.0))
    a.pose = {"Head": ((0, 10, -10), (0, 0, 0)), "ArmL": ((0, -18, 0), (0, 0, 0)), "ArmR": ((0, 18, 0), (0, 0, 0)),
              "Tail": ((0, 0, 12), (0, 0, 0))}
    return a


