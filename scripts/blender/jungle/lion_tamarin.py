"""Тамарин-лев (LionTamarin, Rare, №17 каталога docs/BOSS6_CATALOG.md) — крошечная золотая обезьянка с огненной
львиной гривой больше её самой: присела по-обезьяньи на согнутых лапах (колени наружу), подняла растопыренные
лапки с коготками и «рычит», а выходит писк.
Признаки вида: золотистая шелковистая шерсть (гладкие лапы и хвост без пластин), грива
вокруг тёмного безволосого лица, длинный тонкий хвост S-образно сбоку, длинные пальцы с коготками и стопы-хваталки,
маленькое тельце-груша. Эмоция — напускная свирепость: брови нахмурены, маленький открытый рот «р-р-р» без зубов.
Цвета: тело светлое тёплое золото (брюхо — кремовое пятно), грива глубокая красно-оранжевая (11 прядей-клиньев двух
тонов, кончики загнуты наружу и вниз), лицо шоколадное, мордочка узкая коричневая с тёмным плоским носиком (без
контура губ — модерация).
Зависит от jungle_kit.py (creature_kit, anatomy_kit, art_style, v4_kit).
"""

