def _leg(a, nm, hip, knee, ankle, toe, k, teeth=False):
    """Жучиная лапка: толстое бедро от низа тела вбок к колену, голень вниз-наружу, лапка-тарзус двумя члениками
    вдоль земли; суставы — шарики хитина; на конце — тупой коготок. teeth — у передних лапок на голени снаружи
    тупые зубцы-копалки (как у настоящего жука-носорога)."""
    part(a, nm, "Body", hip)
    hip, knee, ankle, toe = V(hip), V(knee), V(ankle), V(toe)
    A.limb(a, "chit", [hip + (hip - knee).normalized() * 0.08, knee], [0.3, 0.26], joints=False)
    knob(a, "chit", knee, 0.15)
    A.limb(a, "chit", [knee, ankle], [0.25, 0.21], joints=False)
    knob(a, "chit", ankle, 0.1)
    if teeth:
        out = V((knee.x, 0, 0)).normalized()
        for f in (0.42, 0.72):  # зубцы торчат наружу из голени
            c = knee.lerp(ankle, f)
            blunt(a, "chitL", c - out * 0.04, c + out * 0.17 + V((0, 0, 0.05)), 0.11, 0.07)
    d = (toe - ankle).normalized()
    mid = ankle.lerp(toe, 0.55) + V((0, 0, 0.004 * (k % 3)))
    taper(a, "chit", ankle, mid + d * 0.03, 0.15, 0.13, 0.14 + 0.003 * k, 0.12, cut=0.25)  # первый членик
    taper(a, "chitL", mid - d * 0.02, toe, 0.13, 0.11, 0.12, 0.1, cut=0.25)  # второй членик
    blunt(a, "chit", toe - d * 0.04, toe + d * 0.12 + V((0, 0, -0.03)), 0.1, 0.07)  # коготок


