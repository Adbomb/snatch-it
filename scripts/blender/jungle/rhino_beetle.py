"""Жук-носорог (RhinoBeetle, Epic, №24 каталога docs/BOSS6_CATALOG.md) — имя понято буквально: маленький настоящий
носорог с блестящими надкрыльями жука на спине шагает на шести суставчатых жучиных лапках.
Признаки вида: складчатая толстая кожа (тёмные складки-кольца на шее, складки на щеках и на плече); рог на носу и
маленький второй за ним; ушки-трубочки; надкрылья со швом посередине и металлическим отливом; усики-булавы.
Шутка — гибрид носорога с жуком, рог обычного размера.
Эмоция — упрямство: брови насуплены, губы надуты уголками вниз, голова опущена; роет землю передней лапкой (−x),
под лапкой — бугорок земли (часть Haze: в игре подставку прячут).
Цвета: надкрылья металлические фиолетово-синие (ступени тёмного и яркого с голубым бликом), кожа серо-сиреневая,
рог цвета слоновой кости, лапки тёмно-фиолетовые хитиновые, ушки внутри розовые.
Зависит от jungle_kit.py (creature_kit, anatomy_kit, art_style, v4_kit).
"""

