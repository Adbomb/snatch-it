def _tree(a, t, bar_z):
    """Маленькое дерево (часть Haze; правки владельца 2026-11-26 — никаких столбов и перекладин, силуэт виселицы):
    толстый чуть изогнутый ствол с корнями и корой сзади по центру, широкая круглая крона-«облако» нависает над
    крыланом (в профиль он под кроной), из-под кроны вперёд — толстая короткая ветка, за неё держатся лапки."""
    yt = 0.8  # ствол сзади крылана
    for tip in ((-0.58, yt + 0.16, t + 0.03), (0.55, yt + 0.22, t + 0.03), (0.06, yt + 0.62, t + 0.03)):
        blunt(a, "branchD", (0.0, yt, t + 0.34), tip, 0.32, 0.15)  # корни врастопырку
    # ствол изогнут: внизу шире, на середине чуть вбок, к ветке снова к центру
    pts = [(0.0, yt, t - 0.02), (0.1, yt + 0.04, t + 1.1), (0.02, yt + 0.02, t + 2.2), (-0.04, yt - 0.04, bar_z - 0.1)]
    kchain(a, "branch", pts, [0.66, 0.58, 0.52, 0.46], [0.62, 0.55, 0.5, 0.44], up=(0, -1, 0), cut=0.3, overlap=0.35)
    # кора: тёмные продольные бороздки на передней стороне ствола
    for k, (x, z0, z1) in enumerate(((-0.12, t + 0.35, t + 1.2), (0.14, t + 1.1, t + 2.0))):
        f = V(pts[1]).lerp(V(pts[2]), 0.5) if k == 1 else V(pts[0]).lerp(V(pts[1]), 0.5)
        a.box("branchD", f.x + x - 0.045, f.x + x + 0.045, yt - 0.3 - 0.005 * k, yt - 0.2, z0, z1, bevel=0)
    # толстая короткая ветка вперёд, за неё держатся лапки (у y ≈ 0)
    kchain(a, "branch", [(0.0, yt - 0.1, bar_z), (0.0, 0.3, bar_z + 0.06), (0.0, -0.24, bar_z + 0.07)],
           [0.36, 0.32, 0.28], [0.36, 0.32, 0.28], up=(0, -1, 0), cut=0.3, overlap=0.35)
    # широкая крона-«облако» нависает над крыланом: средний шар над веткой, боковые шире в стороны
    cb = bar_z + 0.16  # низ кроны выше ветки: лапки на ветке видны
    # крона — несколько круглых «облаков» разной высоты, вместе круглая шапка (правка владельца 2026-11-26):
    # самое высокое в середине, ниже по бокам и сзади, маленькое спереди над крыланом
    clouds = ((0.0, 0.25, cb + 0.0, 0.66, 0.66, 0.92), (-0.7, 0.3, cb - 0.18, 0.52, 0.56, 0.74),
              (0.68, 0.32, cb - 0.1, 0.5, 0.54, 0.8), (0.05, 0.86, cb - 0.16, 0.56, 0.42, 0.72),
              (0.25, -0.34, cb - 0.06, 0.4, 0.36, 0.6))
    for k, (x, y, z, rx, ry, h) in enumerate(clouds):
        A.body(a, "leaf", (x, y, z), rx, ry, h, "ball", n=3 if k < 3 else 2,
               keys=["leafV", "leaf", "leaf"] if k % 2 == 0 else ["leafV", "leaf", "leafV"], bevel=0)


def _panel(a, key, tiers, poly, lift, depth, inset=0.02, e=0.0, face="F"):
    """Накладка-контур на плоской грани ярусов A.body: poly — точки (x, z) для перёд ("F", −y) или (y, z) для боков
    ("L" −x / "R" +x). На каждом ярусе — срез контура полосой яруса (и плоской частью грани без скосов), вытянутый
    от грани яруса наружу на lift и внутрь на depth: накладка лежит на ступенях тела, края по высоте — ступени.
    e сдвигает срез по высоте внутрь (у соседних накладок верх и низ не совпадают)."""
    for za, zb, bx, by, wx, wy, cut in tiers:
        if face == "F":
            c, half = bx, wx - cut - inset
        else:
            c, half = by, wy - cut - inset
        p = clip_band(poly, c - half, c + half)
        if len(p) < 3:
            continue
        q = clip_band([(z, u) for u, z in p], za + 0.008 + e, zb - 0.004 - e)
        if len(q) < 3:
            continue
        q = [(u, z) for z, u in q]
        if max(u for u, _ in q) - min(u for u, _ in q) < 0.03 or max(z for _, z in q) - min(z for _, z in q) < 0.03:
            continue
        if face == "F":
            f = by - wy
            a.extrude(key, q, f - lift, f + depth, axis="y")
        else:
            sx = 1 if face == "R" else -1
            f = bx + sx * wx
            a.extrude(key, [(z, y) for y, z in q], f - sx * depth, f + sx * lift, axis="x")  # точки (z, y): ось x


def _strip(p0, p1, w0, w1=None):
    """Спица-полоса от p0 к p1 (точки на плоскости грани) шириной w0 → w1: четырёхугольник."""
    p0, p1 = V((p0[0], p0[1], 0)), V((p1[0], p1[1], 0))
    d = (p1 - p0).normalized()
    n = V((-d.y, d.x, 0))
    w1 = w0 if w1 is None else w1
    return [tuple((p0 + n * w0 / 2)[:2]), tuple((p1 + n * w1 / 2)[:2]), tuple((p1 - n * w1 / 2)[:2]),
            tuple((p0 - n * w0 / 2)[:2])]


def _flap(z0, z1, seam, depth=0.075):
    """Правое крыло, запахнутое поверх левого: справа от косого шва seam (точки (x, z) снизу вверх) с фестонами —
    вогнутыми дугами между кончиками пальцев (край перепонки), выше шва — по всей ширине до лапок."""
    edge = []
    for (xa, za), (xb, zb) in zip(seam, seam[1:]):
        d = V((xb - xa, zb - za, 0))
        n = V((d.y, -d.x, 0)).normalized()  # внутрь крыла (вправо от шва)
        for k in range(4):
            f = k / 4
            bulge = depth * math.sin(math.pi * f)
            edge.append((xa + (xb - xa) * f + n.x * bulge, za + (zb - za) * f + n.y * bulge))
    edge.append(seam[-1])
    R = 0.9
    return [(R, z0 - 0.05), (R, z1 + 0.05), (-R, z1 + 0.05), (-R, seam[-1][1])] + list(reversed(edge))


def _half_disc(cx, ztop, w, h, n=6):
    """Открытая улыбка — «D» плоской стороной вверх: верхний край ztop шириной 2w, низ — полуэллипс глубиной h."""
    return [(cx + w * math.cos(math.radians(-180 * k / n)), ztop + h * math.sin(math.radians(-180 * k / n)))
            for k in range(n + 1)]


def cocoon_fruit_bat():
    a = new("CocoonFruitBat", {"wing": ("2C1036", True), "wingF": ("6E3488", True), "wingL": ("A465C2", False), "wingM": ("C996E0", False),
                               "wingU": ("522868", False), "wingS": ("1A0822", False), "fox": ("FFC447", True), "foxD": ("EFA235", True),
                               "muzzle": ("FFEAC2", False), "patch": ("FFF4DE", False), "collar": ("F07A2A", True),
                               "furA": ("FFA23A", False), "furB": ("E2621F", False), "earD": ("4A2346", False),
                               "claw": ("F3E3C3", False), "branch": ("8F5A31", True), "branchD": ("6B4022", False),
                               "leaf": ("3FAE4A", False), "leafV": ("2C8A3A", False),
                               "fruit": ("FF9A2E", False)})
    t = common_stand(a, 1.5)

    # — дерево: видимая часть вне подставки (D58), своя часть Haze —
    part(a, "Haze", "Stand", (0, 0, t))
    t0 = t  # верх подставки: от него растёт дерево
    t -= 0.25  # крылан на 0.25 ниже — над ним помещается круглая крона (габарит ≤ 4.55)
    bar_z = t + 3.7  # ветка у лапок
    _tree(a, t0, bar_z)

    # — кокон: тело, туго завёрнутое в два крыла, висит лапками вверх (качается на лапках) —
    part(a, "Body", "Stand", (0, 0.02, bar_z))
    z0, hb = t + 2.0, 1.36
    z1 = z0 + hb
    prof = (0.9, 0.97, 1.0, 0.95, 0.85, 0.66)  # шире всего посередине, к лапкам сужается; ступени мелкие
    tb = A.body(a, "wing", (0, 0.02, z0), 0.62, 0.46, hb, lambda u: prof[min(int(u * 6), 5)], n=6)
    f0 = tb[0][3] - tb[0][5]  # перёд нижнего яруса
    # левое (нижнее) крыло видно слева от шва: две спицы веером от запястья вверх
    wr = V((0.4, z0 + 0.07, 0))
    _panel(a, "wingU", tb, _strip((-0.3, z0 + 0.07), (-0.33, z0 + 1.05), 0.12, 0.1), 0.03, 0.08, inset=0.03,
           e=0.003)
    _panel(a, "wingU", tb, _strip((-0.3, z0 + 0.07), (-0.08, z0 + 0.5), 0.12, 0.1), 0.034, 0.08, inset=0.037,
           e=0.0045)
    # правое крыло поверх: косой шов снизу от середины вверх к левому краю, фестоны между кончиками пальцев
    seam = [(0.06, z0 - 0.06), (-0.1, z0 + 0.3), (-0.25, z0 + 0.62), (-0.4, z0 + 0.94), (-0.56, z0 + 1.2)]
    _panel(a, "wingF", tb, _flap(z0, z1, seam), 0.065, 0.06)
    # тень под краем запахнутого крыла: тёмная кайма вдоль шва с фестонами — крыло лежит поверх, а не нарисовано
    _panel(a, "wingS", tb, _flap(z0, z1, [(x - 0.06, z - 0.03) for x, z in seam]), 0.045, 0.07, inset=0.026,
           e=0.0015)
    # пальцы правого крыла: веером от запястья к кончикам на шве и вверх к лапкам — сходятся у запястья, как спицы
    for i, tip in enumerate(((-0.25, z0 + 0.62), (-0.4, z0 + 0.94), (-0.06, z1 - 0.03), (0.34, z1 - 0.05))):
        _panel(a, "wingL", tb, _strip(wr[:2], tip, 0.15, 0.12), 0.095 + 0.006 * i, 0.03, inset=0.045 + 0.006 * i,
               e=0.006 + 0.0015 * i)
    # нижний край крыльев у шеи — фестоны (дуги перепонки между пальцами) свисают на воротник
    for key, xa, xb, lift in (("wing", -0.38, 0.06, 0.05), ("wingF", 0.06, 0.4, 0.072)):
        edge = []
        for k in range(2):
            u0, u1 = xa + (xb - xa) * k / 2, xa + (xb - xa) * (k + 1) / 2
            edge += [(u0 + (u1 - u0) * j / 4, z0 - 0.02 - 0.09 * math.sin(math.pi * j / 4)) for j in range(4)]
        edge.append((xb, z0 - 0.02))
        top = z0 + 0.03 + 0.004 * (lift > 0.06)  # верх фестонов заходит в нижний ярус
        a.extrude(key, [(xb, top), (xa, top)] + edge, f0 - lift, f0 + 0.12, axis="y")
    # по бокам — по пальцу от запястья назад-вверх: кокон из крыльев виден и сбоку
    for face in ("L", "R"):
        _panel(a, "wingL" if face == "R" else "wingU", tb, _strip((-0.3, z0 + 0.07), (0.25, z1 - 0.1), 0.14, 0.12),
               0.03, 0.08, inset=0.035, e=0.003, face=face)

    # задние лапки вверх, светлые пальцы с кремовыми коготками обхватывают ветку — видно, что он держится
    for s in S2:
        ank = V((s * 0.15, -0.02, t + 3.56))
        A.limb(a, "wingF", [(s * 0.13, 0.03, z1 - 0.1), tuple(ank)], [0.2, 0.17], joints=False)
        for i, dx in enumerate((-0.055, 0.055)):
            x = s * 0.15 + dx
            e = 0.006 * i
            kchain(a, "wingL", [(x, -0.05, t + 3.55), (x, -0.15 - e, bar_z + 0.04), (x, -0.04, bar_z + 0.2 + e),
                                (x, 0.12, bar_z + 0.15)], [0.11, 0.1, 0.095, 0.09], up=(1, 0, 0), cut=0.2,
                   overlap=0.3)
            spike(a, "claw", (x, 0.12, bar_z + 0.16), (x, 0.23, bar_z + 0.03), 0.1)  # коготь зацепился за ветку

    # рыжий пушистый воротник-жабо между крыльями и головой: клочья шерсти в два тона по нижнему краю
    hc = V((0, -0.08, t + 1.25))  # центр головы
    cz = hc.z + 0.46
    # низ воротника широкий (жабо выглядывает из-за головы), верх узкий — уходит под фестоны крыльев
    tc = A.body(a, "collar", (0, -0.02, cz), 0.68, 0.5, 0.36, lambda u: 1.0 if u < 0.5 else 0.7, n=2)
    za, zb, bx, by, wx, wy, cut = tc[0]
    for k, ang in enumerate((-150, -30, 90)):
        c, sn = math.cos(math.radians(ang)), math.sin(math.radians(ang))
        base = V((c * wx * 0.8, by + sn * wy * 0.8, za + 0.14 + 0.008 * (k % 3)))
        tip = V((c * (wx + 0.2), by + sn * (wy + 0.17), za - 0.12 + 0.01 * (k % 2)))
        blunt(a, "furA" if k % 2 else "furB", base, tip, 0.24, 0.11)

    # — правое крыло приоткрыто (правка владельца 2026-11-26: «не тёмный мешок»): от бока кокона в сторону-вперёд
    #    расходятся три светлых пальца-спицы, между ними натянута сиреневая перепонка с фестонами —
    part(a, "WingOpen", "Body", (0.5, 0.0, z0 + 0.9))
    hinge = Matrix.Translation((0.5, 0.0, 0.0)) @ Matrix.Rotation(math.radians(-38), 4, "Z") @ Matrix.Translation(
        (-0.5, 0.0, 0.0))
    web = [(0.48, z0 + 0.25), (0.48, z0 + 1.2), (0.86, z0 + 1.28), (1.22, z0 + 1.05), (1.2, z0 + 0.78),
           (1.05, z0 + 0.72), (1.12, z0 + 0.46), (0.92, z0 + 0.4), (0.86, z0 + 0.16), (0.66, z0 + 0.2)]
    a.extrude("wingM", web, -0.05, 0.05, axis="y", matrix=hinge)
    for tip in ((1.22, z0 + 1.05), (1.12, z0 + 0.46), (0.86, z0 + 0.16)):
        bar(a, "wingL", hinge @ V((0.5, -0.07, z0 + 1.15)), hinge @ V((tip[0], -0.07, tip[1])), 0.08)

    # — запястья: короткий сливовый большой палец с кремовым коготком-крючком у нижнего края крыла —
    for s, nm in ((1, "ThumbR"), (-1, "ThumbL")):
        wr3 = V((s * 0.43, -0.42, z0 + 0.08))
        part(a, nm, "Body", tuple(wr3))
        knob(a, "wing", tuple(wr3), 0.11)
        tip = wr3 + V((s * 0.1, -0.13, -0.2))
        taper(a, "wing", wr3, tip, 0.13, 0.1, cut=0.25)
        spike(a, "claw", tip + V((0, 0.02, 0.01)), tip + V((s * 0.02, -0.12, 0.04)), 0.08)  # крючок вперёд

    # — голова макушкой вниз: лисья голова строится «как стоит» и переворачивается вокруг центра (180° по y) —
    hm = Matrix.Translation(hc) @ Matrix.Rotation(math.pi, 4, "Y") @ Matrix.Translation(-hc)
    part(a, "Head", "Body", (0, -0.06, hc.z + 0.55))
    with_matrix(a, hm)
    hprof = (0.9, 1.0, 0.95, 0.72)  # широкие щёки, узкое темя с ушами
    th = A.body(a, "fox", (hc.x, hc.y, hc.z - 0.52), 0.64, 0.46, 1.04, lambda u: hprof[min(int(u * 4), 3)], n=4,
                keys=["fox", "fox", "fox", "foxD"])
    f1 = th[1][3] - th[1][5]  # перёд яруса со щеками и носом
    f2 = th[2][3] - th[2][5]  # перёд яруса с глазами
    # длинный лисий нос в две ступени: кремовая морда, чёрная мочка
    A.snout(a, "muzzle", (0, f1, hc.z - 0.15), (0, -1, -0.05), 0.62, 0.32, 0.21, 0.24, 0.17, nose_key="dark",
            nose=0.8, mouth=0)
    # широкая открытая улыбка («D» плоской стороной к носу), внутри — розовый язычок вровень
    # (вся улыбка — на ярусе подбородка: на стыке ярусов она бы распалась на две полосы)
    _panel(a, "mouth", th, _half_disc(0, hc.z - 0.272, 0.23, 0.2), 0.025, 0.06)
    _panel(a, "tongue", th, _half_disc(0, hc.z - 0.37, 0.13, 0.09), 0.034, 0.05, e=0.003)
    # глаза-полумесяцы на светлых пятнах, с ресничкой во внешнем уголке; румянец ниже — обрамляет глаза
    ez = hc.z + 0.14
    for s in S2:
        ex = s * 0.3
        _panel(a, "patch", th, S.octagon(ex - 0.17, ex + 0.17, ez - 0.12, ez + 0.12, 0.06), 0.03, 0.06)
        # глаза открыты: хитрый прищур (веко наполовину, взгляд вбок) — «хихиканье» (правка владельца 2026-11-26)
        eye2(a, (ex, f2 + 0.02, ez - 0.02), 0.13, (s * 0.12, -1, 0.0), "sly", s, "patch", "earD", look=(0.45, -0.1),
             pupil=0.5)
        _panel(a, "blush", th, S.octagon(s * 0.4 - 0.08, s * 0.4 + 0.08, hc.z - 0.15, hc.z - 0.06, 0.03), 0.028,
               0.05)
    # острые уши торчком (у висящего — вниз), развёрнуты в стороны; тёмные снаружи, розовые внутри
    for s, nm in ((1, "EarR"), (-1, "EarL")):
        eb = V((s * 0.28, hc.y + 0.02, hc.z + 0.36))
        part(a, nm, "Head", tuple(hm @ eb))
        et = V((s * 0.66, hc.y + 0.06, hc.z + 0.9))
        taper(a, "earD", eb, et, 0.36, 0.06, 0.14, 0.06, up=(0, -1, 0), cut=0.25)
        d = (et - eb).normalized()
        taper(a, "pink", eb + d * 0.1 + V((0, -0.05, 0)), et - d * 0.13 + V((0, -0.04, 0)), 0.2, 0.04, 0.06,
              0.035, up=(0, -1, 0), cut=0.25)
    with_matrix(a, None)

    face_point(a, (0, -0.6, hc.z))
