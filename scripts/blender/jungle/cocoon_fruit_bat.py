"""Крылан-кокон (CocoonFruitBat, Common, №10 каталога docs/BOSS6_CATALOG.md) — летучая лисица висит вниз головой
на кривой ветке из коряги и так туго завернулась в крылья, что стала коконом: наружу торчит только перевёрнутая лисья мордочка.
Признаки вида: лисья морда (длинный нос в две ступени, острые уши), рыжий пушистый воротник-жабо из клочьев шерсти,
два кожистых крыла внахлёст: правое запахнуто поверх левого по косому шву с фестонами между пальцами, светлые
пальцы-спицы веером от запястья (как у сложенного зонтика), на запястье — короткий большой палец с коготком-крючком;
висит вниз головой на толстых задних лапках, вцепившись когтями в ветку. Голова строится «как стоит»
и переворачивается на 180°: нос вверху, уши внизу.
Эмоция — хихиканье: открытые глаза с хитрым прищуром на светлых пятнах, румянец, широкая открытая улыбка с язычком
(без зубов), ушки торчком.
Цвета: голова золотая, морда и пятна у глаз кремовые, воротник рыжий в два тона, крылья тёмно-сливовые, спицы
светлее; дерево (ствол, ветка, круглая крона) — коричневое с зелёной кроной, — отдельная видимая часть Haze (D58: в игре подставка скрыта), зелёный — только два
листика на ветке.
"""

