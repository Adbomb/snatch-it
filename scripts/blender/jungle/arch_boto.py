"""Дельфин-арка (ArchBoto, Rare, №14 каталога docs/BOSS6_CATALOG.md) — розовый амазонский дельфин (бото) такой
длинный, что ныряет и выныривает одновременно: одно сплошное тело волной — хвост-лопасть торчит над левой лужей,
тело ныряет в неё, выныривает высокой дугой-мостом над подставкой, ныряет в правую лужу и выныривает уже головой.
Признаки вида: розовая кожа; длинный узкий клюв-рострум; высокий круглый лоб-«дыня» ступенью над клювом; низкий
длинный гребень на спине вместо спинного плавника; широкие ласты-вёсла; дыхало на макушке. Эмоция — заливистый смех:
голова запрокинута, клюв приоткрыт улыбкой (без зубов, язык виден), глаза зажмурены «^ ^», брови подняты, щёки-бугры.
Цвета: розовый «бабл-гам», светло-розовое брюхо полосой снизу, гребень темнее; лужи бирюзовые — отдельная часть Haze
(D58: подставка в игре скрыта).
Зависит от jungle_kit (creature_kit, anatomy_kit, art_style, v4_kit).
"""

