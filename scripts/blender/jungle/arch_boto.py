STEP = 0.035  # ступень колец тела по радиусу: нижний конец каждого кольца шире верхнего — полки смотрят вверх
EXT = 0.07  # широкий конец кольца заходит на соседнее (стык под полкой, на изгибе без щели)


def _ring(a, key, p0, p1, w0, w1, h0, h1, wide_low=True):
    """Кольцо тела D39 от p0 к p1 (сечение w — в плоскости волны, h — по y): нижний по z конец шире на 2·STEP и
    выступает за стык на EXT, верхний — без выступа (уходит под полку соседа)."""
    p0, p1 = V(p0), V(p1)
    low0 = p0.z <= p1.z
    d0 = 2 * STEP if (low0 and wide_low) else 0.0
    d1 = 2 * STEP if (not low0 and wide_low) else 0.0
    K.KEY = key
    K.taper(a, p0, p1, w0 + d0, w1 + d1, h0 + d0, h1 + d1, up=(0, -1, 0), cut=A.CUT,
            ext0=EXT if d0 else 0.0, ext1=EXT if d1 else 0.0)


def _side(p0, p1):
    """Сторона брюха для звена p0 → p1 (от хвоста к голове): поворот направления на −90° в плоскости xz."""
    d = (V(p1) - V(p0)).normalized()
    return V((d.z, 0.0, -d.x))


def _tube(a, key, belly_key, pts, ws, belly=True, crest=()):
    """Сплошное тело-трубка из колец по точкам pts (от хвоста к голове) и светлая полоса брюха по нижней стороне,
    теми же кольцами (выступает на 0.025, по y — 0.6 тела). crest — номера точек-вершин волны: на них кольцо-пояс
    шире соседей (оба соседних кольца сужаются к вершине)."""
    P = [V(p) for p in pts]
    for i in range(len(P) - 1):
        w0, w1 = ws[i], ws[i + 1]
        _ring(a, key, P[i], P[i + 1], w0, w1, w0 * 1.04, w1 * 1.04)
        if belly:
            n = _side(P[i], P[i + 1])
            low0 = P[i].z <= P[i + 1].z
            bw = 0.14
            o0 = (w0 + (2 * STEP if low0 else 0)) / 2 - bw / 2 + 0.025
            o1 = (w1 + (0 if low0 else 2 * STEP)) / 2 - bw / 2 + 0.025
            K.KEY = belly_key
            K.taper(a, P[i] + n * o0, P[i + 1] + n * o1, bw, bw, (w0 + (2 * STEP if low0 else 0)) * 0.6,
                    (w1 + (0 if low0 else 2 * STEP)) * 0.6, up=(0, -1, 0), cut=0.3,
                    ext0=EXT if low0 else 0.0, ext1=0.0 if low0 else EXT)
    for k in crest:  # пояс на вершине волны: короткое кольцо шире обоих соседей
        d = (P[k + 1] - P[k - 1]).normalized()
        w = ws[k] + 2 * STEP + 0.02
        K.KEY = key
        K.taper(a, P[k] - d * 0.13, P[k] + d * 0.13, w, w, w * 1.04, w * 1.04, up=(0, -1, 0), cut=A.CUT)
        if belly:
            n = V((d.z, 0.0, -d.x))
            K.KEY = belly_key
            K.taper(a, P[k] - d * 0.115 + n * (w / 2 - 0.045), P[k] + d * 0.115 + n * (w / 2 - 0.045), 0.14, 0.14,
                    w * 0.62, w * 0.62, up=(0, -1, 0), cut=0.3)


def arch_boto():
    a = new("ArchBoto", {"boto": ("FF7EB9", True), "botoL": ("FFD3E6", False), "botoD": ("D44589", False),
                         "water": ("2CCFC4", True), "waterL": ("A4F3EC", False), "cheek": ("FF4F86", False),
                         "mouthIn": ("FFA8C8", False), "mouth": ("7A1E46", False),
                         "melon": ("FF9CCB", True)})
    t = rare_stand(a, 1.55)
    y0 = 0.06  # тело чуть дальше середины: голова и клюв — к игроку

    # ── осевая линия тела волной (x, z над подставкой), от лопасти к голове: хвост → нырок в лужу A → дуга-мост
    #    (полуэллипс) → нырок в лужу B → шея и голова. Низ каждого нырка — под водой (вода до t + 0.07), видна
    #    сплошная «U» над рябью: одно тело ныряет и тут же выныривает
    tail = [(-1.25, 0.74), (-1.22, 0.46), (-1.12, 0.2), (-0.93, 0.04)]
    arch = [(-0.93, 0.04)] + [(-0.06 + 0.68 * math.cos(math.radians(th)), 0.22 + 0.98 * math.sin(math.radians(th)))
                              for th in (180, 154, 128, 104, 90, 76, 52, 26, 0)] + [(0.81, 0.04)]
    neck = [(0.81, 0.04), (0.98, 0.2), (1.04, 0.52), (1.03, 0.86), (1.0, 1.1)]
    P = lambda xz: V((xz[0], y0, t + xz[1]))  # noqa: E731

    # ── лужи — видимая часть Haze: два бирюзовых восьмиугольника у нырков и кольца ряби вокруг тела
    part(a, "Haze", "Stand", (0, 0, t))
    a.prism("water", S.octagon(-1.5, -0.38, -0.44, 0.56, 0.3), t - 0.01, t + 0.07, bevel=0)
    a.prism("water", S.octagon(0.26, 1.38, -0.5, 0.56, 0.3), t - 0.012, t + 0.068, bevel=0)
    for k, (cx, rx, ry) in enumerate(((-0.93, 0.48, 0.34), (0.81, 0.48, 0.34))):
        a.frame("waterL", S.octagon(cx - rx, cx + rx, y0 - ry, y0 + ry, ry * 0.5), 0.075, t + 0.03,
                t + 0.1 + 0.012 * k, axis="z", bevel=0)

    # ── дуга-мост: кольца от нырка A до нырка B, светлое брюхо снизу, на вершине — пояс
    part(a, "Body", "Stand", (-0.06, y0, t + 0.5))
    aw = [0.4, 0.42, 0.45, 0.47, 0.48, 0.48, 0.48, 0.47, 0.46, 0.46, 0.46]
    _tube(a, "boto", "botoL", [P(p) for p in arch], aw, crest=(5,))
    # низкий длинный гребень вместо спинного плавника — узкая тёмная полоса по верху дуги
    rpts = []
    for th in (124, 107, 90, 73, 56):
        r = math.radians(th)
        c = P((-0.06 + 0.68 * math.cos(r), 0.22 + 0.98 * math.sin(r)))
        n = V((0.98 * math.cos(r), 0.0, 0.68 * math.sin(r))).normalized()
        rpts.append(c + n * (0.27 if th in (124, 56) else 0.3))
    kchain(a, "botoD", rpts, [0.12, 0.14, 0.15, 0.14, 0.12], [0.12, 0.13, 0.14, 0.13, 0.12], up=(0, -1, 0), cut=0.3,
           overlap=0.3)

    # ── хвост: из лужи A выныривает хвостовой стебель и широкая лопасть с вырезом (ныряющий хвост)
    part(a, "Tail", "Body", tuple(P((-0.95, 0.1))))
    _tube(a, "boto", "botoL", [P(p) for p in tail], [0.2, 0.26, 0.32, 0.4])
    fx, fz = -1.26, t + 0.78
    fl = [(-0.1, -0.08), (0.1, -0.08), (0.36, 0.06), (0.4, 0.24), (0.2, 0.22), (0.0, 0.12), (-0.2, 0.22),
          (-0.4, 0.24), (-0.36, 0.06)]
    a.extrude("boto", [(fx + x, fz + z) for x, z in fl], y0 - 0.06, y0 + 0.06, axis="y")
    a.extrude("botoD", [(fx + x * 0.72, fz + 0.03 + z * 0.72) for x, z in fl], y0 - 0.085, y0 + 0.085, axis="y")

    # ── из лужи B выныривает перед тела: шея со светлым горлом наружу (+x) и ласты-вёсла
    part(a, "Front", "Body", tuple(P((0.84, 0.1))))
    _tube(a, "boto", "botoL", [P(p) for p in neck], [0.46, 0.46, 0.45, 0.43, 0.41])
    for nm, s in (("FlipperL", -1), ("FlipperR", 1)):
        root = P((1.06, 0.56)) + V((0, s * 0.13, 0))
        tip = root + V((0.38, s * 0.2, -0.24))  # наружу, вниз на ~30° и в сторону; лопасть плашмя к игроку
        part(a, nm, "Front", tuple(root))
        K.KEY = "boto"
        K.taper(a, root, tip, 0.2, 0.32, 0.12, 0.08, up=(0, s, 0), cut=0.3, ext0=0.12)  # один цельный ласт

    # ── голова (правка владельца 2026-11-26: «не голова дракона»): смотрит на игрока и чуть вправо, не запрокинута;
    #    над узким клювом — большой круглый лоб-«дыня», понятные круглые глаза, широкая улыбка вдоль клюва
    hc = P((1.0, 1.36))
    part(a, "Head", "Front", tuple(P((1.0, 1.1))))
    hm = Matrix.Translation(hc) @ Matrix.Rotation(math.radians(40), 4, "Z") @ Matrix.Rotation(math.radians(-6), 4,
                                                                                              "X")
    with_matrix(a, hm)
    A.body(a, "boto", (0, 0.08, -0.36), 0.34, 0.4, 0.74, "ball", n=4, floor=0.55, corner=0.5)  # свод головы
    # лоб-«дыня»: круглая розовая выпуклость впереди над клювом — выпирает вперёд, не вверх
    A.body(a, "melon", (0, -0.26, -0.2), 0.27, 0.22, 0.4, "ball", n=3, floor=0.55, corner=0.5)
    taper(a, "boto", (0, -0.32, -0.16), (0, -0.72, -0.16), 0.2, 0.16, 0.15, 0.13, cut=0.26)  # рострум, две ступени
    taper(a, "boto", (0, -0.7, -0.16), (0, -1.0, -0.15), 0.15, 0.115, 0.125, 0.1, cut=0.26)
    a.box("botoD", -0.07, 0.07, 0.1, 0.2, 0.36, 0.41, bevel=0)  # дыхало на макушке
    for s in S2:
        knob(a, "cheek", (s * 0.27, -0.2, -0.22), 0.075)  # румянец под глазом
        # широкая улыбка: тёмная дуга вдоль клюва, уголки подняты к щекам
        kchain(a, "mouth", [(s * 0.07, -0.86, -0.215), (s * 0.13, -0.5, -0.235), (s * 0.24, -0.26, -0.17),
                            (s * 0.29, -0.2, -0.08)], [0.05] * 4, [0.05] * 4, up=(0, 0, 1), cut=0.2, overlap=0.3)
        # круглые глаза: белок, зрачок к игроку, блик; мягко поднятая бровь
        eye2(a, (s * 0.28, -0.2, 0.02), 0.13, (s * 0.8, -1, 0.05), "calm", s, "boto", "botoD", look=(-0.2 * s, 0.1),
             pupil=0.55)
    with_matrix(a, None)

    # ── нижняя челюсть приоткрыта на ~24°, кончик загнут вверх улыбкой; зубов нет, язык виден
    part(a, "Jaw", "Head", tuple(hm @ V((0, -0.3, -0.24))))
    with_matrix(a, hm)
    taper(a, "boto", (0, -0.3, -0.27), (0, -0.7, -0.29), 0.18, 0.14, 0.1, 0.09, cut=0.26)  # подклювье
    taper(a, "boto", (0, -0.68, -0.285), (0, -0.94, -0.25), 0.14, 0.11, 0.09, 0.08, cut=0.26)
    with_matrix(a, None)

    eye_w = hm @ V((-0.3, -0.12, 0.0))
    face_point(a, tuple(eye_w))
    tgt = hm @ V((0.0, -0.4, -0.1))
    n_w = (hm.to_3x3() @ V((-0.3, -1, 0.15))).normalized()
    FACE_CAM["ArchBoto"] = (tuple(tgt + n_w * 2.9 + V((0, 0, 0.5))), tuple(tgt))  # лицо: глаз, «дыня», улыбка
    closeup(a, tuple(P((-0.3, 0.7))), eye_off=(-0.4, -2.4, 0.6))
    a.pose = {"Head": ((-8, 0, 6), (0, 0, 0)), "Jaw": ((4, 0, 0), (0, 0, 0)), "FlipperL": ((28, 0, 0), (0, 0, 0)),
              "Tail": ((0, 14, 0), (0, 0, 0)), "Front": ((0, -5, 0), (0, 0, 0))}
    return a


