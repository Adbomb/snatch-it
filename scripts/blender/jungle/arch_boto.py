"""Дельфин-арка (ArchBoto, Rare, №14 каталога docs/BOSS6_CATALOG.md) — розовый амазонский дельфин (бото) такой
длинный, что ныряет и выныривает одновременно: хвост-лопасть торчит над левой лужей, тело ныряет в неё, выныривает
высокой дугой над подставкой, и передний конец дуги — уже голова: клюв смотрит вперёд-вниз к правой луже, дельфин
ныряет обратно. Шеи нет (правка владельца 2026-11-26: вертикальная шея читалась как утка).
Признаки вида: розовая кожа; длинный тонкий клюв-рострум с тёмным кончиком; круглый светлый лоб-«дыня», плавно
переходящий в клюв; низкий длинный гребень на спине вместо спинного плавника; широкие ласты-вёсла; дыхало на макушке.
Эмоция — радость: крупные глаза по бокам у основания клюва (белок, чёрный зрачок), линия рта изогнута улыбкой, румянец.
Цвета: розовый «бабл-гам», светло-розовое брюхо и «дыня», гребень и кончик клюва темнее; лужи бирюзовые — отдельная
часть Haze (D58: подставка в игре скрыта).
Зависит от jungle_kit (creature_kit, anatomy_kit, art_style, v4_kit).
"""

