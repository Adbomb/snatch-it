"""Угорь-молния (LightningEel, Legendary, №30 каталога docs/BOSS6_CATALOG.md) — электрический угорь сам себя
щекотнул током: тело выгнулось жёстким вертикальным зигзагом-молнией из 4 звеньев (изгиб вбок, как при плавании),
весь зигзаг чуть наклонён вперёд и светится голубой каймой по краям, угорь стоит на кончике хвоста во всплеске; вдоль боков тела бегут светящиеся
разряды-пилы с плоскими белыми искрами-звёздочками.
Признаки вида: длинное гладкое тело без чешуи и без спинного плавника; плавник-лента вдоль всего брюха (сплошная, с
косыми стыками в изгибах); широкая округлая голова с широким ртом; маленькие глазки; светлое брюхо.
Эмоция — изумлённый смех «ой, щекотно!»: маленькие круглые глазки с зрачками по центру, высокие брови-дуги,
рот раскрыт в улыбке (без зубов) с языком, румянец.
Цвета: спина тёмно-индиговая, бока индиговые, голова на ступень светлее, брови почти чёрные, брюхо оранжевое,
плавник-лента светло-персиковый; разряды неоново-голубые с белыми искрами (светятся, не жёлтые); всплеск бирюзовый —
отдельная часть Haze (D58), подставка в игре скрыта.
Тело — слои-пластины по контуру молнии (ступени D39): широкий бок, уже и толще — брюхо спереди и спина сзади;
шея-клин расширяется к голове, голова продолжает линию тела.
Зависит от jungle_kit (creature_kit, anatomy_kit, art_style, v4_kit).
"""

