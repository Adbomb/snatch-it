def _perp(d):
    """Левая нормаль направления d = (x, z) в плоскости x–z."""
    return V((-d.y, d.x))


def _outline(pts, hws, f=1.0, limit=2.2):
    """Контур ломаной pts [(x, z)…] с полуширинами hws (×f): левый край вперёд, правый назад; в изгибах — острый
    скос (как у знака молнии), не длиннее limit полуширин."""
    P = [V(p) for p in pts]
    n = len(P)
    side = {1: [], -1: []}
    for i in range(n):
        if i == 0:
            m, k = _perp((P[1] - P[0]).normalized()), 1.0
        elif i == n - 1:
            m, k = _perp((P[i] - P[i - 1]).normalized()), 1.0
        else:
            n1 = _perp((P[i] - P[i - 1]).normalized())
            n2 = _perp((P[i + 1] - P[i]).normalized())
            m = (n1 + n2).normalized()
            k = min(1.0 / max(m.dot(n1), 1e-3), limit)
        for s in (1, -1):
            side[s].append(P[i] + m * (s * hws[i] * f * k))
    return side[1], side[-1]


def _strip(a, key, pts, hws, y0, y1, f=1.0):
    """Полоса по ломаной (x, z) с косыми стыками в изломах, вытянутая по y от y0 до y1: одна цельная деталь."""
    left, right = _outline(pts, hws, f)
    poly = [(p.x, p.y) for p in left] + [(p.x, p.y) for p in reversed(right)]
    a.extrude(key, poly, y0, y1, axis="y")


def _slabs(a, pts, hws, layers):
    """Тело-молния: на каждый слой (цвет, доля ширины, y0, y1) — контур ломаной, вытянутый по y. Концы слоёв
    чуть разной длины — торцы слоёв не в одной плоскости."""
    for j, (key, f, y0, y1) in enumerate(layers):
        P = [V(p) for p in pts]
        P[0] = P[0] - (P[1] - P[0]).normalized() * 0.015 * j
        P[-1] = P[-1] + (P[-1] - P[-2]).normalized() * 0.015 * j
        _strip(a, key, P, hws, y0, y1, f)


def _lm(p0, p1, y=0.0):
    """Оси звена от p0 к p1 (точки (x, z)): x — вдоль звена, y — мировая y, z — левая нормаль; начало в p0."""
    d = (V(p1) - V(p0)).normalized()
    return Matrix(((d.x, 0, -d.y, p0[0]), (0, 1, 0, y), (d.y, 0, d.x, p0[1]), (0, 0, 0, 1)))


_CREST = [0]


def _fin(a, pts, hw=0.05, dy=0.0, gap=0.2):
    """Плавник-лента вдоль всего брюха (к −y): сплошная основа по всей ломаной с косыми стыками в изгибах (лента не
    рассыпается на кубики) и волнистый гребень из трапеций на каждом звене — только вдали от изгибов (gap)."""
    _strip(a, "fin", pts, [hw] * len(pts), -0.42 - dy, -0.29 - dy)
    for i in range(len(pts) - 1):
        p0, p1 = V(pts[i]), V(pts[i + 1])
        ln = (p1 - p0).length
        u0, u1 = gap, ln - gap
        if u1 - u0 < 0.25:
            continue
        m = _lm(p0, p1)
        nw = max(round((u1 - u0) / 0.38), 1)
        for j in range(nw):  # гребни волны — трапеции: сбоку лента волнистая, а не гребёнка
            u, h = u0 + (j + 0.5) * (u1 - u0) / nw, (u1 - u0) / nw / 2
            yb = -0.3 - dy + 0.006 * (_CREST[0] % 3)  # у соседних гребней основание на разной глубине
            _CREST[0] += 1
            a.prism("finD", [(u - h * 0.85, yb), (u + h * 0.85, yb), (u + h * 0.3, -0.53 - dy),
                             (u - h * 0.3, -0.53 - dy)], -hw - 0.008, hw + 0.008, bevel=0, matrix=m)


def _star(a, c, y0, y1, r=0.22, ri=0.08, turn=45.0):
    """Плоская белая искра-звёздочка о четырёх лучах в плоскости x–z (к игроку), лучи повёрнуты на turn."""
    pts = []
    for k in range(8):
        ang = math.radians(turn + 45 * k)
        rr = r if k % 2 == 0 else ri
        pts.append((c.x + rr * math.cos(ang), c.y + rr * math.sin(ang)))
    a.extrude("neonSpark", pts, y0, y1, axis="y")


def _bolt(a, p0, p1, h0, h1, s, u0, u1, peaks, k=0):
    """Разряд вдоль бока звена p0→p1 (точки (x, z)) с полуширинами тела h0→h1, сторона s (+1 — левая нормаль):
    пила-зигзаг лежит у края тела — нижние вершины уходят в бок на 0.06, верхние отходят на 0.17; концы разряда
    в теле (свободных концов нет). На вершинах пилы — плоские искры-звёздочки."""
    p0, p1 = V(p0), V(p1)
    d = (p1 - p0).normalized()
    nl = _perp(d) * s
    nv = 2 * peaks + 1
    pts, tops = [], []
    for j in range(nv):
        u = u0 + (u1 - u0) * j / (nv - 1)
        hw = h0 + (h1 - h0) * u
        off = hw + (0.17 if j % 2 else -0.06)
        q = p0.lerp(p1, u) + nl * off
        pts.append(q)
        if j % 2:
            tops.append(q)
    y0 = -0.27 + 0.01 * (k % 3)  # спереди почти вровень с брюхом — тело их не заслоняет; глубина у всех разная
    _strip(a, "neonBolt", pts, [0.05] * nv, y0, y0 + 0.14)
    for q in tops:
        _star(a, q + nl * 0.02, y0 - 0.06, y0 + 0.03, turn=45 + 8 * k)


def lightning_eel():
    a = new("LightningEel", {"back": ("1A1752", True), "flank": ("2A2782", True), "head": ("3D39AC", True),
                             "brow": ("1C1A4A", False), "belly": ("FF8A1F", True), "fin": ("FFC98A", False),
                             "finD": ("FFB066", False), "cheek": ("FF6F91", False), "water": ("2CCFC4", True),
                             "waterL": ("A4F3EC", False), "neonBolt": ("3DD6FF", False),
                             "neonSpark": ("FFFFFF", False), "neonEdge": ("5EE8FF", False)})
    glow(a)
    t = legendary_stand(a, 1.75)

    # ── всплеск — видимая часть Haze (подставка в игре скрыта): бирюзовая лужа, кольцо ряби, корона брызг вокруг
    #    кончика хвоста
    tx = 0.05
    part(a, "Haze", "Stand", (0, 0, t))
    a.prism("water", S.octagon(tx - 1.05, tx + 1.05, -0.95, 0.95, 0.4), t - 0.01, t + 0.07, bevel=0)
    a.frame("waterL", S.octagon(tx - 0.72, tx + 0.72, -0.66, 0.66, 0.28), 0.09, t + 0.03, t + 0.11, axis="z", bevel=0)
    for k in range(8):
        ang = math.radians(22.5 + 45 * k)
        dv = V((math.cos(ang), math.sin(ang), 0))
        h = 0.3 + 0.14 * (k % 2)
        c = V((tx, 0, t + 0.04)) + dv * 0.34
        blunt(a, "waterL" if k % 2 else "water", c, c + dv * 0.2 + V((0, 0, h)), 0.16, 0.07)

    # ── весь угорь наклонён вперёд (к −y) на 7° вокруг кончика хвоста: сбоку не ровный столб
    lean = tilt((tx, 0, t), "X", 7)

    def L(p):
        return tuple(lean @ V(p))

    with_matrix(a, lean)

    # ── хребет молнии: кончик хвоста во всплеске → 4 звена зигзагом → шея внутри головы
    sp = [(tx, t + 0.0), (0.72, t + 0.9), (-0.74, t + 1.62), (0.6, t + 2.45), (0.0, t + 3.0), (0.0, t + 3.32)]
    hw = [0.09, 0.19, 0.26, 0.3, 0.32, 0.32]
    # светящаяся кромка (правка владельца 2026-11-26: «тело-зигзаг светится»): неоновый слой чуть шире тела,
    # тонкий по глубине — по обоим краям молнии от хвоста до шеи горит голубая кайма
    LAY = [("flank", 1.0, -0.17, 0.17), ("flank", 0.84, -0.25, 0.25), ("belly", 0.58, -0.32, -0.05),
           ("back", 0.62, 0.05, 0.32), ("neonEdge", 1.16, -0.07, 0.07)]
    part(a, "Body", "Stand", L((tx, 0, t + 0.02)))
    _slabs(a, sp[1:], hw[1:], LAY)
    _fin(a, sp[1:5])
    # шея-клин: от тела расширяется к голове (на 0.2 шире тела), голова продолжает линию тела, а не сидит шапкой
    a.frustum("flank", (-0.3, 0.3, -0.27, 0.27), (-0.43, 0.43, -0.4, 0.33), t + 2.84, t + 3.08, bevel=0)
    a.frustum("belly", (-0.2, 0.2, -0.33, -0.1), (-0.3, 0.3, -0.47, -0.2), t + 2.86, t + 3.06, bevel=0)
    # хвост — своя часть: первое звено от всплеска до первого изгиба и заход во второе звено
    part(a, "Tail", "Body", L((0.72, 0, t + 0.9)))
    P1, P2 = V(sp[1]), V(sp[2])
    tail = [sp[0], sp[1], tuple(P1 + (P2 - P1) * 0.18)]
    th = [hw[0], hw[1] * 1.05, hw[1] * 1.08]
    _slabs(a, tail, th, [(k, f, y0 - 0.012, y1 + 0.012) for k, f, y0, y1 in LAY])
    _fin(a, [tuple(V(sp[0]) + V((0.12, 0.15))), sp[1], tuple(P1 + (P2 - P1) * 0.14)], hw=0.056, dy=0.008)

    # ── разряды вдоль боков: по одному на звено, на верхнем боку (камера сверху — брюхо их не заслоняет); пила у края
    #    тела, искры на её вершинах
    _bolt(a, sp[0], sp[1], th[0], th[1], 1, 0.3, 0.8, 1, k=0)
    part(a, "Body", "Stand", L((tx, 0, t + 0.02)))
    _bolt(a, sp[1], sp[2], hw[1], hw[2], -1, 0.22, 0.78, 2, k=1)
    _bolt(a, sp[2], sp[3], hw[2], hw[3], 1, 0.22, 0.78, 2, k=2)
    _bolt(a, sp[3], sp[4], hw[3], hw[4], -1, 0.2, 0.8, 1, k=3)

    # ── грудные плавнички на шее за головой: маленькие, машут от щекотки
    nz = t + 2.97
    for s, nm in ((1, "FinL"), (-1, "FinR")):
        root = (s * 0.33, 0.0, nz)
        part(a, nm, "Body", L(root))
        A.flipper(a, "fin", root, (s * 0.82, -0.1, nz + 0.12), 0.22, 0.34, thick=0.14, up=(0, -1, 0.2), segments=2)

    # ── голова (правка владельца 2026-11-26: «округлая и широкая, не плоский ящик»): широкий ступенчатый шар —
    # снизу светлый подбородок (продолжение брюха), сверху тёмная макушка (продолжение спины)
    part(a, "Head", "Body", L((0, 0, t + 3.05)))
    hz, hy = t + 3.36, -0.12  # середина головы
    th = A.body(a, "head", (0, hy, hz - 0.46), 0.66, 0.5, 0.94, "ball", n=4,
                keys=["belly", "head", "head", "flank"])
    for s in S2:
        ex, ez = s * 0.27, hz + 0.12
        yf = front_y(th, ex, ez)
        # глазок: маленький круглый, зрачок по центру чуть выше — изумление
        a.prism("white", S.octagon(ex - 0.09, ex + 0.09, ez - 0.095, ez + 0.095, 0.034), yf - 0.045, yf + 0.06,
                axis="y", bevel=0)
        a.box("dark", ex - 0.042, ex + 0.042, yf - 0.07, yf - 0.035, ez - 0.025, ez + 0.06, bevel=0)
        a.box("glint", ex - 0.03, ex - 0.005, yf - 0.085, yf - 0.065, ez + 0.025, ez + 0.05, bevel=0)
        # бровь-дуга высоко над глазом — «ой!»
        yb = front_y(th, s * 0.25, hz + 0.29)
        _strip(a, "brow", [(s * 0.13, hz + 0.27), (s * 0.26, hz + 0.32), (s * 0.4, hz + 0.28)], [0.03] * 3,
               yb - 0.04, yb + 0.06)
        yc = front_y(th, s * 0.47, hz - 0.08)
        a.box("cheek", s * 0.47 - 0.075, s * 0.47 + 0.075, yc - 0.035, yc + 0.03, hz - 0.13, hz - 0.03, bevel=0)
    # рот: широкая открытая улыбка «D» во всю ширину морды, без зубов; язык внизу
    ym = front_y(th, 0, hz - 0.1)
    mouth = [(-0.38, -0.02), (0.38, -0.02), (0.32, -0.11), (0.17, -0.19), (0.0, -0.21), (-0.17, -0.19), (-0.32, -0.11)]
    a.prism("mouth", [(x, hz + z) for x, z in mouth], ym - 0.03, ym + 0.08, axis="y", bevel=0)
    a.prism("tongue", [(x * 0.5, hz + z - 0.005) for x, z in mouth[2:]], ym - 0.04, ym + 0.07, axis="y", bevel=0)
    yf = ym
    with_matrix(a, None)

    face_point(a, L((0, yf, hz + 0.08)))
    closeup(a, L((0.0, -0.3, t + 1.6)), eye_off=(-0.9, -2.4, 0.8))
    a.pose = {"Body": ((0, -5, 0), (0, 0, 0)), "Head": ((-10, 12, 10), (0, 0, 0)),
              "FinL": ((0, -45, 0), (0, 0, 0)), "FinR": ((0, 40, 0), (0, 0, 0)), "Tail": ((0, 4, 0), (0, 0, 0))}
    return a


