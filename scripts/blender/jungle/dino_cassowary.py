"""Казуар-динозавр (DinoCassowary, Epic, №26 каталога docs/BOSS6_CATALOG.md) — птица забыла, что уже не динозавр:
стоит в позе ящера (тело почти горизонтально, повёрнуто к игроку боком на 35°, голова повёрнута к игроку), сзади —
толстый чешуйчатый хвост ящера, задранный над спиной и загнутый вбок; по хребту от кончика хвоста до шеи — крупные
ступенчатые оранжевые пластины (стегозавр); под телом — мощные лапы динозавра: толстая «окорочок»-голень и жёлтая
цевка. Крыльев нет.
Признаки вида: роговой шлем растёт со лба и отклонён назад; голая ярко-синяя шея (короткая, не длиннее головы);
две красные серёжки-капли разной длины на горле под клювом; косматое, как шерсть, оперение (крупные пряди свисают
вниз ярусами); трёхпалые лапы с толстыми пальцами.
Эмоция — подозрительность: один глаз широко открыт и косится зрачком в сторону игрока, второй прищурен в щёлку под
насупленной бровью, клюв поджат (складки уголков вниз).
Цвета: лицо и шея ярко-синие, серёжки красные, шлем оранжево-золотой, перья тёмно-сливовые (яркость ≤ 30 %), хвост
индиго со светлыми каймами чешуи (не сливается с сиреневой подставкой), пластины оранжевые, лапы жёлтые.
Зависит от jungle_kit (creature_kit, anatomy_kit, v4_kit, art_style).
"""

import math
import os
import sys

from mathutils import Matrix, Vector

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from jungle_kit import *  # noqa: E402,F401,F403

YAW_DEG = 35.0  # тело повёрнуто: голова к +x, хвост к −x — профиль ящера виден спереди, в hero и на телефоне
TURN = -43.0  # голова повёрнута обратно к игроку (итог −8°: косится чуть к камере героя и к игроку)
FTH = ("fth", "fthD", "fthL")  # пряди оперения: три оттенка сливового
BODY_AX = 80.0  # ось тела от вертикали: перёд приподнят всего на 10° — поза ящера, не стоячая фигура
BODY_LEN = 1.55
BODY_RX, BODY_RZ = 0.62, 0.5


def _body_at(t, tt):
    """Точка оси тела (доля tt от зада к груди) и полуширина / полувысота яруса там (профиль яйца)."""
    ang = math.radians(BODY_AX)
    d = V((0, -math.sin(ang), math.cos(ang)))
    c = V((0, 0.8, t + 1.42)) + d * BODY_LEN * tt
    r = max(A.PROFILES["egg"](tt), 0.35)
    return c, BODY_RX * r, BODY_RZ * r


def _strand(a, k, base, tip, w0, w1, out, th=0.15):
    """Прядь «шерсти»: широкая плоская лопасть свисает вниз (толщина — по нормали out), тупой край снизу."""
    taper(a, FTH[k % 3], base, tip, w0, w1, th, th * 0.8, up=out, cut=0.3)


def _plate(a, c, f, h, ln):
    """Ступенчатая пластина хребта: оранжевая пластина (толщина 0.13) и золотая середина толще и ниже (ступень).
    c — середина основания на хребте, f — направление хребта к хвосту; основание уходит в тело на 0.12."""
    f = V(f).normalized()
    side = f.cross(V((0, 0, 1))).normalized()
    up = side.cross(f).normalized()
    m = Matrix(((side.x, f.x, up.x, c.x), (side.y, f.y, up.y, c.y), (side.z, f.z, up.z, c.z), (0, 0, 0, 1)))
    yz = [(-ln / 2, -0.12), (ln / 2, -0.12), (ln / 2, h * 0.5), (ln * 0.3, h), (-ln * 0.12, h), (-ln / 2, h * 0.42)]
    a.extrude("crestT", [(z, y) for y, z in yz], -0.065, 0.065, axis="x", matrix=m)
    a.extrude("crestL", [(-0.1 + (z + 0.12) * 0.6, y * 0.62) for y, z in yz], -0.095, 0.095, axis="x", matrix=m)


def _brow(a, c, normal, w, up, tilt, thick=0.075):
    """Бровь-брусок толщиной 0.075 (тонкая на телефоне мерцает): выступает из лица на 0.035, уходит в голову на 0.2 —
    вровень с лицом, не висит в профиль."""
    m = Matrix.Translation(V(c)) @ A.facing(normal) @ Matrix.Translation((0, 0, up)) @ Matrix.Rotation(
        math.radians(tilt), 4, "Y")
    a.box("dark", -w, w, -0.035, 0.2, -thick / 2, thick / 2, bevel=0, matrix=m)


def _toes(a, ankle, fwd, t):
    """Стопа казуара: три толстых пальца веером вперёд из пятки, на концах — тупые светлые ногти."""
    f = V((fwd[0], fwd[1], 0)).normalized()
    an = V(ankle)
    for i, ang in enumerate((-0.5, 0.0, 0.5)):
        d = Matrix.Rotation(ang, 3, "Z") @ f
        ln = 0.48 if i == 1 else 0.38
        tip = an + d * ln
        z0 = t + 0.1 + 0.006 * i  # у пальцев разная высота — нижние грани не совпадают
        taper(a, "leg", (an.x, an.y, z0 + 0.01), (tip.x, tip.y, z0), 0.22, 0.17, 0.19, 0.15, cut=0.24)
        blunt(a, "nail", (tip.x - d.x * 0.05, tip.y - d.y * 0.05, z0 - 0.012),
              (tip.x + d.x * 0.11, tip.y + d.y * 0.11, z0 - 0.05), 0.14, 0.085)


def _leg(a, nm, s, t, W):
    """Лапа динозавра: колено спрятано в бахроме перьев, ниже — толстая янтарная голень-окорочок назад к пятке,
    оттуда толстая (0.38) жёлтая цевка к стопе. Стопа под серединой тела."""
    hip = V((s * 0.34, 0.16, t + 1.34))
    knee = V((s * 0.4, -0.08, t + 1.02))
    heel = V((s * 0.42, 0.3, t + 0.5))
    ank = V((s * 0.41, 0.12, t + 0.15))
    part(a, nm, "Stand", W(hip))
    A.limb(a, "thigh", [tuple(hip), tuple(knee), tuple(heel)], [0.42, 0.54, 0.34], joints=False)  # окорочок
    knob(a, "thigh", tuple(knee), 0.28, n=3)
    knob(a, "leg", tuple(heel), 0.22, n=2)
    A.limb(a, "leg", [tuple(heel), tuple(ank)], [0.38, 0.34], joints=False)  # цевка
    _toes(a, (ank.x, ank.y - 0.02, ank.z), (s * 0.1, -1, 0), t)


def dino_cassowary():
    a = new("DinoCassowary", {"fth": ("4A1E4C", True), "fthD": ("35143A", False), "fthL": ("52295A", False),
                              "face": ("1E8BFF", True), "neck": ("1773F0", True), "neckD": ("0F56C0", False),
                              "wattle": ("E8283C", True), "casque": ("FF8A1C", True), "casqueG": ("FFC21C", False),
                              "beak": ("3B3752", True), "tail": ("3F46C4", True), "tailL": ("6E78EA", False),
                              "crestT": ("FF7A1A", True), "crestL": ("FFB51F", False), "thigh": ("F2A11C", True),
                              "leg": ("FFD43A", True), "nail": ("F3E9D2", False)})
    t = epic_stand(a, 1.7)
    yaw = Matrix.Translation((0.4, -0.02, 0)) @ Matrix.Rotation(math.radians(YAW_DEG), 4, "Z")

    def W(p):
        return tuple(yaw @ V(p))

    with_matrix(a, yaw)

    # ── лапы (на подставке): стоят под серединой тела ──
    for s in S2:
        with_matrix(a, yaw)
        _leg(a, "LegL" if s > 0 else "LegR", s, t, W)

    # ── тело: почти горизонтальное яйцо (толстый зад к хвосту), косматые пряди свисают вниз ярусами ──
    with_matrix(a, yaw)
    part(a, "Body", "Stand", W((0, 0.1, t + 1.5)))
    ang = math.radians(BODY_AX)
    mb = Matrix.Translation((0, 0.8, t + 1.42)) @ Matrix.Rotation(ang, 4, "X")
    A.body(a, "fth", (0, 0, 0), BODY_RX, BODY_RZ, BODY_LEN, "egg", n=6, matrix=mb)
    k = 0
    for tt in (0.24, 0.5, 0.76):  # верхний ярус — накидка: пряди от спины вниз по бокам
        c, wx, wz = _body_at(t, tt)
        for s in S2:
            base = c + V((s * wx * 0.6, 0, wz * 0.72))
            tip = c + V((s * (wx + 0.08), 0.05, -wz * 0.28))
            _strand(a, k, base, tip, 0.46, 0.32, (s, 0, 0))
            k += 1
    for tt in (0.36, 0.63):  # нижний ярус — бахрома ниже брюха
        c, wx, wz = _body_at(t, tt)
        for s in S2:
            base = c + V((s * wx * 0.88, 0, -wz * 0.05))
            tip = c + V((s * (wx + 0.1), 0.05, -wz - 0.2))
            _strand(a, k, base, tip, 0.42, 0.28, (s, 0, 0))
            k += 1
    c, wx, wz = _body_at(t, 0.1)  # косматый зад: пряди свисают по бокам корня хвоста
    for s in S2:
        base = c + V((s * 0.4, 0, wz * 0.55))
        _strand(a, k, base, base + V((s * 0.16, 0.12, -0.58)), 0.36, 0.24, (s, 0.4, 0))
        k += 1

    # пластины хребта на спине — до основания шеи (по Body: зад, середина, перёд)
    for tt, h in ((0.2, 0.44), (0.45, 0.47), (0.7, 0.4), (0.9, 0.3)):
        c, wx, wz = _body_at(t, tt)
        ang_d = V((0, math.sin(ang), -math.cos(ang)))  # хребет к хвосту
        _plate(a, c + V((0, 0, wz * 0.93)), ang_d, h, 0.4 if tt < 0.85 else 0.32)

    # ── хвост ящера: толстый корень (0.88 ≈ высота тела), задран на ~20° над спиной и загнут вбок (−x);
    # чешуя — светлые кольца-каймы на стыках звеньев, звенья заходят друг в друга, как черепица ──
    part(a, "Tail", "Body", W((0, 0.55, t + 1.58)))
    tp = [V(p) for p in ((0, 0.4, t + 1.52), (0, 0.92, t + 1.67), (-0.06, 1.36, t + 1.84), (-0.2, 1.76, t + 2.02),
                         (-0.4, 2.08, t + 2.18), (-0.62, 2.3, t + 2.3))]
    ws = [0.88, 0.78, 0.64, 0.5, 0.36, 0.2]
    hs = [0.8, 0.7, 0.58, 0.46, 0.33, 0.19]
    n = len(tp) - 1
    for i in range(n):
        d = (tp[i + 1] - tp[i]).normalized()
        taper(a, "tail", tp[i] - d * (0.04 if i else 0.0), tp[i + 1], ws[i] * 0.92, ws[i + 1] * 1.04,
              hs[i] * 0.92, hs[i + 1] * 1.04, cut=0.28)
        if i < n - 1:  # кайма чешуи: светлое кольцо 0.18 вдоль хвоста, шире звена — ступень видна с телефона
            taper(a, "tailL", tp[i + 1] - d * 0.17, tp[i + 1] + d * 0.015, ws[i + 1] * 1.12, ws[i + 1] * 1.1,
                  hs[i + 1] * 1.12, hs[i + 1] * 1.1, cut=0.28)
    # пластины хребта на хвосте: от корня к кончику ниже
    for i, h in enumerate((0.42, 0.36, 0.3, 0.24, 0.17)):
        c = tp[i].lerp(tp[i + 1], 0.5)
        f = tp[i + 1] - tp[i]
        top = c + V((0, 0, (hs[i] + hs[i + 1]) / 4 * 0.96))
        _plate(a, top, f, h, min(0.42, f.length * 0.8))
    # ── шея и голова казуара ──
    part(a, "Head", "Body", W((0, -0.62, t + 1.86)))
    # голая синяя шея — короткая (≈ 0.45, не длиннее головы), у корня — воротник прядей
    kchain(a, "neck", [(0, -0.5, t + 1.74), (0, -0.78, t + 1.99), (0, -0.92, t + 2.2)], [0.44, 0.4, 0.36],
           up=(0, -1, 0))
    for j, ang_c in enumerate((205, 250, 290, 335)):  # воротник: пряди свисают вокруг корня шеи
        ph = math.radians(ang_c)
        nrm = V((math.cos(ph), math.sin(ph), 0))
        base = V((0, -0.6, t + 1.92)) + nrm * 0.2
        _strand(a, j + 1, base, base + nrm * 0.12 + V((0, 0.04, -0.38)), 0.3, 0.2, tuple(nrm), th=0.13)
    hc = V((0, -1.0, t + 2.36))
    hm = Matrix.Translation(hc) @ Matrix.Rotation(math.radians(TURN), 4, "Z") @ Matrix.Translation(-hc)
    HM = yaw @ hm
    with_matrix(a, HM)
    # голова: боковой профиль (плоское лицо спереди, круглый затылок), снаружи — ступень уже
    hp = [(-0.32, -0.24), (-0.32, 0.29), (-0.22, 0.36), (0.06, 0.37), (0.26, 0.27), (0.33, 0.02), (0.26, -0.22),
          (0.08, -0.33), (-0.24, -0.27)]
    layered(a, "face", [(hc.y + y, hc.z + z) for y, z in hp], [(0.3, 1, 1), (0.37, 0.86, 0.86)], (hc.y, hc.z))
    fy = hc.y - 0.32  # плоскость лица
    # роговой шлем растёт со лба (перёд — сразу за бровями), отклонён назад на ~12°, ниже прежнего на ~25 %;
    # золотая середина, оранжевые бока ступенью
    cp = [(-0.25, 0.12), (-0.28, 0.34), (-0.2, 0.56), (-0.06, 0.72), (0.08, 0.77), (0.2, 0.7), (0.26, 0.5), (0.26, 0.3),
          (0.14, 0.12)]
    prof = [(hc.y + y, hc.z + z) for y, z in cp]
    layered(a, "casqueG", prof, [(0.09, 1, 1)], (hc.y, hc.z + 0.2))
    layered(a, "casque", prof, [(0.16, 0.86, 0.84)], (hc.y, hc.z + 0.2))
    # клюв: от середины лица ниже глаз вперёд и вниз на ~30°, верхний край дугой, длина ≈ 0.5; спереди — клин:
    # у основания ширина 0.3, к кончику сужается ступенями до 0.1 (не висит «хоботом»)
    bz = hc.z - 0.18
    bp = [(0.06, 0.08), (-0.06, 0.08), (-0.22, 0.04), (-0.36, -0.04), (-0.46, -0.16), (-0.5, -0.27), (-0.43, -0.25),
          (-0.3, -0.17), (-0.15, -0.12), (0.06, -0.12)]
    layered(a, "beak", [(fy + y, bz + z) for y, z in bp], [(0.05, 1, 1), (0.1, 0.72, 0.84), (0.15, 0.42, 0.7)],
            (fy + 0.06, bz - 0.02))
    for s in S2:  # клюв поджат: складки уголков вниз
        bar(a, "neckD", (s * 0.17, fy + 0.0, bz - 0.04), (s * 0.23, fy + 0.02, bz - 0.13), 0.07, 0.07, bevel=0)
    # лицо подозрительное: левый глаз (−x, к игроку) широко открыт и косится зрачком вбок, бровь поднята;
    # правый (+x) прищурен в щёлку, бровь насуплена
    wide = dict(lid=0.12, lid_tilt=-4, look=(-0.85, 0.05))
    squint = dict(lid=0.62, lid_tilt=10, look=(-0.6, -0.4))
    for x, nrm, mood, kw, up, tilt in ((-0.165, (-0.1, -1, 0.03), "sly", wide, 0.2, -14),
                                       (0.165, (0.1, -1, 0.03), "angry", squint, 0.17, -24)):
        c = (x, fy + 0.005, hc.z + 0.06)
        eye2(a, c, 0.12, nrm, mood, 1 if x > 0 else -1, "face", "dark", show_brow=False, **kw)
        _brow(a, c, nrm, 0.15, up, tilt)

    # ── серёжки: две красные капли разной длины (0.35 и 0.45) свисают с горла под клювом ──
    part(a, "Wattles", "Head", tuple(HM @ V((0, fy + 0.12, hc.z - 0.27))))  # ось внутри головы
    with_matrix(a, HM)
    # общий корень серёжек на горле — вокруг оси сустава нет пустоты (сгиб не раскрывается)
    knob(a, "wattle", (0, fy + 0.1, hc.z - 0.27), 0.13, n=3)
    for s, ln in ((1, 0.35), (-1, 0.45)):
        top = V((s * 0.075, fy + 0.1, hc.z - 0.26))
        bot = V((s * 0.095, fy + 0.05, hc.z - 0.3 - ln + 0.1))
        taper(a, "wattle", top, bot, 0.1, 0.15, 0.1, 0.15, cut=0.3)
        knob(a, "wattle", (bot.x, bot.y, bot.z - 0.03), 0.1, n=3)
    with_matrix(a, None)

    f = HM @ V((0, fy, hc.z))
    face_point(a, tuple(f))
    FACE_CAM["DinoCassowary"] = (tuple(f + V((-1.5, -4.4, 0.8))), tuple(f + V((-0.05, 0.0, 0.2))))
    closeup(a, W((-0.55, 0.1, t + 1.5)), eye_off=(-2.0, -1.4, 0.6))
    a.pose = {"Head": ((8, 0, -14), (0, 0, 0)), "Wattles": ((20, 0, 0), (0, 0, 0)), "Tail": ((6, 0, 20), (0, 0, 0)),
              "LegR": ((-22, 0, 0), (0, -0.04, 0.1))}
    return a


