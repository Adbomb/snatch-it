def _gaster(t):
    """Профиль брюшка вдоль оси назад: у стебелька уже, в середине широкое, к концу ступенями сходит до ≈ 60 % —
    сзади круглое брюшко, а не ящик."""
    return max(0.3, math.sin(math.pi * (0.15 + 0.75 * t)) ** 0.6)


def _leaf_half(a, ml, s, u0, u1, wmax, sag, n=6, veins=(0.24, 0.42, 0.6)):
    """Половина листа (как leaf_half набора, s = ±1 — сторона от главной жилки) в осях ml: три ступени (тёмный край,
    средний слой с кольцами D39, светлая середина) повёрнуты вокруг жилки вниз на sag°. Боковые жилки — свои:
    от главной жилки до 85 % ширины, ступенями по слоям листа (на каждом слое утоплены на 0.02, толщина 0.09),
    без обрубков и без выхода за край."""
    hw = leaf_outline(u0, u1, n=n, wmax=wmax)[1]
    mh = ml @ Matrix.Rotation(math.radians(-s * sag), 4, "X")
    uc = (u0 + u1) / 2
    edge = [(u0 + (u1 - u0) * i / n, s * hw(i / n)) for i in range(n + 1)]

    def poly(ku, kw):
        pts = [(uc + (u - uc) * ku, w * kw) for u, w in edge]
        return pts + [(uc + (u1 - uc) * ku, -s * 0.05), (uc + (u0 - uc) * ku, -s * 0.05)]

    a.extrude("leafE", poly(1.0, 1.0), -0.06, 0.02, axis="z", matrix=mh)
    a.extrude("leaf", poly(0.92, 0.86), 0.0, 0.07, axis="z", matrix=mh)
    a.extrude("leafL", poly(0.72, 0.6), 0.05, 0.12, axis="z", matrix=mh)

    def inside(p, ku, kw):  # точка (u, w) внутри контура слоя (контур сжат к середине: ku вдоль, kw поперёк)
        f = (uc + (p.x - uc) / ku - u0) / (u1 - u0)
        return 0.0 < f < 1.0 and abs(p.y) < kw * hw(f)

    def leave(p0, p1, ku, kw):  # где отрезок p0 → p1 выходит из контура слоя (доля 0…1)
        lo, hi = 0.0, 1.0
        if inside(p1, ku, kw):
            return 1.0
        for _ in range(24):
            mid = (lo + hi) / 2
            lo, hi = (mid, hi) if inside(p0.lerp(p1, mid), ku, kw) else (lo, mid)
        return lo

    with_matrix(a, mh)
    ang = math.radians(38)
    for f0 in veins:  # ёлочкой к кончику
        p0 = V((u0 + (u1 - u0) * f0, s * 0.03))
        far = p0 + V((math.cos(ang), s * math.sin(ang))) * 3.0
        pe = p0.lerp(far, leave(p0, far, 1.0, 0.85))
        tl, tm = leave(p0, pe, 0.72, 0.6), leave(p0, pe, 0.92, 0.86)
        for ta, tb, zc in ((0.0, tl, 0.127), (max(tl - 0.06, 0.0), tm, 0.073), (max(tm - 0.06, 0.0), 1.0, 0.022)):
            if tb - ta > 0.04:
                pa, pb = p0.lerp(pe, ta), p0.lerp(pe, tb)
                bar(a, "leafV", (pa.x, pa.y, zc), (pb.x, pb.y, zc), 0.09, 0.05, bevel=0)
    with_matrix(a, None)


def ant_strongman():
    """Муравей собран в своих осях и уменьшен матрицей sm в SC раз вокруг середины подставки; голова — ещё крупнее
    (HS) вокруг шеи: на телефоне читается лицо. Лист — в мире: огромный, поднят над головой почти горизонтально, его
    середина (место хвата) — над центром масс муравья."""
    a = new("AntStrongman", {"ant": ("EE5527", True), "antD": ("B8331F", False), "antM": ("F2B13E", False),
                             "leafE": ("3E9A45", False), "leaf": ("6CCB42", True), "leafL": ("98DE5C", True),
                             "leafV": ("2F7A36", False), "sweat": ("5FE3FF", False)})
    t = epic_stand(a, 1.7)
    SC, DZ, HS = 0.58, -0.32, 1.3  # масштаб муравья, присед (тело ниже на DZ), увеличение головы
    sm = Matrix.Translation((0, 0, t)) @ Matrix.Scale(SC, 4) @ Matrix.Translation((0, 0, DZ - t))
    neck = V((0, -0.06, t + 1.25))
    hm = sm @ Matrix.Translation(neck) @ Matrix.Scale(HS, 4) @ Matrix.Translation(-neck)

    def q(p, m=sm):
        return tuple(m @ V(p))

    # ── лист: огромный, как гриф штанги над головой; сначала он (в мире), потом руки — кулаки под главной жилкой ──
    u0, u1, wmax, sag, tilt_x, roll = -1.52, 1.78, 0.95, 6, 15, -6
    UG, GRIP = -0.04, 0.34  # середина хвата на жилке (≈ 45 % длины листа) и полуширина хвата (шире плеч)
    rot = Matrix.Rotation(math.radians(roll), 4, "Y") @ Matrix.Rotation(math.radians(tilt_x), 4, "X")
    ml = Matrix.Translation(V((-0.03, 0.06, t + 1.8)) - rot @ V((UG, 0, 0))) @ rot

    # ── тело ────────────────────────────────────────────────────────────────────────────────────────────────────
    with_matrix(a, sm)
    part(a, "Body", "Stand", q((0, 0.2, t + 0.8)))
    # брюшко отодвинуто назад: между ним и грудью — видимый стебелёк; кольца вдоль оси назад, конец круглый
    d = V((0, 0.95, -0.12)).normalized()
    mg = Matrix.Translation((0, 0.8, t + 0.8)) @ d.to_track_quat("Z", "Y").to_matrix().to_4x4()
    A.body(a, "ant", (0, 0, 0), 0.42, 0.38, 0.9, _gaster, n=5, keys=["ant", "antD", "ant", "antD", "ant"],
           matrix=mg)
    # тонкая талия-стебелёк: перемычка и два узелка (шире 0.12 стада — не мерцает), за задними лапами
    kchain(a, "antD", [(0, 0.18, t + 0.76), (0, 0.84, t + 0.8)], [0.15, 0.15], [0.15, 0.15], up=(0, 0, 1))
    for y, z, r in ((0.44, 0.775, 0.12), (0.64, 0.81, 0.13)):
        knob(a, "antD", (0, y, t + z), r, n=2)
    # грудь — широкая, как у штангиста: к ней по бокам крепятся плечи рук
    kchain(a, "ant", [(0, 0.2, t + 0.72), (0, 0.04, t + 0.94), (0, -0.05, t + 1.22)], [0.4, 0.62, 0.46],
           [0.34, 0.44, 0.34], up=(0, -1, 0))
    # четыре опорные лапы в глубоком приседе: бедро наружу, колено выше таза, голень круто вниз, стопа вперёд/назад;
    # задняя пара сдвинута вперёд — не закрывает стебелёк сбоку
    for s in S2:
        for y0, yk, yf, tip in ((-0.06, -0.22, -0.38, -0.24), (0.06, 0.18, 0.24, 0.2)):
            hip = (s * 0.16, y0, t + 0.86)
            knee = (s * 0.62, yk, t + 1.02)
            foot = (s * 0.8, yf, t + 0.1 - DZ)
            A.limb(a, "antD", [hip, knee, foot], [0.3, 0.26, 0.22], joints=False)
            knob(a, "antD", knee, 0.17)
            taper(a, "antD", (s * 0.8, yf, t + 0.08 - DZ), (s * 0.88, yf + tip, t + 0.05 - DZ), 0.17, 0.13, 0.13, 0.1)
    # ── голова (крупнее тела: HS) ───────────────────────────────────────────────────────────────────────────────
    with_matrix(a, hm)
    part(a, "Head", "Body", q(tuple(neck)))
    A.body(a, "ant", (0, -0.12, t + 1.2), 0.42, 0.38, 0.76, "ball", n=4)
    # глаза натуги — зажмурены «> <»: две тёмные планки-уголка на каждом, углом к носу (толщина 0.075 стада —
    # не мерцает); вместе со сжатым ртом и потом — усилие, а не злость
    for s in S2:
        mf = Matrix.Translation((s * 0.17, -0.47, t + 1.66)) @ A.facing((s * 0.3, -1, 0.1))
        for dz in (1, -1):
            bar(a, "dark", mf @ V((s * 0.13, -0.03, dz * 0.11)), mf @ V((-s * 0.09, -0.03, dz * 0.005)), 0.12, 0.1,
                bevel=0)
    for s in S2:
        # жвалы: крупные светлые клещи под ртом, концы сведены к середине
        kchain(a, "antM", [(s * 0.2, -0.32, t + 1.3), (s * 0.26, -0.6, t + 1.28), (s * 0.08, -0.7, t + 1.27)],
               [0.16, 0.14, 0.11], [0.13, 0.12, 0.1], up=(0, 0, 1), cut=0.25, overlap=0.3)
        # коленчатый усик: стержень вверх-вперёд под 65° (колено), дальше жгутик вперёд и янтарная булава-капелька
        # (меньше кулака втрое по объёму и другого цвета — не «вторые кулаки»)
        base = V((s * 0.13, -0.32, t + 1.86))
        knee = base + V((s * 0.11, -0.16, 0.3))
        tip = knee + V((s * 0.03, -0.26, -0.08))  # жгутик — вперёд, к игроку, не в сторону (не «молоток»)
        A.limb(a, "antD", [tuple(base), tuple(knee), tuple(tip)], [0.12, 0.11, 0.11], joints=False)
        knob(a, "antD", tuple(knee), 0.085, n=2)
        dv = (tip - knee).normalized()
        # булава-капля: широкая часть на конце, к жгутику сужается (ось — от конца назад к колену)
        mc = Matrix.Translation(tip + dv * 0.16) @ (-dv).to_track_quat("Z", "Y").to_matrix().to_4x4()
        A.body(a, "antM", (0, 0, 0), 0.09, 0.09, 0.24, "egg", n=3, floor=0.45, bevel=0, matrix=mc)
    # сжатый рот (тужится): тёмная полоска уголками вниз, без зубов (каталог: пасти беззубы) — силу показывают
    # зажмуренные глаза, капли пота и сведённые жвалы
    a.box("mouth", -0.16, 0.16, -0.52, -0.44, t + 1.45, t + 1.52, bevel=0)
    for s in S2:
        a.box("mouth", s * 0.12 - 0.05, s * 0.12 + 0.05, -0.52, -0.44, t + 1.4, t + 1.47, bevel=0)
    # капли пота: две на виске со стороны игрока (hero), одна — на другом виске; кончиком вверх
    for c in ((-0.42, -0.26, t + 1.42), (-0.43, -0.16, t + 1.7), (0.43, -0.24, t + 1.52)):
        A.body(a, "sweat", c, 0.095, 0.08, 0.27, "drop", n=4, floor=0.3, bevel=0)
    with_matrix(a, None)
    # ── лист ────────────────────────────────────────────────────────────────────────────────────────────────────
    part(a, "Leaf", "ArmL", tuple(ml @ V((UG + GRIP, 0, -0.14))))  # вращается вокруг кулака ArmL
    for s in S2:
        _leaf_half(a, ml, s, u0, u1, wmax, sag)
    a.box("leafV", u0 + 0.12, u1 - 0.28, -0.065, 0.065, 0.06, 0.16, bevel=0, matrix=ml)  # главная жилка
    a.box("leafE", u0 + 0.3, u1 - 0.7, -0.09, 0.09, -0.14, -0.03, bevel=0, matrix=ml)  # жилка снизу: за неё хват
    taper(a, "leafV", ml @ V((u0 + 0.14, 0, -0.01)), ml @ V((u0 - 0.24, 0, -0.1)), 0.13, 0.1, cut=0.2)  # черешок
    # ── руки: из боков груди, локти широко в стороны, кулаки снизу упираются в жилку (в осях муравья) ─────────────
    smi = sm.inverted()
    with_matrix(a, sm)
    for s, nm in ((1, "ArmL"), (-1, "ArmR")):
        palm = smi @ (ml @ V((UG + s * GRIP, 0, -0.14 - 0.11)))  # верх кулака заходит в жилку на 0.02
        sh = V((s * 0.2, -0.02, t + 0.98))  # плечо начинается внутри груди, ниже головы
        part(a, nm, "Body", q(tuple(sh)))
        elbow = sh.lerp(palm, 0.42) + V((s * 0.42, -0.06, 0))
        A.limb(a, "antD", [tuple(sh), tuple(elbow), tuple(palm)], [0.26, 0.27, 0.24], joints=False)
        knob(a, "antD", tuple(elbow), 0.18)
        dv = (elbow - sh).normalized()
        L = (elbow - sh).length * 0.7
        side = V((-dv.z * s, 0, abs(dv.x))).normalized()
        bc = sh.lerp(elbow, 0.5) + V((0, -0.04, 0)) + side * 0.05
        mb = Matrix.Translation(bc - dv * L / 2) @ dv.to_track_quat("Z", "Y").to_matrix().to_4x4()
        A.body(a, "ant", (0, 0, 0), 0.21, 0.22, L, "ball", n=3, floor=0.5, bevel=0, matrix=mb)  # бицепс
        knob(a, "antD", tuple(palm + V((0, 0, 0.02))), 0.21, n=3)  # кулак
    with_matrix(a, None)
    face_point(a, q((0, -0.5, t + 1.55), hm))
    closeup(a, q((0.3, -0.1, t + 1.9), hm), eye_off=(-0.6, -2.4, 1.4))
    a.pose = {"Leaf": ((0, 10, 0), (0, 0, 0)), "Head": ((0, 0, 12), (0, 0, 0)), "ArmR": ((0, -6, 0), (0, 0, 0))}
    return a


