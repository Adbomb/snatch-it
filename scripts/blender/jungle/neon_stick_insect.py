"""Палочник-неон (NeonStickInsect, Common, №12 каталога docs/BOSS6_CATALOG.md) — притворяется веточкой, но он
пухлый и ярко-неоново-голубой: его видно отовсюду, а сам уверен, что спрятался, и подмигивает «меня не видно».
Шутка в позе: настоящая поза маскировки палочника — тело прямое и ровное, как палка, передние ноги вытянуты вперёд
вместе с усиками в одну линию с телом, — а он яркий, толстый и подмигивает игроку.
Признаки вида (мадагаскарский палочник Achrioptera): длинное членистое тело из пухлых сегментов со светлой каймой
(короткая переднегрудь, длинная среднегрудь, брюшко из колец, кончик чуть загнут вверх); шесть толстых коротких ног
из трёх члеников (бедро, голень, лапка) со светлыми коленцами, средние и задние ноги — в стороны от боков; жёлтые
бугорки на задних ногах и на спине груди; два коротких красно-розовых крылышка; короткие толстые усики вперёд.
Эмоция — самоуверенность: один глаз подмигивает, другой хитро прищурен под поднятой бровью, ухмылка наискось,
румянец. Цвета: электрический голубой (тело и голова), ноги на ступень темнее, светло-голубая кайма сегментов
и коленца, красно-розовые крылышки, жёлтые бугорки; зелёного нет.
Правка владельца 2026-11-25: тонких палочек нет — ноги, усики и сегменты толстые. Зависит от jungle_kit.
"""

import math
import os
import sys

from mathutils import Matrix, Vector

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
