def _barrel(u):
    """Сегмент-бочонок: концы уже середины, задний конец чуть уже переднего (ярусы разной ширины — грани не
    совпадают)."""
    return 0.76 + 0.24 * math.sin(math.pi * u) - 0.05 * u


END = _barrel(1 / 6)  # доля радиуса переднего (широкого) крайнего яруса сегмента из 3 ярусов


def _axis(p0, p1):
    """Оси сегмента: z — от p0 к p1, y — как можно ближе к миру z (вверх), x — вбок."""
    p0, p1 = V(p0), V(p1)
    return Matrix.Translation(p0) @ (p1 - p0).normalized().to_track_quat("Z", "Y").to_matrix().to_4x4()


def _seg(a, key, p0, p1, w, h, n=3, keys=None):
    """Пухлый сегмент тела от p0 к p1: бочонок из n ярусов поперёк оси (ступени D39), w — вбок, h — по вертикали."""
    L = (V(p1) - V(p0)).length
    return A.body(a, key, (0, 0, 0), w, h, L, _barrel, n=n, floor=0.7, matrix=_axis(p0, p1), keys=keys)


def _rim(a, key, p, d, w, h, half=0.045):
    """Светлая кайма сегмента: сплошной восьмиугольный пояс шириной 2·half в складке p поперёк направления d; чуть
    шире концов соседних сегментов (выступ ≤ 0.04 — полоса, не рамка и не висящие язычки)."""
    m = _axis(V(p) - V(d) * half, V(p) + V(d) * half)
    a.prism(key, S.octagon(-w, w, -h, h, min(w, h) * 0.34), 0.0, 2 * half, axis="z", bevel=0, matrix=m)


def neon_stick_insect():
    a = new("NeonStickInsect", {"stick": ("1FA8FF", True), "leg": ("1C5FD6", True), "rim": ("9FEFFF", False),
                                "joint": ("8FE3FF", False), "brow": ("17338F", False), "wing": ("FF4F7E", True),
                                "wingL": ("FFA3BC", False), "bump": ("FFD21C", False)})
    t = common_stand(a, 1.5)

    def P(x, z, y=0.0):
        return V((x, y, t + z))

    # тело прямое и ровное, как палка (поза маскировки): переднегрудь, длинная среднегрудь, заднегрудь, три кольца
    # брюшка и светлый кончик, чуть загнутый вверх; (x начала, x конца, z оси, полуширина, полувысота, ярусов)
    segs = [(-0.88, -0.58, 0.42, 0.22, 0.23, 2), (-0.58, 0.06, 0.39, 0.26, 0.27, 3), (0.06, 0.42, 0.37, 0.28, 0.28, 3),
            (0.42, 0.74, 0.37, 0.29, 0.29, 3), (0.74, 1.04, 0.38, 0.26, 0.26, 3), (1.04, 1.3, 0.41, 0.22, 0.22, 2),
            (1.3, 1.52, 0.48, 0.17, 0.17, 2)]
    part(a, "Body", "Stand", tuple(P(-0.2, 0.39)))
    for k, (x0, x1, zc, w, h, n) in enumerate(segs):
        if k == 3:
            # жёлтые бугорки на спине среднегруди (у Achrioptera грудь в шипиках) — тупые, короткие; ещё в части Body
            for x in (-0.42, -0.12):
                blunt(a, "bump", P(x, 0.6), P(x + 0.04, 0.76), 0.14, 0.07)
            part(a, "Abdomen", "Body", tuple(P(x0, zc)))
        if k == 5:
            part(a, "Tail", "Abdomen", tuple(P(x0, zc)))
        z1 = segs[k + 1][2] if k + 1 < len(segs) else zc + 0.12
        p0, p1 = P(x0, zc), P(x1, (zc + z1) / 2 if k + 1 < len(segs) else z1)
        d = (p1 - p0).normalized()
        last = k == len(segs) - 1
        _seg(a, "stick", p0 - d * 0.05, p1 + d * (0.0 if last else 0.05), w, h, n=n,
             keys=["stick", "rim"] if last else None)  # кончик брюшка — светлый
        if not last:
            w2, h2 = segs[k + 1][3], segs[k + 1][4]
            _rim(a, "rim", p1, d, max(w, w2) * END + 0.018, max(h, h2) * END + 0.018)
    _rim(a, "rim", P(-0.88, 0.42), V((1, 0, 0)), 0.22 * END + 0.018, 0.23 * END + 0.018)  # воротник у головы

    # ноги — три членика (бедро, голень, лапка), толстые и короткие, темнее тела; светлое коленце. Передние вытянуты
    # вперёд под головой вместе с усиками (поза «я веточка»), средние и задние — бедро в сторону от бока, коленце ниже
    # спины, стопа в полшага от бока. (имя, тазик, колено, конец голени, конец лапки — каждая точка (x, y, z))
    legs = (("F", (-0.72, 0.13, 0.37), (-1.12, 0.3, 0.16), (-1.56, 0.25, 0.14), (-1.84, 0.2, 0.1)),
            ("M", (-0.04, 0.22, 0.34), (-0.22, 0.5, 0.56), (-0.34, 0.58, 0.13), (-0.54, 0.62, 0.09)),
            ("H", (0.36, 0.24, 0.34), (0.6, 0.52, 0.58), (0.74, 0.6, 0.13), (0.94, 0.64, 0.09)))
    for nm, hip, knee, ank, toe in legs:
        for s in S2:
            side = "L" if s > 0 else "R"
            pts = [P(x, z, s * y) for x, y, z in (hip, knee, ank, toe)]
            part(a, "Leg" + nm + side, "Body", tuple(pts[0]))
            up = (0, 0, 1) if nm == "F" else (1, 0, 0)
            kchain(a, "leg", pts, [0.21, 0.2, 0.19, 0.18], [0.21, 0.2, 0.19, 0.16], up=up, cut=0.24, overlap=0.4)
            knob(a, "joint", tuple(pts[1]), 0.112, n=1)  # светлое коленце — сочленение видно издалека
            knob(a, "joint", tuple(pts[2]), 0.092, n=1)  # светлый сустав голени и лапки
            if nm == "H":  # жёлтые бугорки: на бедре вверх, на голени назад
                b = pts[0].lerp(pts[1], 0.55)
                blunt(a, "bump", b, b + V((0.03, s * 0.05, 0.17)), 0.13, 0.065)
                b = pts[1].lerp(pts[2], 0.5)
                blunt(a, "bump", b, b + V((0.17, s * 0.03, 0.02)), 0.12, 0.06)

    # два коротких крылышка на заднегруди: отдельные, разведены в стороны, подняты на 25°
    for s in S2:
        root = P(0.1, 0.6, s * 0.17)
        part(a, "Wing" + ("L" if s > 0 else "R"), "Body", tuple(root))
        el, sp = math.radians(25), math.radians(24)
        x = V((math.cos(el) * math.cos(sp), s * math.cos(el) * math.sin(sp), math.sin(el)))
        nrm = V((0, -s * 0.45, 1)).normalized()
        y = nrm.cross(x).normalized()
        z = x.cross(y)
        m = Matrix(((x.x, y.x, z.x, root.x), (x.y, y.y, z.y, root.y), (x.z, y.z, z.z, root.z), (0, 0, 0, 1)))
        a.prism("wing", S.octagon(-0.04, 0.46, -0.15, 0.15, 0.1), -0.045, 0.045, axis="z", bevel=0, matrix=m)
        a.prism("wingL", S.octagon(0.08, 0.38, -0.08, 0.08, 0.05), 0.035, 0.07, axis="z", bevel=0, matrix=m)

    # голова: крупная, повёрнута к игроку на 40° (лицо видно спереди, в hero и в игре); подмигивает
    hc = P(-1.08, 0.62)
    part(a, "Head", "Body", tuple(P(-0.86, 0.44)))
    hm = Matrix.Translation(hc) @ Matrix.Rotation(math.radians(-40), 4, "Z")
    with_matrix(a, hm)
    th = A.body(a, "stick", (0, 0, -0.35), 0.4, 0.36, 0.7, "ball", n=4, t0=0.06, t1=0.94, floor=0.45)
    ez = 0.04
    r = 0.13
    hh = r * 1.1
    for s in S2:
        ex = s * 0.17
        c = (ex, front_y(th, ex, ez) + 0.01, ez)
        nrm = (s * 0.2, -1, 0.05)
        if s > 0:  # подмигивает: глаз закрыт, бровь опущена к глазу
            eye2(a, c, 0.12, nrm, "sly", s, "stick", "leg", closed=True, show_brow=False)
            brow_bar(a, "brow", c, nrm, 0.16, 0.12 * 1.1 * 0.95 + 0.04, -12, thick=0.1, depth=0.16)
        else:  # второй глаз — хитрый прищур под высоко поднятой бровью (бровь лежит прямо на веке)
            eye2(a, c, r, nrm, "sly", s, "stick", "leg", lid=0.01, look=(0.3, -0.1), show_brow=False)
            brow_bar(a, "brow", c, nrm, 0.17, hh + 0.075, -14, thick=0.1, depth=0.16)  # бровь поднята и выгнута —
            # «ну-ну, меня не видно»
    # ухмылка наискось: брусок на нижнем ярусе лица, уголок у подмигивающего глаза выше и загнут вверх
    my = front_y(th, 0.0, -0.215) - 0.012
    mm = Matrix.Translation((0.03, my, -0.215)) @ Matrix.Rotation(math.radians(-10), 4, "Y")
    a.box("mouth", -0.16, 0.13, -0.02, 0.06, -0.036, 0.036, bevel=0, matrix=mm)
    mc = mm @ Matrix.Translation((0.13, 0, 0)) @ Matrix.Rotation(math.radians(-40), 4, "Y")
    a.box("mouth", -0.03, 0.08, -0.025, 0.055, -0.034, 0.034, bevel=0, matrix=mc)
    fy = front_y(th, 0.24, -0.06)
    a.box("blush", 0.17, 0.3, fy - 0.012, fy + 0.05, -0.11, -0.045, bevel=0)  # румянец под подмигивающим глазом
    with_matrix(a, None)
    # короткие толстые усики: корни на макушке за бровями, вытянуты вперёд вдоль тела — в одну линию с передними ногами
    for s in S2:
        root = hm @ V((s * 0.14, 0.12, 0.27))
        side = (hm.to_3x3() @ V((s, 0, 0))) * 0.07
        mid = root + V((-0.34, 0, 0.13)) + side
        tip = mid + V((-0.36, 0, -0.02)) + side
        kchain(a, "leg", [root, mid, tip], [0.13, 0.12, 0.1], [0.13, 0.12, 0.1], up=(0, 0, 1), cut=0.24, overlap=0.4)
    face_point(a, tuple(hm @ V((0, -0.36, 0.0))))
    closeup(a, (-0.2, -0.28, t + 0.42), eye_off=(-0.8, -2.4, 0.8))
    # поза (второй кадр): «привет, меня не видно» — машет игроку средней ногой, голова гордо поднята и ещё сильнее к игроку,
    # кончик брюшка задран, крылышки распахнуты
    a.pose = {"Head": ((0, 10, 22), (0, 0, 0.03)), "LegMR": ((-70, 0, 0), (0, 0, 0)), "Tail": ((0, -34, 0), (0, 0, 0)),
              "WingL": ((22, 0, 0), (0, 0, 0)), "WingR": ((-22, 0, 0), (0, 0, 0)), "LegHR": ((0, 0, -12), (0, 0, 0))}
    return a


ITEM = ("NeonStickInsect", neon_stick_insect, "Палочник-неон", "Common")
