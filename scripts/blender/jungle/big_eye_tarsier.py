"""Долгопят-глазастик (BigEyeTarsier, Common, №6 каталога docs/BOSS6_CATALOG.md) — глаза у него больше головы:
на коричневом стебле висит пара огромных янтарных глаз с ушами и обхватывает стебель длинными пальцами.
Поза — классическое вертикальное цепляние долгопята: стебель перед животом, все четыре лапы обхватывают его,
ступни не касаются подставки, голова с глазами — самая верхняя и самая широкая масса силуэта.
Признаки вида: огромные круглые глаза навыкате (купол из ступеней, в профиле — самый большой бугор головы, сидят
в меховых веках), большие овальные уши со складкой (отдельные части), длинные пальцы с дисками-подушечками на руках
и ногах (обхватывают стебель спереди), длинные прыгучие задние лапы (бедро, колено в сторону, длинная стопа от пятки
к стеблю), тонкий голый хвост с кисточкой. Эмоция — изумление: рот «о», брови подняты, глаза распахнуты.
Цвета: карамельно-рыжий мех, кремовое брюшко, янтарные глаза (к середине темнее), розовые уши и пальцы со светлыми
подушечками; стебель коричневый (часть Haze, D58: в игре подставка скрыта), зелёный — только росток на стебле.
"""

