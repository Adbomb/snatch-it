def _oct(r, k=0.58):
    """Правильный восьмиугольник с апофемой r (точки в плоскости детали)."""
    return S.octagon(-r, r, -r, r, r * k)


def _arch(s, r_in, r_out, angles):
    """Дуга-веко в плоскости глаза: от внутреннего радиуса r_in до внешнего r_out по углам angles (градусы,
    0 — наружу от носа, 90 — вверх); s зеркалит левую и правую сторону."""
    outer = [(s * r_out * math.cos(math.radians(g)), r_out * math.sin(math.radians(g))) for g in angles]
    inner = [(s * r_in * math.cos(math.radians(g)), r_in * math.sin(math.radians(g))) for g in reversed(angles)]
    return outer + inner


def _cap(R, z0, k=0.58):
    """Верх восьмиугольника с апофемой R выше горизонтали z0 (точки x, z): веко-капюшон над глазом."""
    pts = _oct(R, k)
    out = []
    for i, (x0, y0) in enumerate(pts):
        x1, y1 = pts[(i + 1) % len(pts)]
        if y0 >= z0:
            out.append((x0, y0))
        if (y0 - z0) * (y1 - z0) < 0:
            u = (z0 - y0) / (y1 - y0)
            out.append((x0 + (x1 - x0) * u, z0))
    return out


def _big_eye(a, c, r, normal, s):
    """Огромный глаз навыкате в осях (c, normal): купол из трёх ступеней — янтарная радужка, к середине темнее,
    большой тёмный зрачок (≈ 58 % радужки) и два блика; всего выступает на 0.4, в голову уходит на 0.15.
    Меховые веки двумя ступенями охватывают глаз сверху и с боков — глаз сидит в голове, а не висит пластиной."""
    m = Matrix.Translation(V(c)) @ A.facing(normal)
    for key, rr, front, back in (("amber", 1.0, -0.17, 0.1), ("amberD", 0.8, -0.31, 0.0), ("dark", 0.57, -0.35, -0.2)):
        a.prism(key, _oct(r * rr), front, back, axis="y", bevel=0, matrix=m)
    for gx, gz, g in ((-0.065, 0.06, 0.08), (0.07, -0.07, 0.045)):  # блики на зрачке: крупный вверху, малый внизу
        a.box("glint", s * gx - g / 2, s * gx + g / 2, -0.37, -0.34, gz - g / 2, gz + g / 2, bevel=0, matrix=m)
    # веко — меховая чаша: снаружи-снизу через верх к переносице, спереди короче купола глаза (глаз выпирает из неё);
    # второй ярус — только капюшон сверху
    a.extrude("fur", _arch(s, r * 0.97, r * 1.17, (-70, -22.5, 22.5, 67.5, 112.5, 157.5)), 0.22, -0.13, axis="y",
              matrix=m)
    # верхнее веко-капюшон двумя ступенями поверх купола: срезает верх радужки — глаз под веком, а не линза в оправе
    # (внутренний край чуть выше — удивлённо-любопытный взгляд)
    mh = m @ Matrix.Rotation(math.radians(s * 5), 4, "Y")
    for z0, rr, front, back in ((0.66, 1.04, -0.32, -0.05), (0.78, 0.95, -0.38, -0.28)):
        a.prism("fur", _cap(r * rr, r * z0), front, back, axis="y", bevel=0, matrix=mh)


def _finger(a, wrist, knuckle, tip, sy, w=0.1, pad_r=0.075):
    """Длинный палец, согнутый вокруг стебля (ось x = 0, y = sy): запястье → сустав → кончик, два бруска внахлёст;
    на кончике — диск-подушечка светлее пальца, повёрнутый наружу от стебля."""
    p0, p1, p2 = V(wrist), V(knuckle), V(tip)
    d1, d2 = (p1 - p0).normalized(), (p2 - p1).normalized()
    bar(a, "skin", p0, p1 + d1 * w * 0.5, w, w, bevel=0)
    bar(a, "skin", p1 - d2 * w * 0.5, p2, w * 0.95, w * 0.95, bevel=0)
    n_ = V((p2.x, p2.y - sy, 0)).normalized()
    m = Matrix.Translation(p2 + n_ * 0.03) @ A.facing(tuple(n_))
    a.prism("pad", _oct(pad_r, 0.5), -0.03, 0.035, axis="y", bevel=0, matrix=m)


def _hand(a, wrist, z, s, sy, spread=0.13):
    """Кисть на стебле: запястье у бока стебля (сторона s), три длинных пальца поперёк всего переда стебля
    (спереди видны розовые полосы), подушечки — у другого бока; средний палец длиннее — подушечки не слипаются."""
    for dz, tx, ty in ((spread, -0.06, -0.205), (0.0, -0.14, -0.175), (-spread, -0.06, -0.205)):
        knuckle = (s * 0.17, sy - 0.15, z + dz * 0.7)
        _finger(a, wrist, knuckle, (s * tx, sy + ty, z + dz), sy)


def _foot(a, ball, z, s, sy, spread=0.15):
    """Стопа на стебле: три пальца со своей стороны s обхватывают бок стебля, подушечки смотрят вбок-вперёд."""
    for dz, tx, ty in ((spread, 0.12, -0.17), (0.0, 0.17, -0.14), (-spread, 0.12, -0.17)):
        knuckle = (s * 0.25, sy - 0.07, z + dz * 0.6)
        _finger(a, ball, knuckle, (s * tx, sy + ty, z + dz), sy, w=0.095, pad_r=0.07)


def big_eye_tarsier():
    a = new("BigEyeTarsier", {"fur": ("C97B3D", True), "furD": ("8F4F22", False), "belly": ("FFE7C2", False),
                              "amber": ("FFB52E", False), "amberD": ("E07B00", False), "ear": ("F7A3AE", False),
                              "skin": ("F28FA8", False), "pad": ("FFB5C8", False), "tail": ("EDB487", False),
                              "tuft": ("B8692E", False), "stem": ("8F5A31", True), "stemD": ("6B4123", False),
                              "leaf": ("6CC24A", False), "leafV": ("3E8E36", False)})
    t = common_stand(a, 1.5)
    sy = -0.36  # ось стебля: перед брюшком, брюшко прижато к стеблю

    # стебель — насест (видимая часть вне подставки, D58): толстый у корня, узел-шапка сверху, росток вбок
    part(a, "Haze", "Stand", (0, sy, t))
    kchain(a, "stem", [(0.0, sy, t - 0.03), (0.01, sy, t + 1.34)], [0.36, 0.33], up=(0, -1, 0), cut=0.3, overlap=0.3)
    a.prism("stemD", _oct(0.25, 0.5), t - 0.02, t + 0.09, bevel=0, matrix=Matrix.Translation((0, sy, 0)))
    a.prism("stemD", _oct(0.2, 0.5), t + 1.3, t + 1.37, bevel=0, matrix=Matrix.Translation((0.01, sy, 0)))
    flat_leaf(a, "leaf", "leafV", (-0.1, sy - 0.01, t + 1.33), (-0.55, sy - 0.03, t + 1.44), 0.22, 0.07,
              (0.2, -1, 0.3))

    # тело: короткое и круглое, шире в бёдрах, уже в плечах; кремовое брюшко у стебля
    part(a, "Body", "Stand", (0, 0.16, t + 0.95))
    prof = lambda u: 1.0 if u < 0.34 else (0.9 if u < 0.67 else 0.72)  # noqa: E731
    A.body(a, "fur", (0, 0.16, t + 0.58), 0.48, 0.4, 0.82, prof, n=3, lean=-0.06,
           front=("belly", 0.7, t + 0.62, t + 1.4))

    # длинные прыгучие задние лапы: бедро вбок-вперёд к колену, голень вниз-назад к пятке, длинная стопа от пятки
    # вперёд к стеблю; пальцы с дисками обхватывают низ стебля, ступни над подставкой
    for s, nm, fz in ((1, "LegL", t + 0.28), (-1, "LegR", t + 0.34)):
        hip = V((s * 0.28, 0.2, t + 0.72))
        part(a, nm, "Body", tuple(hip))
        knee = V((s * 0.5, -0.04, fz + 0.32))
        heel = V((s * 0.44, 0.24, fz))
        ball_ = V((s * 0.26, sy + 0.04, fz))
        taper(a, "fur", hip, knee, 0.34, 0.22, 0.32, 0.2, up=(s, 0, 0), cut=0.3)  # бедро
        knob(a, "fur", tuple(knee), 0.12)
        taper(a, "fur", knee, heel, 0.17, 0.13, 0.16, 0.12, up=(s, 0, 0), cut=0.3)  # голень
        knob(a, "fur", tuple(heel), 0.09)
        taper(a, "fur", heel, ball_, 0.15, 0.12, 0.12, 0.1, cut=0.25)  # длинная стопа (признак долгопята)
        knob(a, "skin", tuple(ball_), 0.075)
        _foot(a, tuple(ball_), fz, s, sy)

    # руки: от плеч вперёд к стеблю, левая выше, правая ниже; длинные пальцы с дисками поперёк всего стебля
    for s, nm, wz in ((1, "ArmL", t + 1.1), (-1, "ArmR", t + 0.72)):
        sh = V((s * 0.2, 0.06, t + 1.24))
        part(a, nm, "Body", tuple(sh))
        el = V((s * 0.47, -0.1, wz + 0.12))
        wr = V((s * 0.24, sy + 0.02, wz))
        A.limb(a, "fur", [tuple(sh), tuple(el), tuple(wr)], [0.16, 0.13, 0.11], joints=False)
        knob(a, "skin", tuple(wr), 0.075)
        _hand(a, tuple(wr), wz, s, sy)

    # голова: круглая; огромные глаза навыкате шире головы, в меховых веках
    part(a, "Head", "Body", (0, 0.04, t + 1.4))
    hc = V((0, 0.02, t + 1.8))
    A.ball(a, "fur", tuple(hc), 0.44, n=4, ry=0.38, rz=0.42)
    er = 0.28
    for s in S2:
        _big_eye(a, hc + V((s * 0.31, -0.32, 0.05)), er, (s * 0.25, -1, 0.04), s)
        # брови высоко над веками, внутренние концы подняты — изумление
        m = Matrix.Translation(hc + V((s * 0.27, -0.42, 0.42))) @ Matrix.Rotation(math.radians(s * 16), 4, "Y")
        a.box("furD", -0.15, 0.15, -0.08, 0.12, -0.045, 0.045, bevel=0, matrix=m)
    # мордочка: кремовый бугорок под глазами, розовый носик, рот «о»
    mz = hc.z - 0.3
    A.body(a, "belly", (0, hc.y - 0.33, mz - 0.12), 0.15, 0.13, 0.24, "ball", n=2, floor=0.5, bevel=0)
    a.box("pink", -0.06, 0.06, hc.y - 0.5, hc.y - 0.4, mz + 0.03, mz + 0.1, bevel=0)
    a.prism("mouth", _oct(0.065), hc.y - 0.485, hc.y - 0.38, axis="y", bevel=0,
            matrix=Matrix.Translation((0, 0, mz - 0.06)))
    # большие подвижные уши: высокие овалы (≈ 1.5 : 1), наклонены наружу, поперёк — складка
    for s, nm in ((1, "EarL"), (-1, "EarR")):
        base = hc + V((s * 0.3, 0.1, 0.26))
        part(a, nm, "Head", tuple(base))
        c = hc + V((s * 0.48, 0.14, 0.58))
        m = Matrix.Translation(c) @ A.facing((s * 0.5, -1, 0.15)) @ Matrix.Rotation(math.radians(s * 22), 4, "Y")
        a.prism("ear", S.octagon(-0.16, 0.16, -0.23, 0.26, 0.1), -0.02, 0.07, axis="y", bevel=0, matrix=m)
        a.prism("pink", S.octagon(-0.1, 0.1, -0.15, 0.18, 0.06), -0.045, 0.0, axis="y", bevel=0, matrix=m)
        a.box("ear", -0.1, 0.1, -0.065, -0.01, -0.07, 0.0, bevel=0, matrix=m)  # складка уха
        taper(a, "ear", base, c + V((0, 0.03, -0.18)), 0.18, 0.2, 0.14, 0.14, cut=0.25)  # корень уха в голове

    # тонкий голый хвост свисает вдоль стебля назад-вниз, у подставки загибается; на конце — ступенчатая кисточка
    part(a, "Tail", "Body", (0, 0.48, t + 0.7))
    pts = [(0, 0.42, t + 0.72), (0.02, 0.6, t + 0.6), (0.05, 0.7, t + 0.36), (0.1, 0.78, t + 0.15),
           (0.26, 0.86, t + 0.09)]
    kchain(a, "tail", pts, [0.12, 0.115, 0.11, 0.1, 0.09], up=(1, 0, 0), cut=0.25, overlap=0.3)
    tuft = [V((0.24, 0.85, t + 0.08)), V((0.42, 0.93, t + 0.2)), V((0.56, 0.97, t + 0.34)), V((0.64, 0.99, t + 0.48))]
    for k, w in enumerate((0.2, 0.16, 0.11)):  # три яруса кисточки, к концу уже
        d = (tuft[k + 1] - tuft[k]).normalized()
        taper(a, "tuft", tuft[k] - d * 0.04, tuft[k + 1], w, w * 0.9, w, w * 0.9, up=(0, 0, 1), cut=0.3)

    face_point(a, tuple(hc + V((0, -0.7, 0.0))))
    closeup(a, (0.0, sy, t + 0.9))
    # поза: от изумления отпустил стебель верхней рукой и вскинул её, голову склонил набок, уши развернул, хвост дёрнул
    a.pose = {"Head": ((0, 14, 12), (0, 0, 0)), "EarL": ((0, -25, 10), (0, 0, 0)), "EarR": ((0, 22, -10), (0, 0, 0)),
              "ArmL": ((-70, 0, 20), (0, 0, 0)), "Tail": ((0, 0, 30), (0, 0, 0))}
    return a


