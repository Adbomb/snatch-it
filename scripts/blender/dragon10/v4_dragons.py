"""Король-дракон v4 — три разные конструкции силуэта (этап A, без брони и украшений, один нейтральный материал).

A «Титан» — четвероногий тяжеловес: огромная голова на короткой толстой шее, высокая холка с лопатками, низкая
  широкая стойка, лапы с локтями врозь, мощный хвост с булавой, крылья полуподняты.
B «Владыка» — сидит по-королевски на задних лапах: прямые передние лапы, грудь колесом, длинная толстая S-образная
  шея, длинные рога назад, широко раскрытые крылья, длинный хвост обвивает передние лапы.
C «Император» — хищная стойка на задних пальцеходящих лапах: корпус наклонён вперёд, огромные плечи, передние лапы
  с когтями выставлены вперёд, широкая голова с костяным венцом из рогов, крылья сложены вдоль спины как плащ,
  длинный тяжёлый хвост-противовес.
Лицо смотрит в −y, верх +z; 1 единица — модель (в игре ×3).
"""

import math

import v4_kit as K
from v4_kit import Matrix, V

S2 = (1, -1)


def tip_blade(a, tail, pts):
    end, prev = V(tail[-1]), V(tail[-2])
    d = (end - prev).normalized()
    m = Matrix.Translation(end) @ Matrix.Rotation(math.atan2(d.x, -d.y), 4, "Z")
    a.extrude(K.KEY, pts, -0.07, 0.07, axis="x", matrix=m)


# ── A. Титан ─────────────────────────────────────────────────────────────────────────────────────────────────
def titan():
    a = K.new_art("DragonA")
    body = [(-2.4, 2.15), (-3.25, 3.1), (-3.5, 4.5), (-3.05, 5.75), (-1.75, 6.75), (-0.3, 6.45), (1.2, 5.85),
            (2.6, 5.55), (3.55, 4.85), (3.75, 3.75), (3.1, 2.75), (1.8, 2.15), (0.2, 1.9), (-1.2, 1.95)]
    K.layered(a, body, [(1.0, 1.0, 1.0), (1.65, 0.94, 0.93), (2.15, 0.8, 0.8)], anchor=(0.2, 4.0))
    for s in S2:  # лопатки: массы над передними лапами
        K.layered(a, [(-3.1, 3.4), (-3.25, 5.0), (-2.4, 6.55), (-1.0, 6.3), (-1.2, 4.6), (-2.0, 3.3)],
                  [(0.42, 1.0, 1.0), (0.62, 0.86, 0.86)], anchor=(-2.2, 4.8), xc=s * 2.05)
    K.chain(a, [(0, -2.6, 5.15), (0, -3.5, 6.25), (0, -4.15, 6.95)], [2.3, 1.95, 1.7], [2.4, 2.05, 1.75],
            up=(0, -1, 0.2))
    K.head(a, (0, -3.85, 6.65), L=3.9, H=1.95, W=1.62, pitch=6, jaw=0.52, brow=0.3, snout_w=0.56)
    for s in S2:  # рога толстые: в стороны-вверх-назад; шипы-скулы
        K.chain(a, [(s * 0.8, -0.7, 1.75), (s * 1.7, -0.3, 2.4), (s * 2.25, 0.45, 3.35), (s * 2.1, 1.0, 4.1)],
                [0.78, 0.62, 0.45, 0.24])
        K.spike(a, (s * 2.1, 1.0, 4.1), (s * 1.9, 1.35, 4.7), 0.24)
        K.spike(a, (s * 1.45, 0.1, 0.45), (s * 2.2, 0.65, 0.85), 0.42)
        K.spike(a, (s * 1.45, -0.6, 0.1), (s * 2.15, -0.4, 0.2), 0.34)
    a.transform = None
    K.spines(a, [(0, -2.6, 8.4), (0, -2.0, 7.5), (0, -1.2, 7.05), (0, -0.2, 6.75), (0, 1.0, 6.25), (0, 2.2, 5.95),
                 (0, 3.1, 5.5)], [0.6, 0.72, 0.85, 0.75, 0.62, 0.52, 0.42], lean=0.4)
    for s in S2:
        # передние лапы: локоть врозь, мощное предплечье, широкая лапа
        K.chain(a, [(s * 2.05, -2.15, 4.6), (s * 2.55, -1.75, 2.75), (s * 2.35, -2.35, 1.2), (s * 2.3, -2.55, 0.42)],
                [1.6, 1.35, 1.12, 1.05], [1.8, 1.45, 1.15, 1.05], up=(0, -1, 0))
        K.taper(a, (s * 2.3, -2.1, 0.32), (s * 2.35, -3.5, 0.28), 1.55, 1.3, 0.66, 0.54)
        K.claws(a, (s * 2.35, -3.45, 0.32), s, 3, 0.42, 0.62)
        K.spike(a, (s * 2.7, -1.45, 2.8), (s * 3.05, -0.5, 3.0), 0.42)
        # задние: тяжёлое бедро, скакательный сустав, лапа
        K.layered(a, [(0.9, 5.15), (2.9, 5.3), (3.65, 4.0), (3.3, 2.7), (2.5, 1.9), (1.3, 2.15), (0.75, 3.4)],
                  [(0.5, 1.0, 1.0), (0.76, 0.86, 0.86)], anchor=(2.2, 3.7), xc=s * 1.85)
        K.chain(a, [(s * 1.95, 2.6, 2.3), (s * 2.0, 3.35, 1.15), (s * 2.0, 2.85, 0.38)], [1.15, 0.95, 0.9],
                up=(0, -1, 0))
        K.taper(a, (s * 2.0, 3.15, 0.3), (s * 2.05, 1.7, 0.27), 1.3, 1.12, 0.6, 0.5)
        K.claws(a, (s * 2.05, 1.75, 0.3), s, 3, 0.36, 0.5)
        K.wing(a, V((s * 1.35, -1.1, 6.35)), s, {"E": (2.0, 2.4), "W": (3.6, 4.4), "T": (0.4, -0.9),
                                                    "F": [(6.1, 3.3), (6.5, 0.9), (5.2, -1.0), (3.4, -1.6)]},
               sweep=30, lean=8, bone=(0.55, 0.4, 0.22))
    tail = [(0, 3.4, 4.25), (0, 4.9, 3.25), (0.6, 6.1, 1.95), (1.8, 7.0, 0.95), (3.4, 7.1, 0.6), (4.8, 6.3, 0.55),
            (5.6, 5.1, 0.55)]
    K.chain(a, tail, [2.1, 1.75, 1.4, 1.12, 0.9, 0.72, 0.62], up=(0, 0, 1))
    K.spines(a, [V(p) + V((0, 0, w * 0.45)) for p, w in zip(tail[1:-1], (1.75, 1.4, 1.12, 0.9, 0.72))],
             [0.58, 0.5, 0.42, 0.36, 0.3])
    c = V((5.85, 4.55, 0.62))  # булава — ступенчатый ком с шипами
    K.taper(a, c + V((0, 0.55, 0)), c - V((0, 0.55, 0)), 1.35, 0.95, 1.2, 0.85)
    K.taper(a, c + V((0.5, 0, 0)), c - V((0.5, 0, 0)), 0.95, 0.95, 1.0, 1.0)
    for d in ((1, 0, 0), (-1, 0, 0), (0, 0, 1), (0, -1, 0)):
        K.spike(a, c + V(d) * 0.55, c + V(d) * 1.25, 0.36)
    return a


# ── B. Владыка ───────────────────────────────────────────────────────────────────────────────────────────────
def lord():
    a = K.new_art("DragonB")
    body = [(-1.15, 1.0), (-1.95, 2.6), (-2.35, 4.1), (-2.15, 5.5), (-1.3, 6.4), (0.1, 6.5), (0.95, 5.6), (1.45, 4.2),
            (1.95, 2.8), (2.15, 1.4), (1.45, 0.6), (0.2, 0.6)]
    K.layered(a, body, [(0.82, 1.0, 1.0), (1.22, 0.92, 0.93), (1.5, 0.78, 0.8)], anchor=(0.2, 3.6))
    neck = [(0, -1.35, 5.75), (0, -2.45, 6.75), (0, -2.55, 7.85), (0, -2.0, 8.75), (0, -2.25, 9.6), (0, -2.85, 10.05)]
    K.chain(a, neck, [2.05, 1.6, 1.32, 1.15, 1.05, 1.0], [2.15, 1.65, 1.36, 1.18, 1.08, 1.02], up=(0, -1, 0))
    K.head(a, (0, -2.75, 9.8), L=3.3, H=1.35, W=1.0, pitch=10, jaw=0.38, brow=0.26, snout_w=0.58)
    for s in S2:  # длинные древние рога: назад дугой и вниз; малые рога ниже
        K.chain(a, [(s * 0.46, -0.7, 1.12), (s * 0.68, 0.3, 1.62), (s * 0.85, 1.6, 1.78), (s * 0.95, 2.8, 1.35),
                    (s * 0.9, 3.5, 0.68)], [0.5, 0.4, 0.3, 0.2, 0.09])
        K.chain(a, [(s * 0.74, -0.25, 0.62), (s * 1.12, 0.5, 0.8), (s * 1.3, 1.15, 0.62)], [0.27, 0.19, 0.07])
    a.transform = None
    K.spines(a, [V(p) + V((0, 0.7, 0.2)) for p in neck[1:-1]] + [V((0, 0.25, 6.6)), V((0, 1.0, 5.9))],
             [0.46, 0.42, 0.38, 0.34, 0.48, 0.42], up=(0, 0.5, 1))
    for s in S2:
        x = s * 1.2
        K.chain(a, [(x, -1.15, 5.2), (x, -1.15, 3.25), (x, -1.55, 1.15), (x, -1.7, 0.42)], [1.12, 0.88, 0.72, 0.68],
                up=(0, -1, 0))
        K.taper(a, (x, -1.45, 0.28), (x, -2.55, 0.25), 0.92, 0.78, 0.52, 0.44)
        K.claws(a, (x, -2.5, 0.28), s, 3, 0.28, 0.42)
        K.layered(a, [(-0.2, 3.4), (1.0, 3.95), (2.3, 3.0), (2.6, 1.4), (2.0, 0.35), (0.4, 0.3), (-0.5, 1.2)],
                  [(0.38, 1.0, 1.0), (0.55, 0.86, 0.86)], anchor=(1.1, 2.0), xc=s * 1.45)
        K.taper(a, (s * 1.52, 0.55, 0.3), (s * 1.52, -1.0, 0.26), 0.88, 0.75, 0.56, 0.46)
        K.claws(a, (s * 1.52, -0.95, 0.28), s, 3, 0.27, 0.38)
        K.wing(a, V((s * 0.95, 0.4, 6.15)), s, {"E": (2.0, 2.1), "W": (4.0, 3.75), "T": (0.5, -1.3),
                                                   "F": [(6.8, 2.7), (7.0, 0.5), (5.9, -1.5), (4.0, -2.3)]},
               sweep=14, lean=12, bone=(0.4, 0.28, 0.15))
    tail = [(0, 1.9, 1.3), (0, 3.2, 0.72), (1.4, 4.2, 0.55), (3.0, 3.6, 0.47), (3.6, 1.8, 0.44), (3.0, -0.1, 0.42),
            (1.85, -1.3, 0.4), (0.95, -1.95, 0.38)]
    K.chain(a, tail, [1.35, 1.12, 0.94, 0.78, 0.64, 0.52, 0.42, 0.33], up=(0, 0, 1))
    K.spines(a, [V(p) + V((0, 0, w * 0.45)) for p, w in zip(tail[1:-1], (1.12, 0.94, 0.78, 0.64, 0.52, 0.42))],
             [0.36, 0.32, 0.29, 0.25, 0.21, 0.18])
    tip_blade(a, tail, [(0.0, 0.2), (0.36, 0.42), (0.68, -0.1), (0.34, -0.95), (0.0, -0.15)])
    return a


# ── C. Император ─────────────────────────────────────────────────────────────────────────────────────────────
def emperor():
    a = K.new_art("DragonC")
    tilt = 18  # наклон корпуса вперёд вокруг таза — хищная стойка, а не человеческая
    L = Matrix.Translation((0, 0.3, 3.1)) @ Matrix.Rotation(math.radians(tilt), 4, "X") @ \
        Matrix.Translation((0, -0.3, -3.1))
    chest = [(-1.0, 4.6), (-2.05, 5.6), (-2.3, 6.6), (-1.85, 7.6), (-0.7, 8.05), (0.9, 7.9), (1.6, 6.9), (1.5, 5.6),
             (0.6, 4.7)]
    K.layered(a, chest, [(1.0, 1.0, 1.0), (1.85, 0.94, 0.92), (2.45, 0.8, 0.8)], anchor=(0.0, 6.4), matrix=L)
    belly = [(-0.75, 3.0), (-1.45, 3.9), (-1.6, 5.0), (-0.9, 5.6), (0.9, 5.6), (1.35, 4.6), (1.1, 3.4), (0.4, 2.85)]
    K.layered(a, belly, [(0.85, 1.0, 1.0), (1.3, 0.9, 0.9)], anchor=(0.0, 4.2), matrix=L)
    for s in S2:  # огромные плечи с гребнями шипов
        K.chain(a, [L @ V((s * 1.7, -0.4, 7.35)), L @ V((s * 3.2, -0.2, 7.5))], [2.15, 1.75], [2.0, 1.6])
        for k, (dx, h) in enumerate(((2.3, 0.9), (2.85, 0.75), (3.35, 0.55))):
            p = L @ V((s * dx, 0.1, 8.2 - k * 0.1))
            K.spike(a, p, p + V((s * 0.3, 0.45, h)), 0.46 - k * 0.07)
    neck0 = L @ V((0, -0.9, 7.75))
    K.chain(a, [neck0, V((0, -2.45, 8.55)), V((0, -2.9, 9.25))], [2.1, 1.72, 1.5], [2.2, 1.78, 1.52], up=(0, -1, 0))
    K.head(a, (0, -2.75, 8.95), L=3.2, H=1.6, W=1.4, pitch=4, jaw=0.5, brow=0.28, snout_w=0.55)
    # костяной венец: рога веером вокруг затылка — природная корона
    for x, y, z, tx, ty, tz, w in ((0.0, 0.05, 1.7, 0.0, 0.85, 3.0, 0.5), (0.58, 0.0, 1.65, 1.1, 0.75, 2.85, 0.44),
                                   (-0.58, 0.0, 1.65, -1.1, 0.75, 2.85, 0.44), (1.1, -0.05, 1.42, 2.0, 0.55, 2.35, 0.4),
                                   (-1.1, -0.05, 1.42, -2.0, 0.55, 2.35, 0.4), (1.38, -0.1, 0.95, 2.45, 0.45, 1.35, 0.36),
                                   (-1.38, -0.1, 0.95, -2.45, 0.45, 1.35, 0.36)):
        mid = ((x + tx) / 2 * 1.05, (y + ty) / 2, (z + tz) / 2 + 0.15)
        K.chain(a, [(x, y, z), mid], [w, w * 0.72])
        K.spike(a, mid, (tx, ty, tz), w * 0.72)
    a.transform = None
    for s in S2:
        # передние лапы выставлены вперёд, как у хищника: локти наружу, кисти с когтями
        sh = L @ V((s * 3.05, -0.35, 7.0))
        el = V((s * 3.7, -1.7, 4.75))
        wr = V((s * 3.2, -3.15, 3.95))
        K.chain(a, [sh, el, wr], [1.42, 1.18, 0.98], [1.5, 1.22, 1.0], up=(0, 0, 1))
        K.taper(a, wr, wr + V((0, -0.8, -0.3)), 1.15, 0.95, 0.72, 0.6)
        for k in range(4):
            b = wr + V(((k - 1.5) * 0.27, -0.9, -0.36))
            K.spike(a, b, b + V((0, -0.42, -0.42)), 0.22)
        K.spike(a, el, el + V((s * 0.45, 0.55, -0.35)), 0.44)
        # бёдра и пальцеходящие задние лапы в приседе
        K.layered(a, [(-0.9, 4.3), (0.6, 4.4), (1.25, 3.1), (0.55, 1.8), (-1.0, 1.95), (-1.45, 3.05)],
                  [(0.58, 1.0, 1.0), (0.82, 0.85, 0.85)], anchor=(-0.1, 3.0), xc=s * 1.55)
        K.chain(a, [(s * 1.6, -1.0, 2.1), (s * 1.6, 0.65, 1.0), (s * 1.6, -0.05, 0.32)], [1.08, 0.84, 0.78],
                up=(0, -1, 0))
        K.taper(a, (s * 1.6, 0.3, 0.28), (s * 1.6, -1.55, 0.24), 1.2, 1.02, 0.6, 0.5)
        K.claws(a, (s * 1.6, -1.5, 0.28), s, 3, 0.36, 0.5)
        # крылья сложены вдоль спины, как плащ: сгибы поднимаются над плечами, концы свисают назад
        K.wing(a, L @ V((s * 1.05, 1.0, 7.5)), s,
               {"E": (0.75, 1.5), "W": (1.35, 2.4), "T": (0.15, -2.6),
                "F": [(2.7, 0.8), (2.9, -1.9), (2.2, -3.9), (1.2, -4.7)]},
               sweep=70, lean=-4, tilt=-8, bone=(0.46, 0.34, 0.18), offset=0.06)
    tail = [(0, 1.2, 3.35), (0, 2.8, 3.05), (0, 4.4, 2.45), (0.35, 5.8, 1.45), (1.1, 7.0, 0.62), (2.3, 7.8, 0.46),
            (3.5, 8.0, 0.42)]
    K.chain(a, tail, [1.75, 1.5, 1.25, 1.0, 0.78, 0.58, 0.42], up=(0, 0, 1))
    K.spines(a, [V(p) + V((0, 0, w * 0.45)) for p, w in zip(tail[:-1], (1.75, 1.5, 1.25, 1.0, 0.78, 0.58))],
             [0.55, 0.5, 0.44, 0.38, 0.3, 0.24])
    K.spines(a, [L @ V((0, 1.7, 7.7)), L @ V((0, 1.8, 6.8)), L @ V((0, 1.65, 5.8)), L @ V((0, 1.4, 4.8))],
             [0.6, 0.55, 0.5, 0.42], up=(0, 0.8, 1))
    tip_blade(a, tail, [(0.0, 0.25), (0.42, 0.48), (0.8, -0.12), (0.4, -1.1), (0.0, -0.18)])
    return a


