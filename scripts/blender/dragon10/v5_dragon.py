"""Король-дракон v5 — гибрид A «Титан» + B «Владыка» (только форма: нейтральный материал, без короны, брони, мантии).

От A: массивный четвероногий корпус с поднятой грудью, широкая грудь, мощные лапы, крупная голова, толстый хвост.
От B: величественная осанка, S-образная шея, длинные изогнутые рога, большие раскрытые крылья.
Новое: выразительная морда (три ступени сужения, гребень переносицы, скулы с шипами, тяжёлые надбровья, приоткрытая
сильная челюсть с клыками), крупные когти на раздельных пальцах, крыло растёт из мышцы на лопатке, перепонка
крепится к боку; живая поза — голова чуть повёрнута, левая передняя лапа шагает, крылья раскрыты по-разному, хвост
изогнут. Стиль D39: ступенчатые формы и острые рёбра (слоёные профили и звенья из v4_kit), без гладкой органики.
"""

import math

import v4_kit as K
from v4_kit import Matrix, V

S2 = (1, -1)


def head(a, origin, L=3.8, H=1.85, W=1.58, pitch=10.0, yaw=0.0, jaw_open=13.0):
    """Морда: слои по ширине — череп, три ступени морды, гребень переносицы, скулы, надбровья; челюсть приоткрыта."""
    M = Matrix.Translation(origin) @ Matrix.Rotation(math.radians(yaw), 4, "Z") @ \
        Matrix.Rotation(math.radians(-pitch), 4, "X")
    a.transform = M
    K.slab(a, [(0.2, -0.1 * H), (0.28, 0.55 * H), (0.05, 0.95 * H), (-0.3 * L, 1.02 * H), (-0.44 * L, 0.94 * H),
               (-0.54 * L, 0.74 * H), (-0.54 * L, 0.0), (-0.12 * L, -0.2 * H)], -0.62 * W, 0.62 * W)
    K.slab(a, [(-0.5 * L, 0.76 * H), (-0.72 * L, 0.6 * H), (-0.72 * L, 0.0), (-0.5 * L, 0.0)], -0.55 * W, 0.55 * W)
    K.slab(a, [(-0.7 * L, 0.62 * H), (-0.9 * L, 0.5 * H), (-0.9 * L, 0.02 * H), (-0.7 * L, 0.02 * H)], -0.45 * W, 0.45 * W)
    K.slab(a, [(-0.88 * L, 0.52 * H), (-1.02 * L, 0.46 * H), (-1.08 * L, 0.26 * H), (-1.04 * L, 0.06 * H),
               (-0.88 * L, 0.06 * H)], -0.34 * W, 0.34 * W)
    K.slab(a, [(-0.46 * L, 0.88 * H), (-0.96 * L, 0.6 * H), (-0.96 * L, 0.5 * H), (-0.46 * L, 0.72 * H)],
           -0.16 * W, 0.16 * W)  # гребень переносицы
    K.slab(a, [(0.1, -0.15 * H), (0.14, 0.6 * H), (-0.18 * L, 0.82 * H), (-0.42 * L, 0.66 * H), (-0.5 * L, 0.2 * H),
               (-0.3 * L, -0.25 * H)], -W, W)  # скулы
    K.slab(a, [(-0.2 * L, 1.0 * H), (-0.52 * L - 0.32 * H, 0.86 * H), (-0.52 * L - 0.26 * H, 0.7 * H),
               (-0.25 * L, 0.76 * H)], -0.95 * W, 0.95 * W)  # надбровья
    for s in S2:
        K.slab(a, [(-0.36 * L, 0.66 * H), (-0.49 * L, 0.75 * H), (-0.51 * L, 0.6 * H), (-0.39 * L, 0.53 * H)],
               s * 0.86 * W, s * 0.99 * W)  # глаз под надбровьем, внешний угол выше
        K.slab(a, [(-0.94 * L, 0.44 * H), (-1.04 * L, 0.54 * H), (-1.08 * L, 0.38 * H), (-0.98 * L, 0.3 * H)],
               s * 0.1 * W, s * 0.3 * W)  # ноздри
        K.spike(a, (s * 0.9 * W, -0.5 * L, 0.98 * H), (s * 1.15 * W, -0.38 * L, 1.32 * H), 0.24 * H)  # рожок брови
        K.spike(a, (s * W, -0.12 * L, 0.32 * H), (s * (W + 0.75), 0.15 * L, 0.48 * H), 0.3 * H)  # шип скулы
        K.spike(a, (s * W * 0.9, -0.28 * L, 0.05 * H), (s * (W + 0.45), -0.12 * L, -0.12 * H), 0.2 * H)
        for y, ln, w in ((-0.94, 0.42, 0.17), (-0.76, 0.3, 0.13), (-0.6, 0.22, 0.1)):  # верхние клыки
            K.spike(a, (s * 0.36 * W, y * L, 0.06 * H), (s * 0.37 * W, y * L, -ln * H), w * H)
        # длинные изогнутые рога (от B): назад над шеей, концы вверх
        K.chain(a, [(s * 0.56, -1.0, 1.72), (s * 0.95, -0.35, 2.2), (s * 1.42, 0.55, 2.45), (s * 1.82, 1.55, 2.35),
                    (s * 2.05, 2.45, 2.0), (s * 2.2, 3.05, 2.25)], [0.64, 0.53, 0.42, 0.31, 0.2, 0.1])
        K.spike(a, (s * 2.2, 3.05, 2.25), (s * 2.32, 3.3, 2.8), 0.1)
        K.chain(a, [(s * 1.0, 0.0, 0.95), (s * 1.5, 0.7, 1.12), (s * 1.78, 1.3, 0.95)], [0.32, 0.22, 0.08])
    # нижняя челюсть: мощная, приоткрыта на шарнире
    hinge = V((0, -0.12 * L, 0.0))
    a.transform = M @ Matrix.Translation(hinge) @ Matrix.Rotation(math.radians(jaw_open), 4, "X") @ \
        Matrix.Translation(-hinge)
    K.slab(a, [(-0.12 * L, -0.02 * H), (-0.98 * L, -0.02 * H), (-1.0 * L, -0.15 * H), (-0.86 * L, -0.42 * H),
               (-0.4 * L, -0.55 * H), (-0.1 * L, -0.4 * H)], -0.5 * W, 0.5 * W)
    K.slab(a, [(-0.05 * L, -0.05 * H), (-0.5 * L, -0.05 * H), (-0.46 * L, -0.52 * H), (-0.1 * L, -0.46 * H)],
           -0.66 * W, 0.66 * W)  # жевательные мышцы
    K.slab(a, [(-0.84 * L, -0.12 * H), (-1.0 * L, -0.12 * H), (-0.98 * L, -0.4 * H), (-0.86 * L, -0.46 * H)],
           -0.38 * W, 0.38 * W)  # подбородок ступенью
    for s in S2:
        for y, ln, w in ((-0.9, 0.34, 0.15), (-0.7, 0.24, 0.11)):  # нижние клыки
            K.spike(a, (s * 0.32 * W, y * L, -0.04 * H), (s * 0.33 * W, y * L, ln * H), w * H)
    a.transform = None
    return M


def wing(a, root, s, local, sweep, lean, tilt, flank, bone=(0.55, 0.38, 0.2)):
    """Крыло: плоскость (u — наружу, v — вверх); край перепонки крепится к боку в точке flank (мир)."""
    M = (Matrix.Translation(root) @ Matrix.Rotation(math.radians(s * sweep), 4, "Z")
         @ Matrix.Rotation(math.radians(-s * tilt), 4, "Y") @ Matrix.Rotation(math.radians(lean), 4, "X")
         @ Matrix.Scale(s, 4, V((1, 0, 0))))
    t = M.inverted() @ V(flank)
    E, W, T = V(local["E"]), V(local["W"]), V((t.x, t.z))
    F = [V(f) for f in local["F"]]

    def P(v):
        return M @ V((v.x, 0.0, v.y))

    def notch(p, q, k=0.3):
        mid = (p + q) / 2
        return mid + (W - mid) * k

    for i, (p, q) in enumerate(zip(F, F[1:])):
        dy = 0.06 * (i % 2)
        a.extrude(K.KEY, [tuple(W), tuple(p), tuple(notch(p, q)), tuple(q)], -0.05 + dy, 0.05 + dy, axis="y", matrix=M)
    a.extrude(K.KEY, [tuple(W), tuple(F[-1]), tuple(notch(F[-1], T, 0.22)), tuple(T), (0.0, 0.0), tuple(E)], -0.05, 0.05,
              axis="y", matrix=M)
    K.chain(a, [P(V((0, 0))), P(E), P(W)], [bone[0], bone[0] * 0.8, bone[1]], up=(0, 0, 1))
    for f in F:
        K.chain(a, [P(W), P(f)], [bone[1] * 0.85, bone[2] * 0.45], up=(0, 0, 1), overlap=0.2)
        K.spike(a, P(f), P(f) + (P(f) - P(W)).normalized() * 0.55, bone[2] * 0.6)
    K.spike(a, P(W), P(W) + (M.to_3x3() @ V((0.15, 0.0, 1.0))).normalized() * 0.85, bone[1] * 0.85)  # коготь-палец
    K.spike(a, P(E), P(E) + (M.to_3x3() @ V((-0.3, 0.0, 0.9))).normalized() * 0.5, bone[1] * 0.6)


def paw(a, s, wrist, ankle, front_y, z=0.3, width=1.45, claw=0.72):
    """Лапа: ступня, четыре раздельных пальца с крупными когтями (три вперёд, один внутрь)."""
    x = wrist.x
    K.taper(a, ankle, V((x, front_y + 0.55, z)), 1.2, 1.25, 0.9, 0.62)
    for k, (dx, ln) in enumerate(((-0.42, 0.62), (0.0, 0.72), (0.42, 0.62))):
        b = V((x + dx * width / 1.45, front_y + 0.55, z))
        e = b + V((dx * 0.25, -ln, -0.08))
        K.taper(a, b, e, 0.42, 0.34, 0.42, 0.3)
        K.spike(a, e + V((0, 0.05, 0.02)), e + V((dx * 0.1, -claw, -0.2)), 0.3)
    b = V((x - s * 0.62, front_y + 0.9, z + 0.1))
    K.spike(a, b, b + V((-s * 0.45, -0.25, -0.15)), 0.28)  # внутренний коготь


def dragon():
    a = K.new_art("DragonV5")
    # корпус: грудь поднята, спина спускается к крупу — величественная посадка на четырёх лапах
    body = [(-2.3, 2.75), (-3.2, 3.7), (-3.5, 5.0), (-3.05, 6.2), (-1.8, 7.0), (-0.3, 6.65), (1.2, 5.9), (2.6, 5.45),
            (3.5, 4.7), (3.65, 3.7), (3.0, 2.8), (1.8, 2.35), (0.2, 2.2), (-1.3, 2.4)]
    K.layered(a, body, [(1.0, 1.0, 1.0), (1.6, 0.94, 0.93), (2.05, 0.8, 0.8)], anchor=(0.2, 4.35))
    # грудные мышцы: две ступенчатые массы впереди — грудь не плоская
    for s in S2:
        K.layered(a, [(-3.62, 4.25), (-3.78, 5.25), (-3.3, 6.05), (-2.6, 5.7), (-2.7, 4.4)],
                  [(0.48, 1.0, 1.0), (0.66, 0.9, 0.88)], anchor=(-3.0, 5.1), xc=s * 0.72)
    # лопатки — мышечные массы, из которых растут крылья
    for s in S2:
        K.layered(a, [(-3.2, 3.6), (-3.3, 5.3), (-2.55, 6.85), (-1.1, 6.6), (-1.25, 4.8), (-2.05, 3.5)],
                  [(0.42, 1.0, 1.0), (0.64, 0.86, 0.86)], anchor=(-2.2, 5.1), xc=s * 2.0)
        K.chain(a, [(s * 1.75, -1.75, 6.3), (s * 1.6, -1.2, 7.05)], [1.15, 0.85], [1.25, 0.9])
    # шея: толстая у груди (A), S-изгиб (B), голова высоко
    neck = [(0, -2.6, 5.95), (0, -3.75, 6.95), (0, -3.95, 8.1), (0, -3.5, 9.0), (0, -3.8, 9.8), (0, -4.35, 10.2)]
    K.chain(a, neck, [2.6, 2.22, 1.88, 1.62, 1.46, 1.36], [2.7, 2.3, 1.92, 1.65, 1.48, 1.38], up=(0, -1, 0))
    head(a, (0, -4.15, 9.75), pitch=10, yaw=-7, jaw_open=13)
    K.spines(a, [V(p) + V((0, 0.8, 0.25)) for p in neck[1:-1]] +
             [V((0, -1.4, 7.4)), V((0, -0.3, 7.05)), V((0, 1.0, 6.4)), V((0, 2.2, 5.95)), V((0, 3.15, 5.4))],
             [0.55, 0.5, 0.46, 0.42, 0.78, 0.72, 0.6, 0.5, 0.42], up=(0, 0.4, 1), lean=0.4)
    for s in S2:
        step = s > 0  # левая передняя лапа шагает вперёд
        sh = V((s * 2.05, -2.35, 5.25))
        el = V((s * 2.5, -2.25, 3.45)) if step else V((s * 2.5, -1.9, 3.25))
        wr = V((s * 2.4, -3.35, 1.55)) if step else V((s * 2.38, -2.45, 1.3))
        K.chain(a, [sh, el, wr], [1.62, 1.35, 1.1], [1.8, 1.45, 1.12], up=(0, -1, 0))
        K.spike(a, el + V((s * 0.3, 0.3, 0.0)), el + V((s * 0.55, 1.1, 0.2)), 0.42)  # шпора локтя
        paw(a, s, wr, wr + V((0, 0.0, -0.25)), (-3.95 if step else -3.1))
        # задние лапы: тяжёлое бедро, скакательный сустав, лапа; правая чуть назад
        dy = 0.0 if s > 0 else 0.35
        K.layered(a, [(0.9, 5.15), (2.9, 5.3), (3.65, 4.0), (3.3, 2.7), (2.5, 1.9), (1.3, 2.15), (0.75, 3.4)],
                  [(0.5, 1.0, 1.0), (0.76, 0.86, 0.86)], anchor=(2.2, 3.7), xc=s * 1.85)
        hk = V((s * 2.0, 3.35 + dy, 1.2))
        K.chain(a, [(s * 1.95, 2.6, 2.3), hk, (s * 2.0, 2.75 + dy, 0.45)], [1.15, 0.95, 0.9], up=(0, -1, 0))
        K.spike(a, hk + V((0, 0.35, 0.0)), hk + V((0, 0.95, 0.1)), 0.34)
        paw(a, s, V((s * 2.0, 0, 0)), V((s * 2.0, 2.75 + dy, 0.4)), 1.75 + dy, width=1.35, claw=0.62)
        # крылья: большие, раскрыты по-разному; корень на лопатке, край перепонки — к боку
        wing(a, V((s * 1.55, -1.1, 7.0)), s,
             {"E": (2.05, 2.25), "W": (3.95, 3.9), "F": [(6.6, 3.05), (6.95, 0.78), (5.9, -1.2), (4.05, -2.15)]},
             sweep=20 if s > 0 else 26, lean=12, tilt=6 if s > 0 else -3, flank=(s * 1.75, 1.0, 5.2))
    # хвост: толстый, живой S-изгиб — сначала поднят, потом к земле и вбок; наконечник-лезвие
    tail = [(0, 3.4, 4.5), (0, 4.8, 4.65), (0.6, 6.2, 3.85), (1.8, 7.2, 2.45), (3.0, 7.5, 1.15), (4.3, 7.0, 0.58),
            (5.3, 5.9, 0.48), (5.6, 4.6, 0.45)]
    ws = [2.05, 1.75, 1.45, 1.2, 0.97, 0.77, 0.6, 0.47]
    K.chain(a, tail, ws, up=(0, 0, 1))
    K.spines(a, [V(p) + V((0, 0, w * 0.45)) for p, w in zip(tail[1:-1], ws[1:-1])], [0.62, 0.56, 0.48, 0.4, 0.34, 0.28])
    end, prev = V(tail[-1]), V(tail[-2])
    d = (end - prev).normalized()
    m = Matrix.Translation(end) @ Matrix.Rotation(math.atan2(d.x, -d.y), 4, "Z")
    a.extrude(K.KEY, [(0.0, 0.25), (0.5, 0.5), (0.9, -0.15), (0.45, -1.25), (0.0, -0.2)], -0.08, 0.08, axis="x",
              matrix=m)
    return a
